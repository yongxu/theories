def once(text, old, new, where):
    """Replace old by new exactly once, or find new already in place."""
    if old in text:
        assert text.count(old) == 1, (where, 'more than once', old[:80])
        return text.replace(old, new)
    assert new in text, (where, 'neither the old text nor the new is in place: place it by hand', old[:120])
    return text


