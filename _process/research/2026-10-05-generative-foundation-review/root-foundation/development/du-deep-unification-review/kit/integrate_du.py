def homes():
    for path, name, rid, after, before in HOMES:
        section = (HERE / name).read_text(encoding='utf-8')
        anchor = f'<a id="r-{rid}"></a>\n'
        text = path.read_text(encoding='utf-8')
        if anchor in text:
            assert section in text, (rid, 'a different home section is in place: remove it and rerun')
            print(path.name, ': the home section of', rid, 'is already in place')
            continue
        assert text.count(after) == 1 and text.count(before) == 1, (rid, 'the place has moved: place it by hand')
        i, j = text.index(after), text.index(before)
        assert i < j, (rid, 'the section to follow no longer comes before the next one')
        # nothing but the section followed lies between (the anchor of another result there stops the stage)
        between = text[i + len(after):j]
        anchors = re.findall(r'<a id="(r-[^"]+)"></a>', between)
        assert not anchors, (rid, 'other home sections now lie between: place it by hand', anchors)
        path.write_text(text.replace(before, '\n' + section + before), encoding='utf-8')
        print(path.name, ': the home section of', rid, 'inserted')


