def anchors():
    """land_du.sh prepare's dry run, after main is merged: every text, pattern and prior state that the record, register
    and texts stages read is where they read it, each exactly once (or, for the edits that allow it, already in place).
    Nothing is written. Returns the problems found."""
    problems = []

    def once_in(text, s, what, done=None):
        k = text.count(s)
        if k != 1 and not (k == 0 and done is not None and done in text):
            problems.append((what, k))

    def one_match(text, pattern, what):
        k = len(re.findall(pattern, text))
        if k != 1:
            problems.append((what, k))

    method = METHOD.read_text(encoding='utf-8')
    # record: 08 §3's receipt sentence; the three home sections' places
    if len(SENTENCE.findall(method)) != 1:
        problems.append(("08 §3's receipt sentence", len(SENTENCE.findall(method))))
    for path, name, rid, after, before in HOMES:
        text = path.read_text(encoding='utf-8')
        if f'<a id="r-{rid}"></a>' in text:
            problems.append((rid, 'a home section with this anchor is already in place'))
        once_in(text, after, rid + ': the section it follows')
        once_in(text, before, rid + ': the section it precedes')
        if after in text and before in text:
            i, j = text.index(after), text.index(before)
            between = re.findall(r'<a id="(r-[^"]+)"></a>', text[i + len(after):j]) if i < j else ['(out of order)']
            if between:
                problems.append((rid, 'other home sections now lie between its places', between))
    # record: COVERAGE's prior state
    for edit, state in coverage_state(json.loads(COVERAGE.read_text(encoding='utf-8'))).items():
        if state not in ('old', 'new'):
            problems.append(('COVERAGE ' + edit, state))
    # register: the end of the apart register's roots
    once_in(APART.read_text(encoding='utf-8'), APART_ANCHOR, 'THEOREM-CONNECTIVITY-APART.json: the end of its roots')
    # texts (a): 08 §7's paragraph, U3's sentence and table; the edge paragraph and its generator
    if method.count(CONN_START) != 1 or method.count(CONN_END) != 1:
        problems.append(('08 §7: the connectivity section\'s bounds', method.count(CONN_START), method.count(CONN_END)))
    else:
        _, _, sec = conn_section(method)
        for i, pattern in enumerate(CONN_PATTERNS):
            one_match(sec, pattern, f'08 §7: figure phrase {i + 1}')
        one_match(sec, CONN_NONE, '08 §7: the count resting on no law')
        once_in(sec, old_u3(law_word(sec)), "08 §7: U3's sentence")
        for label in TABLE_ROWS.values():
            one_match(sec, table_row(label), f'08 §7: the table row {label}')
    once_in(method, OLD_EDGE, "08 §7: the edge paragraph's sentence on the premises")
    u4 = U4.read_text(encoding='utf-8')
    once_in(u4, U4_OLD_SENTENCE, "make_record_u4.py home()'s sentence")
    once_in(u4, U4_OLD_COUNTS, 'make_record_u4.py counts()')
    if not isinstance(json.loads((ROOT / EDGE).read_text(encoding='utf-8')).get('history'), list):
        problems.append(('the boundary record has no history list', EDGE))
    # texts (d): 04, and the boundary data it reads (merged main's; check() later holds the landing's to it)
    life_text = LIFE.read_text(encoding='utf-8')
    once_in(life_text, OLD_BASES, "04's Bases")
    once_in(life_text, OLD_OPEN, "04's Open")
    state = life_state(json.loads((ROOT / MASTER).read_text(encoding='utf-8')))
    if state:
        problems.append(('04', state))
    # the Chinese README's rows (in the package join) and the rows they follow
    lines = README_ZH.read_text(encoding='utf-8').split('\n')
    for after, row in ZH_ROWS:
        if lines.count(row) != 1:
            problems.append(('README.zh.md: the row of the package join', row[:50], lines.count(row)))
        k = sum(1 for line in lines if line.startswith(after))
        if k != 1:
            problems.append(('README.zh.md: the row it follows', after, k))
    # texts (e): the front pages and READING-BUDGETS' rows
    for path, old, _ in FRONTS:
        once_in((ROOT / path).read_text(encoding='utf-8'), old, path + ': ' + old[:40])
    budgets_text = BUDGETS.read_text(encoding='utf-8')
    for row, *_ in BUDGET_ROWS:
        one_match(budgets_text, budget_row(row), 'READING-BUDGETS: the row ' + row)
    for script in (MEASURE, LAYERS, U4):
        if not script.is_file():
            problems.append(('a script the texts stage runs is missing', str(script)))
    # texts (c): WHAT-REMAINS
    remains = WHAT_REMAINS.read_text(encoding='utf-8')
    once_in(remains, WHAT_REMAINS_BEFORE, 'WHAT-REMAINS: the section the two go before')
    if LANDED_PREFIX in remains:
        problems.append(('WHAT-REMAINS: DU\'s landed section is already there', LANDED_PREFIX))
    return problems


