APART_ANCHOR = '  }\n },\n "instances": {'  # the end of the register's roots, where register() adds the leaves'


def names_in(log, label):
    m = re.search(re.escape(label) + r"[^:]*: (\[[^\]]*\])", log)
    return [] if not m else [s.strip().strip("'\"") for s in m.group(1).strip('[]').split(',') if s.strip()]


def register(log_path):
    t = APART.read_text(encoding='utf-8')
    log = Path(log_path).read_text(encoding='utf-8')
    listed = names_in(log, 'apart roots without a reason in')
    block, others, unknown = '', [], []
    for name in listed:
        module = next((m for m, names in mr.LEAF.items() if name in names), None)
        if module is None:
            others.append(name)
            continue
        if name not in REASONS:
            unknown.append(name)
            continue
        if json.dumps(name, ensure_ascii=False) in t:
            continue
        cat, why = REASONS[name]
        block += ('  ' + json.dumps(name, ensure_ascii=False) + ': {\n   "module": "' + module + '",\n'
                  '   "category": "' + cat + '",\n   "reason": ' + json.dumps(why, ensure_ascii=False) + '\n  },\n')
    assert not unknown, ('roots of the leaves with no reason: add each to REASONS, read from its statement', unknown)
    if block:
        assert t.count(APART_ANCHOR) == 1
        t = t.replace(APART_ANCHOR, '  },\n' + block.rstrip(',\n') + '\n },\n "instances": {')
        json.loads(t)
        APART.write_text(t, encoding='utf-8')
    gone = names_in(log, 'register entries no longer apart roots')
    unexpected = [g for g in gone if g not in NOW_USED]
    assert not unexpected, ('register entries no longer apart roots that these leaves do not explain', unexpected)
    t = APART.read_text(encoding='utf-8')
    d = json.loads(t)
    dropped = [g for g in gone if g in d['roots']]
    for g in dropped:
        start = t.index('  ' + json.dumps(g, ensure_ascii=False) + ': {\n')
        end = t.index('\n  },\n', start) + len('\n  },\n')
        t = t[:start] + t[end:]
    if dropped:
        after = json.loads(t)
        assert all(g not in after['roots'] for g in dropped) and len(after['roots']) == len(d['roots']) - len(dropped)
        APART.write_text(t, encoding='utf-8')
    print('dropped', len(dropped), 'register entries the leaves now use:', ', '.join(dropped) or 'none')
    print('registered', block.count('"module"'), 'roots of the leaves:',
          ', '.join(n for n in listed if n in REASONS) or 'none')
    if others:
        print("roots not the leaves', for their owners:", ', '.join(others))


