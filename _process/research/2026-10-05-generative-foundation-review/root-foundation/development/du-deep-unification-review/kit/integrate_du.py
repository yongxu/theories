def coverage_state(data):
    """What coverage() finds: for each of its four edits, 'old' (to apply), 'new' (in place) or a problem."""
    rows = {r['id']: r for r in data['rows']}
    items = {p['name']: p for p in data['premises']['items']}
    sig, c, fin, lift = rows['significance'], items[C_PREMISE], items['finite'], items['L, lifting']
    others = [r['id'] for r in data['rows'] if r['id'] != 'significance' and DROPPED in r['declarations']]
    state = {
        'significance row': ('old' if DROPPED in sig['declarations'] and DROPPED not in json.dumps(sig.get('instances', {}))
                             else 'new' if DROPPED not in sig['declarations'] else 'the dropped declaration has an instance'),
        'C witnesses': ('new' if 'Becoming.ReadsNoOrder.not_entails' in c['witnesses'] and c['note'] == C_NOTE
                        else 'old' if c['witnesses'] == C_OLD else f"C's witnesses or note: {c['witnesses']}"),
        'finite witnesses': ('new' if fin['witnesses'] == FIN_NEW else 'old' if fin['witnesses'] == [] and
                             fin['note'].endswith('but are not listed here') else f"finite: {fin['witnesses']}"),
        'L witnesses': ('new' if lift['witnesses'] == L_NEW else 'old' if lift['witnesses'] == [] else
                        f"L: {lift['witnesses']}"),
    }
    if others:
        state['other rows'] = f'the dropped declaration stands in another row: {others}'
    return state


def coverage():
    """TEXTS (b), agreed by OU's owner: the significance row, and the witnesses of C, finite and L."""
    data = json.loads(COVERAGE.read_text(encoding='utf-8'))
    rows = {r['id']: r for r in data['rows']}
    sig = rows['significance']
    if DROPPED in sig['declarations']:
        sig['declarations'].remove(DROPPED)
        assert DROPPED not in json.dumps(sig.get('instances', {})), 'the dropped declaration has an instance listed'
    others = [r['id'] for r in data['rows'] if DROPPED in r['declarations']]
    assert not others, ('the dropped declaration stands in another row', others)
    # The row has no note field; its reason is the significance row's own entry in the measure's REASONS and the C
    # premise's note below.
    items = {p['name']: p for p in data['premises']['items']}
    c = items[C_PREMISE]
    if 'Becoming.ReadsNoOrder.not_entails' not in c['witnesses']:
        assert c['witnesses'] == C_OLD, c['witnesses']
        c['witnesses'].append('Becoming.ReadsNoOrder.not_entails')
        c['note'] = C_NOTE
    assert c['note'] == C_NOTE, 'the C premise note differs from both its old and its new text'
    fin = items['finite']
    if fin['witnesses'] != FIN_NEW:
        assert fin['witnesses'] == [] and fin['note'].endswith('but are not listed here'), fin
        fin['witnesses'] = list(FIN_NEW)
        fin['note'] = FIN_NOTE
    lift = items['L, lifting']
    if lift['witnesses'] != L_NEW:
        assert lift['witnesses'] == [], lift
        lift['witnesses'] = list(L_NEW)
        lift['note'] = L_NOTE
    COVERAGE.write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('COVERAGE: significance row', len(sig['declarations']), 'declarations; C, finite and L witnessed')


