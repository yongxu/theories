#!/bin/bash
# ND's final stage: the head claim (head_bd4.sh's pattern): in ND's worktree, detached at main, board_bd4.py head and one commit of the
# board; then the fast-forward of the shared checkout, only if main has not moved and no clause holds the head. The
# worktree is put back on its branch after. Run it from a copy of the kit outside the worktree: main may not hold it.
# usage: head_nd_final.sh WORKTREE
set -u
W=$1; R=/Users/ren/theories; K=$(cd "$(dirname "$0")" && pwd); B=_process/BECOMING-WORKBOARD.md
cd "$R" || exit 1
[ "$(git branch --show-current)" = main ] || { echo "SHARED CHECKOUT NOT ON MAIN"; exit 7; }
git show main:$B | grep -m1 '^- \*\*Queue:\*\*' | grep -q '(landing now' && { echo "HEAD HELD"; exit 3; }
base=$(git rev-parse main)
cd "$W" && [ -z "$(git status --porcelain --untracked-files=no)" ] || { echo "WORKTREE NOT CLEAN"; exit 2; }
branch=$(git branch --show-current)
git checkout -q --detach "$base" || exit 2
python3 -B "$K/board_nd_final.py" head || { git checkout -q "$branch"; exit 2; }
[ "$(git diff --name-only)" = "$B" ] || { echo "UNEXPECTED PATHS"; git diff --name-only; git checkout -q -- $B; git checkout -q "$branch"; exit 2; }
git commit -q -m "Board: ND's final stage at the head of the queue (landing now: the record id master-laws-on-the-grammar renamed shared-laws-on-the-grammar by research.py rename-id; tools/research/master_laws.py, tools/research/tests/test_master_laws.py and theories/becoming/results/data/master-laws.json renamed shared_laws.py, test_shared_laws.py and shared-laws.json, every kit script on main calling them by path updated, no shim; keys and category values named for shared laws; documents and tools only, no Lean, no new record and no core run; the connectivity and the view regenerated from the checker's cache; then render, strict check, links, tests and both dossier checks, then the fast-forward)" -- $B
new=$(git rev-parse HEAD)
git checkout -q "$branch"
cd "$R"
[ "$(git rev-parse main)" = "$base" ] || { echo "MAIN MOVED; $new not landed"; exit 4; }
git show main:$B | grep -m1 '^- \*\*Queue:\*\*' | grep -q '(landing now' && { echo "HEAD HELD; $new not landed"; exit 3; }
git merge --ff-only -q "$new" && echo "CLAIMED $new" || { echo "FF FAILED"; exit 5; }
