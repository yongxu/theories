#!/usr/bin/env python3
"""OU3f: render TABLE.md, the per-module table of every theorem reading only `active`, from data/classification.tsv,
data/active-only.json and data/reach.json. The table is this workspace's own view of its data, regenerated by this
script; AUDIT.md gives the argument.
usage (from the checkout root): python3 -B <kit>/render_table.py"""
import collections
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
D = HERE.parent / 'data'
A = json.loads((D / 'active-only.json').read_text(encoding='utf-8'))
R = json.loads((D / 'reach.json').read_text(encoding='utf-8'))
rows = [l.rstrip('\n').split('\t') for l in (D / 'classification.tsv').read_text(encoding='utf-8').split('\n')
        if l.strip() and not l.startswith('#')]
CAT = {'a': '(a)', 'a-done': '(a), done', 'b': '(b)', 'c-model': '(c) model', 'c-witness': '(c) witness',
       'c-rep': '(c) representation', 'c-below': '(c) field-free law below', 'c-calibration': '(c) calibration'}
by = collections.defaultdict(list)
for n, cat, law, note in rows:
    by[A['Becoming.' + n]['module'].replace('Becoming.', '')].append((n, cat, law, note))
total = collections.Counter(r[1] for r in rows)
out = ['# OU3f: every theorem reading only `active`, by module', '',
       'Rendered by `kit/render_table.py` from `data/classification.tsv` (the classification), `data/active-only.json` (the '
       'recount) and `data/reach.json` (which proofs reach a grammar theorem); the argument is in [AUDIT.md](AUDIT.md). '
       '"Upper" marks a theorem whose upper bound reads more fields than `active`.', '',
       '| category | theorems |', '|---|---|']
out += [f'| {CAT[c]} | {total[c]} |' for c in CAT if total[c]]
out += [f'| all | {len(rows)} |', '']
for m in sorted(by, key=lambda m: (-len(by[m]), m)):
    c = collections.Counter(r[1] for r in by[m])
    out += [f'## {m} ({len(by[m])}: ' + ', '.join(f'{CAT[k]} {v}' for k, v in sorted(c.items(), key=lambda kv: list(CAT).index(kv[0]))) + ')', '',
            '| theorem | category | law or anchor | note |', '|---|---|---|---|']
    for n, cat, law, note in sorted(by[m], key=lambda r: (list(CAT).index(r[1]), r[0])):
        up = '' if A['Becoming.' + n]['upper'] == ['active'] else ' (upper)'
        out.append(f'| `{n}`{up} | {CAT[cat]} | {law.replace("|", "/")} | {note.replace("|", "/")} |')
    out.append('')
(HERE.parent / 'TABLE.md').write_text('\n'.join(out), encoding='utf-8')
print('TABLE.md:', len(rows), 'rows in', len(by), 'modules')
