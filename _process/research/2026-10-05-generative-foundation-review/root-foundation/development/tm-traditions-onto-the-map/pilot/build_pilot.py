#!/usr/bin/env python3
"""Check TM's dialectics pilot against the records and the atlas, and write DIALECTICS.md (AI-written, 10 November 2026).

usage: python3 -B build_pilot.py [--check]
dialectics.json is the hand data. Every landing's record must exist and hold each declaration it cites; every
countermodel declaration must be in some record; every dynamic a `joins` names must be in the atlas. Statuses are read
from the records. With --check nothing is written and the exit is 1 if the page would change.
"""
import json, sys
from collections import Counter
from pathlib import Path
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[6]
REC = ROOT / 'theories/becoming/results/records'
UP = '../' * 7
def main():
    d = json.loads((HERE / 'dialectics.json').read_text(encoding='utf-8'))
    recs = {}
    for p in REC.glob('*.json'):
        try: r = json.loads(p.read_text(encoding='utf-8'))
        except Exception: continue
        recs[r['id']] = (r.get('status'), {x for ref in r.get('references', []) for x in (ref.get('declarations') or [])}, r.get('title') or {})
    alld = set().union(*[v[1] for v in recs.values()])
    dyn = {x['id'] for x in json.loads((ROOT / 'theories/becoming/results/atlas/entries/dynamics.json').read_text(encoding='utf-8'))}
    cx = {x['id'] for x in json.loads((ROOT / 'theories/becoming/results/atlas/entries/correspondences.json').read_text(encoding='utf-8'))}
    errors = []
    for e in d['entries']:
        for l in e['landings']:
            if l['record'] not in recs: errors.append((e['id'], 'no record', l['record'])); continue
            for x in l['declarations']:
                if x not in recs[l['record']][1]: errors.append((e['id'], 'not in record', l['record'], x))
        c = e['countermodel']['declaration']
        if c and c not in alld: errors.append((e['id'], 'countermodel unknown', c))
        j = e['joins']
        if j:
            for k in ('from', 'to'):
                if j[k] and j[k] not in dyn: errors.append((e['id'], 'dynamic unknown', j[k]))
    for s in d['same_as']:
        if s not in cx: errors.append(('same_as', 'no crosswalk entry', s))
    L = ['*Generated by `build_pilot.py` from `dialectics.json` in this folder (AI-written, TM, 10 November 2026); do not edit by hand.*', '',
         '# The dialectics pilot: twenty claims, where each lands', '', d['about'], '',
         'Each claim is read by what the map asks: which dynamics it joins and which law it is a case of, or the blank it names. A claim that opposites turn into one another lands as an exit from one dynamic into another, with its premise. An evaluative claim lands as evaluation forming within the dynamics: what it reads, what it draws on, what it opens and closes and who bears it, never as support for or against a ranking. A countermodel corrects our unrestricted reading of a source, and the source itself only where it admits the domain.', '']
    eff = Counter(e['map_effect']['kind'] for e in d['entries']); rel = Counter(l['relation'] for e in d['entries'] for l in e['landings'])
    L += ['**Counts.** Map effect: ' + ', '.join('%s %d' % kv for kv in eff.most_common()) + '. Landings by relation: ' + ', '.join('%s %d' % kv for kv in rel.most_common()) + '. Exits or joins named: %d.' % sum(1 for e in d['entries'] if e['joins']), '']
    for e in d['entries']:
        L += ['<a id="%s"></a>' % e['id'], '## %s · %s' % (e['name']['zh'], e['name']['en']), '',
              '*%s. Class %s; %s; force: %s. %s*' % (e['source']['work'], e['class'], e['direction_or_evaluation'], e['force'], 'Read against the text.' if e['source']['text_read'] in ('external-read', 'read-in-repo') else 'From the AI\'s memory, unchecked.'), '',
              '**Its own sense.** ' + e['sense'], '']
        ra = e.get('read_against')
        if ra: L += ['**In the text** (%s, %s): 「%s」. %s' % (ra['file'], ra['locator'], ra['quote'], ra['found']), '']
        for l in e['landings']:
            t = recs[l['record']][2]
            L.append('- **%s, %s** · [%s](%stheories/becoming/results/records/%s.md) (%s): %s %s' % (l['relation'], l['strength'], t.get('en') or l['record'], UP, l['record'], recs[l['record']][0], l['note'], ' '.join('`%s`' % x[len('Becoming.'):] for x in l['declarations'])))
        if not e['landings']: L.append('- No law carries it.')
        c = e['countermodel']
        L += ['', '**Countermodel.** ' + (('`%s`: ' % c['declaration'][len('Becoming.'):]) if c['declaration'] else '') + c['note'],
              '', '**Does the source admit the scope?** %s. %s' % (e['source_admits']['value'].capitalize(), e['source_admits']['note'])]
        j = e['joins']
        if j: L += ['', '**Joins.** From `%s` to %s, where: %s. %s' % (j['from'], ('`%s`' % j['to']) if j['to'] else 'outside it', j['premise'], j['note'])]
        m = e['map_effect']
        L += ['', '**On the map.** %s%s; corrected: %s.' % (m['kind'], (' (%s)' % m['to']) if m.get('to') else '', m['corrected']), '', '**What the source adds.** ' + e['residue'], '']
    L += ['## Already in the crosswalk, not repeated', '', ', '.join('`%s`' % s for s in d['same_as']) + '.', '', '## Not mapped', '']
    L += ['- %s: %s.' % (n['claim'], n['why']) for n in d['not_mapped']] + ['']
    text = '\n'.join(L); p = HERE / 'DIALECTICS.md'; changed = (not p.exists()) or p.read_text(encoding='utf-8') != text
    if changed and '--check' not in sys.argv and not errors: p.write_text(text, encoding='utf-8')
    print(json.dumps({'entries': len(d['entries']), 'errors': errors, 'effects': dict(eff), 'relations': dict(rel), 'changed': changed}, ensure_ascii=False, indent=1))
    return 1 if errors or (changed and '--check' in sys.argv) else 0
if __name__ == '__main__': sys.exit(main())
