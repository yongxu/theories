#!/usr/bin/env python3
"""WX: list every atlas field this landing changed, old and new, with the home it restates, for the reader.

usage: python3 -B field_diff.py BASE OUT   (BASE a commit, e.g. main)"""
import json
import subprocess
import sys

BASE, OUT = sys.argv[1], sys.argv[2]
E = 'theories/becoming/results/atlas/entries/'


def leaves(x, path):
    if isinstance(x, str):
        yield tuple(path), x
    elif isinstance(x, dict):
        for k, v in x.items():
            yield from leaves(v, path + [k])
    elif isinstance(x, list):
        for i, v in enumerate(x):
            yield from leaves(v, path + [i])


lines, n = [], 0
for fn in ('correspondences.json', 'dynamics.json', 'correspondence_groups.json'):
    old = {e['id']: e for e in json.loads(subprocess.check_output(['git', 'show', f'{BASE}:{E}{fn}']).decode('utf-8'))}
    for e in json.load(open(E + fn, encoding='utf-8')):
        o = dict(leaves(old[e['id']], []))
        for p, s in leaves(e, []):
            if o.get(p) != s:
                n += 1
                home = ''
                if p[0] == 'targets':
                    t = e['targets'][p[1]]
                    home = (t.get('anchor') or '') + (f" (record {t['record']})" if t.get('record') else '')
                lines += [f"### {n}. `{e['id']}` · `{'.'.join(map(str, p))}`" + (f" · {home}" if home else ''), '',
                          f"- before: {o.get(p)}", f"- after: {s}", '']
open(OUT, 'w', encoding='utf-8').write(f"# WX: the atlas fields changed, before and after ({n})\n\nAgainst `{BASE}`. Generated by `kit/field_diff.py`.\n\n" + '\n'.join(lines))
print(n)
