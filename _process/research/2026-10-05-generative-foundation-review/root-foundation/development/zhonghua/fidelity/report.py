"""The fidelity count (FC1): write RESULTS.md from data/results_main.json and data/results_calib.json.

    python3 -I fidelity/report.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / 'data'


def f(x, k=2):
    return '—' if x is None else ('%.*f' % (k, x))


def ci(c):
    return '—' if not c else '[%s, %s]' % (f(c[0]), f(c[1]))


def row(c):
    w = c['wilcoxon']
    return '| %s | %d | %s | %s | %s | %s | %s |' % (c['label'], c['n_tiao'], f(c['mean_zh']), f(c['mean_en']),
                                                f(c['mean_diff']), ci(c['ci95']), f(w.get('p'), 3))


def main():
    R = json.loads((DATA / 'results_main.json').read_text())
    C = json.loads((DATA / 'results_calib.json').read_text())
    out = ['# FC1: the fidelity count, results', '',
           'Generated by `report.py` from `data/results_main.json`; design FIDELITY.md, plan ANALYSIS-PLAN.md, codebook '
           'v1.1 (CODEBOOK-REVISIONS.md). LLM-coded, with no human audit: provisional, as the design says. AI-written.', '',
           '## Units', '',
           '%d scored pairs (條, declaration) in %d 條; the calibration set (%d pairs) is excluded.' %
           (R['units'], R['tiao'], C['units']), '',
           'Coded segments: ' + ', '.join('%s %d' % (k, v) for k, v in sorted(R['coded_segments'].items())), '',
           '## Reliability (Krippendorff\'s α)', '',
           '| pass / language / quantity | main | calibration (v1.1) |', '|---|---|---|']
    for k, v in R['reliability'].items():
        cv = C['reliability'].get(k, {})
        a = v.get('alpha', v.get('alpha_nominal'))
        b = cv.get('alpha', cv.get('alpha_nominal'))
        out.append('| %s | %s (n %s) | %s |' % (k, f(a), v.get('n', v.get('matched_spans')), f(b)))
    out += ['', '## Decisions on the registered predictions', '']
    for coder in ('consensus', 'claude', 'codex'):
        cc = R['comparisons'][coder]
        out.append('- **%s**: F1 (X_A) %s; F2 (X) %s; F4 (load) %s' % (
            coder, 'CI ' + ci(cc['X_A']['ci95']), 'CI ' + ci(cc['X']['ci95']), 'CI ' + ci(cc['load']['ci95'])))
    out += ['', 'Decision by the plan (consensus): ' + ', '.join('%s %s' % kv for kv in R['decisions'].items()), '']
    for coder in ('consensus', 'claude', 'codex'):
        cc = R['comparisons'][coder]
        out += ['## Comparisons, %s' % coder, '',
                '| comparison (zh − en) | 條 | mean zh | mean en | mean diff | 95% CI | Wilcoxon p |',
                '|---|---:|---:|---:|---:|---|---:|']
        for k in ('X', 'X_A', 'X_R', 'X_E', 'O', 'O_rate', 'S', 'P', 'X_U0', 'X_noneg', 'X_noreading', 'naive_X', 'load'):
            out.append(row(cc[k]))
        for k, v in cc['genre'].items():
            out.append(row(v))
        out.append('')
    out += ['## By 篇 (consensus X)', '', '| 篇 | 條 | mean zh | mean en | mean diff | 95% CI | Wilcoxon p |',
            '|---|---:|---:|---:|---:|---|---:|']
    for k, v in R['by_pian'].items():
        out.append(row(v))
    p = R.get('poisson') or {}
    out += ['', '## Other statistics', '',
            '- McNemar on consensus X ≥ 1 over pairs: b (zh only) %s, c (en only) %s, p %s.' % (
                R['mcnemar_X_ge_1']['b'], R['mcnemar_X_ge_1']['c'], f(R['mcnemar_X_ge_1']['p'], 4)),
            '- Poisson rate ratio zh/en (cluster-robust over 條): %s, 95%% CI %s.' % (f(p.get('rr')), ci(p.get('ci'))),
            '- X_anchor against coded X: Spearman ρ %s (n %s).' % (
                f((R.get('x_anchor_spearman') or {}).get('rho')), (R.get('x_anchor_spearman') or {}).get('n')), '']
    (HERE / 'RESULTS.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('RESULTS.md written')


if __name__ == '__main__':
    main()
