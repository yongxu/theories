"""Integrator decisions on the revisers' name flags (21 October 2026): reads the first decisions
(names-decisions-initial.tsv, 20 October), writes names-decisions.tsv and names-dropped.tsv.
Each change keeps its reason in the 注 column; dropped names are listed with theirs."""
import csv, os
H = os.path.dirname(os.path.abspath(__file__)); F = H + '/names-decisions.tsv'
rows = list(csv.DictReader(open(H + '/names-decisions-initial.tsv', encoding='utf-8'), delimiter='\t')); by = {r['名']: r for r in rows}
FIELDS = list(rows[0].keys()); dropped = []
def up(n, **kw):
    r = by[n]
    for k, v in kw.items():
        k = {'what': '所名', 'anchor': '锚', 'quote': '引', 'form': '式', 'note': '注'}[k]
        r[k] = (r[k] + '；' + v[1:]) if v.startswith('+') else v
def ren(o, n, **kw):
    r = by.pop(o); r['名'] = n; by[n] = r; r['注'] = (r['注'] + '；' if r['注'] not in ('', '—') else '') + '原拟「%s」' % o
    if kw: up(n, **kw)
def drop(n, why):
    r = by.pop(n); dropped.append({'名': n, '篇': r['篇'], '所名': r['所名'], '理由': why})
def add(n, c, what, anchor='—', quote='—', form='新', note='—'):
    by[n] = {'名': n, '篇': c, '所名': what, '锚': anchor, '引': quote, '式': form, '注': note}

