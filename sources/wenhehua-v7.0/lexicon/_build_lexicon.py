records=[]
for line in text.strip().splitlines():
    fields=line.split('|')
    if len(fields)!=5: raise ValueError(line)
    records.append(dict(zip(['词','层级','工作定义','构造路径/前提','误用警示'],fields)))
# more than one row for 续? merge one and add semantic nuances in warning
seen=set(); unique=[]
for x in records:
    if x['词'] not in seen:
        seen.add(x['词']); unique.append(x)
    else:
        next(z for z in unique if z['词']==x['词'])['误用警示']+='；另义：'+x['工作定义']
with open(r/'核心概念精注.csv','w',encoding='utf-8-sig',newline='') as f:
    w=csv.DictWriter(f,fieldnames=list(unique[0]));w.writeheader();w.writerows(unique)
(r/'核心概念精注.json').write_text(json.dumps(unique,ensure_ascii=False,indent=2),encoding='utf-8')
by_class=collections.defaultdict(list)
for x in unique: by_class[x['层级']].append(x)
with open(r/'01_核心概念精注.md','w',encoding='utf-8') as f:
    f.write('# 文之字义：精注核心词谱\n\n')
    f.write(f'> 共 {len(unique)} 个去重后的核心概念，系对原始389条广义候选的**强化解释和可构造前提**；并非这些词全部具有已核证的先秦义。\n\n')
    f.write('**证据分级**：此表「工作定义」属于本项目提出的形式语义，不是古字训诂。古典书证需另列出处和释读争议；没有可靠书证时不推测「本义」。\n\n')
    f.write('## 层级说明\n\n- **核**：第一层构造候选（文、合、化）。\n- **元律**：语法、等价与性质的规则层（则、理、约等）。\n- **派生**：可由给定关系图或重写等结构构造。\n- **语义**：引入时间、动力学、几何、概率、因果等额外解释。\n- **规范**：价值、权利和制度评价，依赖显式的社会规范。\n\n')
    for cl, vals in by_class.items():
        f.write(f'## {cl}（{len(vals)} 词）\n\n| 词 | 工作定义 | 构造路径/前提 | 误用警示 |\n|---|---|---|---|\n')
        for z in vals:
            f.write('| '+ ' | '.join(z[k].replace('|','／') for k in ['词','工作定义','构造路径/前提','误用警示'])+' |\n')
        f.write('\n')
# expanded whole glossary add level from focused definitions, retain all provenance columns
focus={x['词']:x for x in unique}
expanded=[]
for x in original:
    y=dict(x)
    if x['词'] in focus:
        y['概念层级']=focus[x['词']]['层级']
        y['形式前提']=focus[x['词']]['构造路径/前提']
        y['误用提示']=focus[x['词']]['误用警示']
    else:
        status=x['形式地位']
        if '核' in status: layer='核'
        elif '规范' in x['语义族']: layer='规范'
        elif '语义' in status or '扩展' in status: layer='语义'
        else: layer='派生/待检'
        y['概念层级']=layer
        y['形式前提']='需按本项目形式框架逐条核验，尚无统一导出定理'
        y['误用提示']='仅为候选工作义，不可视为词源已证或数学定理'
    expanded.append(y)
fields=list(expanded[0]);
with open(r/'完整词库389_增注.csv','w',encoding='utf-8-sig',newline='') as f:
    w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(expanded)
(r/'完整词库389_增注.json').write_text(json.dumps(expanded,ensure_ascii=False,indent=2),encoding='utf-8')
with open(r/'02_词库使用指南.md','w',encoding='utf-8') as f:
    cnt=collections.Counter(x['语义族'] for x in original)
    f.write('# 文之词林：完整候选词库索引与使用指南\n\n')
    f.write(f'**389 条工作词条，{len(set(x["词"] for x in original))} 个去重词项。** 重复项用于不同语义族，一词多义不做武断合并。它们是候选而非389条已证古典义项。\n\n')
    f.write('词表分为三个层次：`核心概念精注.csv` 提供可直接参与理论讨论的高密度词；`完整词库389_增注.csv` 提供全量候选、证据等级、形式层级与风险；`03_文之构造图谱.md` 提供哪些词构成哪些数学模式。\n\n')
    f.write('## 15 个语义族\n\n| 词族 | 词条数 |\n|---|---:|\n')
    for c,n in sorted(cnt.items()):f.write(f'| {c} | {n} |\n')
    f.write('\n## 读法\n\n- 想构造软件：从「文/合/化/界/端/类/则/证」开始。\n- 想研究物理/生态：加入「流/场/能/守/势/稳/阈」，并补独立动力学语义。\n- 想研究抽象和智能：加入「观/象/映/抽/等价/因/知/学/反身」。\n- 想研究公共系统：加入「共/义/善/自由/多样/续」；这些是必须显式论证的规范项。\n\n## 古义与新义界线\n\n原始表里「经学线索」只表示存在文本可作语义联想，不等于每个形式含义具有历史依据。`文理/文脉/文势/文界/文观/文谱/文之文` 这些作为研究用法时必须写「项目命名」。不能用古典引文为图论定理背书。\n')
print('core',len(unique),'full',len(expanded),'unique',len(set(x['词'] for x in expanded)))
