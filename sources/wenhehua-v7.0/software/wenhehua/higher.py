"""A finite executable fragment of the bicategory MonicSp(Csp(T)).

The ambient T is a finite typed directed *hypergraph* category with a
specified signature. Here we implement finite open hypergraphs whose
left/right interfaces are discrete typed vertex interfaces.

0-cells: typed port lists (interfaces).
1-cells: boundary-injective open typed hypergraphs (cospans).
2-cells: boundary-preserving, monic spans of open graphs (change witnesses).
Horizontal composition: pushout gluing along the common interface.
Vertical composition: pullback of injective change witnesses.

This program is a FINITE FRAGMENT, not an implementation/proof of the full
symmetric monoidal bicategory. It does not automatically infer which changes
are generated by a declared set of local DPO rewrite rules.
"""
from __future__ import annotations
from collections import Counter
from dataclasses import dataclass
from typing import Dict, Mapping, Optional, Tuple
from itertools import permutations

from .core import Graph, Edge, Signature, Match, GrammarError, glue


def _bound(label: str, index: int) -> str:
    return f'{label}:{index}'


def _clone(graph: Graph, ports: Optional[Mapping[str, str]] = None) -> Graph:
    return Graph(dict(graph.nodes), dict(graph.edges),
                 dict(graph.ports if ports is None else ports))


@dataclass
class OpenGraph:
    """Finite open network; each input/output boundary leg is injective.

    Boundary identifiers have the canonical form in:0... and out:0...
    and refer to typed graph vertices. An input and an output MAY refer to
    the same internal vertex (e.g., a wire identity).
    """
    graph: Graph
    input_types: Tuple[str, ...]
    output_types: Tuple[str, ...]

    def check(self, sig: Signature) -> None:
        self.graph.check(sig)
        expected = ({_bound('in', i) for i in range(len(self.input_types))} |
                    {_bound('out', i) for i in range(len(self.output_types))})
        if set(self.graph.ports) != expected:
            raise GrammarError(f'open graph boundary mismatch: {expected ^ set(self.graph.ports)}')
        for side, types in [('in', self.input_types), ('out', self.output_types)]:
            vertices = []
            for i, kind in enumerate(types):
                if kind not in sig.node_types:
                    raise GrammarError(f'unknown boundary node type {kind}')
                vertex = self.graph.ports[_bound(side, i)]
                if self.graph.nodes[vertex] != kind:
                    raise GrammarError('boundary type does not match graph node')
                vertices.append(vertex)
            if len(vertices) != len(set(vertices)):
                raise GrammarError(f'non-monic {side} boundary leg')

    @classmethod
    def identity(cls, sig: Signature, types: Tuple[str, ...]) -> 'OpenGraph':
        nodes = {f'wire{i}': ty for i, ty in enumerate(types)}
        ports = {_bound('in', i): f'wire{i}' for i in range(len(types))}
        ports.update({_bound('out', i): f'wire{i}' for i in range(len(types))})
        result = cls(Graph(nodes, {}, ports), tuple(types), tuple(types))
        result.check(sig)
        return result


def _horizontal_data(sig: Signature, first: OpenGraph, second: OpenGraph):
    """Compute a typed interface pushout and its canonical inclusion maps.

    The returned maps retain identities for the finite host graphs; these
    are implementation-specific labels, not categorical equalities.
    """
    first.check(sig); second.check(sig)
    if first.output_types != second.input_types:
        raise GrammarError('horizontal boundary types differ')
    along = {_bound('out', i): _bound('in', i)
             for i in range(len(first.output_types))}
    merged = glue(sig, first.graph, second.graph, along, hide=False)
    outer_ports = {
        **{_bound('in', i): merged.ports[f'L.{_bound("in", i)}']
           for i in range(len(first.input_types))},
        **{_bound('out', i): merged.ports[f'R.{_bound("out", i)}']
           for i in range(len(second.output_types))},
    }
    result = OpenGraph(_clone(merged, outer_ports),
                       first.input_types, second.output_types)
    result.check(sig)
    ln = {n: f'L::{n}' for n in first.graph.nodes}
    rn = {n: f'R::{n}' for n in second.graph.nodes}
    for i in range(len(first.output_types)):
        r_vertex = second.graph.ports[_bound('in', i)]
        l_vertex = first.graph.ports[_bound('out', i)]
        rn[r_vertex] = f'L::{l_vertex}'
    le = {e: f'L::{e}' for e in first.graph.edges}
    re = {e: f'R::{e}' for e in second.graph.edges}
    return result, Match(ln, le), Match(rn, re)


def horizontal(sig: Signature, first: OpenGraph,
               second: OpenGraph) -> OpenGraph:
    """Horizontal 1-cell composition (合): pushout over a discrete interface."""
    return _horizontal_data(sig, first, second)[0]


def _valid_graph_map(sig: Signature, src: Graph, dst: Graph, m: Match):
    src.check(sig); dst.check(sig)
    if set(m.nodes) != set(src.nodes) or set(m.edges) != set(src.edges):
        raise GrammarError('incomplete span leg')
    if (len(set(m.nodes.values())) != len(m.nodes) or
        len(set(m.edges.values())) != len(m.edges)):
        raise GrammarError('span legs must be monic on nodes and edges')
    for a, b in m.nodes.items():
        if b not in dst.nodes or src.nodes[a] != dst.nodes[b]:
            raise GrammarError('span node map not typed')
    for a, b in m.edges.items():
        e, f = src.edges[a], dst.edges.get(b)
        if f != Edge(e.kind, tuple(m.nodes[v] for v in e.sources),
                               tuple(m.nodes[v] for v in e.targets)):
            raise GrammarError('span edge map does not preserve incidence')


@dataclass
class Change:
    """A 2-cell represented by a monic span of open cospans.

    before <- common -> after; the common subgraph is the preserved part.
    The boundary of the before and after systems must factor identically
    through common. The 2-cell does NOT record a temporal duration/rate.
    """
    before: OpenGraph
    after: OpenGraph
    common: Graph
    into_before: Match
    into_after: Match

    def check(self, sig: Signature):
        self.before.check(sig); self.after.check(sig)
        if self.before.input_types != self.after.input_types or \
           self.before.output_types != self.after.output_types:
            raise GrammarError('change cannot silently alter external boundary types')
        if self.common.ports:
            raise GrammarError('common span apex ports are derived, not stored')
        _valid_graph_map(sig, self.common, self.before.graph, self.into_before)
        _valid_graph_map(sig, self.common, self.after.graph, self.into_after)
        for port in self.before.graph.ports:
            b, a = self.before.graph.ports[port], self.after.graph.ports[port]
            if not any(self.into_before.nodes[k] == b and
                       self.into_after.nodes[k] == a for k in self.common.nodes):
                raise GrammarError(f'change fails to preserve external port {port}')

    def common_open(self, sig: Signature) -> OpenGraph:
        """Factor external boundary through preserved subgraph."""
        self.check(sig)
        ports = {}
        for port, before_node in self.before.graph.ports.items():
            common_vertex = next(k for k in self.common.nodes
                                 if self.into_before.nodes[k] == before_node)
            ports[port] = common_vertex
        return OpenGraph(_clone(self.common, ports),
                         self.before.input_types, self.before.output_types)

    @classmethod
    def identity(cls, sig: Signature, network: OpenGraph) -> 'Change':
        network.check(sig)
        common = _clone(network.graph, {})
        m = Match({k:k for k in common.nodes},
                  {k:k for k in common.edges})
        result = cls(network, network, common, m, m)
        result.check(sig)
        return result


def horizontal_change(sig: Signature, left: Change, right: Change) -> Change:
    """Horizontal pasting of two 2-cells; valid only with compatible boundaries."""
    left.check(sig); right.check(sig)
    before, bleft, bright = _horizontal_data(sig, left.before, right.before)
    after, aleft, aright = _horizontal_data(sig, left.after, right.after)
    common, cleft, cright = _horizontal_data(sig, left.common_open(sig),
                                            right.common_open(sig))
    b_nodes: Dict[str, str] = {}
    a_nodes: Dict[str, str] = {}
    b_edges: Dict[str, str] = {}
    a_edges: Dict[str, str] = {}
    for ch, c_incl, b_incl, a_incl in [
        (left, cleft, bleft, aleft),
        (right, cright, bright, aright)
    ]:
        for k in ch.common.nodes:
            c = c_incl.nodes[k]
            b = b_incl.nodes[ch.into_before.nodes[k]]
            a = a_incl.nodes[ch.into_after.nodes[k]]
            if c in b_nodes and (b_nodes[c] != b or a_nodes[c] != a):
                raise GrammarError('shared interface witness mismatch')
            b_nodes[c] = b; a_nodes[c] = a
        for e in ch.common.edges:
            c = c_incl.edges[e]
            b = b_incl.edges[ch.into_before.edges[e]]
            a = a_incl.edges[ch.into_after.edges[e]]
            if c in b_edges and (b_edges[c] != b or a_edges[c] != a):
                raise GrammarError('shared edge witness mismatch')
            b_edges[c] = b; a_edges[c] = a
    witness = Change(before, after, _clone(common.graph, {}),
                     Match(b_nodes, b_edges), Match(a_nodes, a_edges))
    witness.check(sig)
    return witness


def vertical_change(sig: Signature, first: Change, second: Change) -> Change:
    """Vertical pasting by finite pullback of monic spans over the middle graph.

    Restriction: middle graph and boundaries must be IDENTICAL on ids; a
    2-cell transport/isomorphism is needed for nonidentical presentations.
    """
    first.check(sig); second.check(sig)
    if first.after != second.before:
        raise GrammarError('vertical changes require exactly matching middle cospan')
    middle_nodes1 = {v:k for k,v in first.into_after.nodes.items()}
    middle_nodes2 = {v:k for k,v in second.into_before.nodes.items()}
    common_vertices = sorted(set(middle_nodes1) & set(middle_nodes2))
    nodes: Dict[str, str] = {}
    into_b: Dict[str, str] = {}
    into_a: Dict[str, str] = {}
    key_of_middle: Dict[str, str] = {}
    for i, mid in enumerate(common_vertices):
        new_name = f'P::v::{i}'
        key_of_middle[mid] = new_name
        nodes[new_name] = first.after.graph.nodes[mid]
        into_b[new_name] = first.into_before.nodes[middle_nodes1[mid]]
        into_a[new_name] = second.into_after.nodes[middle_nodes2[mid]]

    middle_edges1 = {v:k for k,v in first.into_after.edges.items()}
    middle_edges2 = {v:k for k,v in second.into_before.edges.items()}
    common_edges = sorted(set(middle_edges1) & set(middle_edges2))
    edges: Dict[str, Edge] = {}
    edge_into_b: Dict[str, str] = {}
    edge_into_a: Dict[str, str] = {}
    for i, mid in enumerate(common_edges):
        e = first.after.graph.edges[mid]
        if any(v not in key_of_middle for v in e.sources + e.targets):
            raise GrammarError('pullback edge endpoint missing')
        name = f'P::e::{i}'
        edges[name] = Edge(e.kind, tuple(key_of_middle[v] for v in e.sources),
                           tuple(key_of_middle[v] for v in e.targets))
        edge_into_b[name] = first.into_before.edges[middle_edges1[mid]]
        edge_into_a[name] = second.into_after.edges[middle_edges2[mid]]
    change = Change(first.before, second.after, Graph(nodes, edges),
                    Match(into_b, edge_into_b), Match(into_a, edge_into_a))
    change.check(sig)
    return change


def signature(change: Change) -> tuple:
    """Boundary-aware span witness signature *for fixed outer graph ids*.

    Two monic span witnesses with identically named before/after graphs and
    the same list of preserved node/edge pairs are isomorphic as spans.
    """
    return (
        tuple(sorted((change.into_before.nodes[k], change.into_after.nodes[k])
                     for k in change.common.nodes)),
        tuple(sorted((change.into_before.edges[k], change.into_after.edges[k])
                     for k in change.common.edges)),
    )


def isomorphic_witness(sig: Signature, first: Change, second: Change) -> bool:
    """Check equality of spans up to apex renaming (same external graph ids)."""
    first.check(sig); second.check(sig)
    return (first.before == second.before and first.after == second.after and
            signature(first) == signature(second))


def open_graph_isomorphic(sig: Signature, first: OpenGraph,
                          second: OpenGraph) -> bool:
    """Exact boundary-aware finite hypergraph isomorphism, exponential worst case.

    Meant for small test objects, not large graphs. It preserves both ordered
    interfaces and typed edge multiplicity, ignoring internal vertex/edge names.
    """
    first.check(sig); second.check(sig)
    if first.input_types != second.input_types or \
       first.output_types != second.output_types:
        return False
    a, b = first.graph, second.graph
    if len(a.nodes) != len(b.nodes) or len(a.edges) != len(b.edges):
        return False
    a_ports = {node: frozenset(p for p, n in a.ports.items() if n == node)
               for node in a.nodes}
    b_ports = {node: frozenset(p for p, n in b.ports.items() if n == node)
               for node in b.nodes}
    a_groups: Dict[tuple, list] = {}
    b_groups: Dict[tuple, list] = {}
    for n, t in a.nodes.items():
        a_groups.setdefault((t, a_ports[n]), []).append(n)
    for n, t in b.nodes.items():
        b_groups.setdefault((t, b_ports[n]), []).append(n)
    if {k:len(v) for k,v in a_groups.items()} != \
       {k:len(v) for k,v in b_groups.items()}:
        return False
    groups = sorted(a_groups, key=lambda x: str(x))
    expected = Counter((e.kind, e.sources, e.targets) for e in b.edges.values())
    def search(i: int, assignment: Dict[str, str]):
        if i == len(groups):
            return Counter((e.kind,
                            tuple(assignment[n] for n in e.sources),
                            tuple(assignment[n] for n in e.targets))
                           for e in a.edges.values()) == expected
        key = groups[i]
        for p in permutations(b_groups[key]):
            mapping = dict(zip(a_groups[key], p))
            if search(i+1, {**assignment, **mapping}):
                return True
        return False
    return search(0, {})
