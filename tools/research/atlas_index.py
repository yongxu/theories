"""The map's index (AA's next phase, step 1): the stores joined in one SQLite index, and what does not join.

The map lives in five stores that were built apart: the result records, the atlas (its dynamics, exits, transitions,
test links and crosswalk), the tests table, the theory graph and the declarations the core run lists. This tool reads
them into one disposable SQLite index with typed tables, and measures where they meet and where they do not: exits
that name no destination, tests that name no record or dynamic, crosswalk targets that reach no record, joins that
match more than one thing, and the records the atlas's dynamics do not cite. It writes those measures as a generated
page (JOINS.md, beside the atlas), so the gaps the map-structures readings named are counted on every render and a
later step can be seen to close them. It tries test ids (LA2, LA4, IN1) and premise ids (K3's 17) on a small batch,
measuring what such ids would join, without adding any entry.

The index is generated, never committed: `python3 -B tools/research/atlas_index.py` writes it to tmp/ (scratch the
repository ignores), with the Lean catalogue's declarations and a full-text table added for queries. The page reads
only what a render has in hand, the records, this render's atlas data and theory graph, the tests table, COVERAGE and
the core receipt, so it is a function of those, as the other generated pages are. Nothing here is a result: a join
counted is a key matched, not a correspondence checked. AI-written (9 November 2026)."""
