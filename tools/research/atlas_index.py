def _n(x: int) -> str:
    return f'{x:,}'


def _pct(a: int, b: int) -> str:
    return f'{a:,} of {b:,}' if b else f'{a:,}'


def _rec(r: str) -> str:
    return atlas._record(r, HERE)


def _dyn(d: str, homes: dict) -> str:
    return f'[{d}]({atlas._section(d, homes, REPORT)})' if d in homes else d


def _chapter(path: str) -> str:
    return f'[{posixpath.basename(path)}]({atlas._href(path, HERE)})' if path else 'no home section in a chapter'


