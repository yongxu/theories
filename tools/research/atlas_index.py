def _en(value) -> str:
    """A text's English, its Chinese where it has none, on one line; '' for nothing."""
    if value is None:
        return ''
    if isinstance(value, str):
        return ' '.join(value.split())
    return ' '.join(registry.en(value).split()) if isinstance(value, dict) else ''


def _zh(value) -> str:
    return value.get('zh', '') if isinstance(value, dict) else ''


def _english(value) -> str:
    """Every English string in a field, its Chinese where a text has no English, joined: what the mention route reads."""
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        return ' '.join(_english(x) for x in value)
    if isinstance(value, dict):
        if 'en' in value or 'zh' in value:
            return _en(value)
        return ' '.join(_english(x) for x in value.values())
    return ''


def slug(text: str) -> str:
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')


def base_ids(test_id: str) -> list[str]:
    """The ids a test row names: 'CG3 (round 1)' names CG3, 'TR4, TR5' names TR4 and TR5."""
    return [x for x in (re.sub(r'\s*\(.*?\)\s*', '', part).strip() for part in test_id.split(',')) if x]


def mentions(token: str):
    """A whole-token match of a test id in prose: LA2 not in LA2b, CG3 not in CG3b."""
    return re.compile(r'(?<![A-Za-z0-9_-])' + re.escape(token) + r'(?![A-Za-z0-9_])')


def _read(path: str):
    p = ROOT / path
    return json.loads(p.read_text(encoding='utf-8')) if p.is_file() else None


def inputs() -> set:
    """What the page reads beside the records and what the render writes in the same run (the atlas data, the graph),
    for research.py's input snapshot."""
    return {ROOT / TESTS, ROOT / COVERAGE, ROOT / SESSION_MAP, ROOT / registry.CORE_RECEIPT}


# --- loading -------------------------------------------------------------------------------------------------------

def load(records=None, atlas_json: str | None = None, graph_json: str | None = None) -> dict:
    """The stores, parsed: from what a render has in hand where given, else from the committed files."""
    if records is None:
        records, errors = registry.load_records()
        if errors:
            raise ValueError('records: ' + '; '.join(errors[:3]))
    receipt = _read(registry.CORE_RECEIPT) or {}
    return {
        'records': records,
        'atlas': json.loads(atlas_json) if atlas_json else _read(atlas.DATA),
        'graph': json.loads(graph_json) if graph_json else _read(theory_graph.GRAPH),
        'tests': (_read(TESTS) or {}).get('tests', []),
        'coverage': _read(COVERAGE) or {},
        'families': {f['id']: f.get('title_en', '') for f in (_read(SESSION_MAP) or {}).get('families', [])},
        'core': registry.receipt_declaration_names(receipt),
    }


def build(conn: sqlite3.Connection, src: dict, full: bool = False) -> None:
    """Fill the index. `full` adds the Lean catalogue's declarations and a full-text table, for queries; the page
    reads neither (the catalogue is written later in the same render, so a page reading it would lag a render)."""
    conn.executescript(SCHEMA + (FULL_SCHEMA if full else ''))
    records = src['records']
    by_id = {r['id']: r for r in records}
    rows = []
    for r in records:
        rows.append((r['id'], _en(r.get('title')), r.get('kind'), r.get('status'), int(r.get('status') not in NOT_LIVE),
                     r.get('family')))
    conn.executemany('INSERT INTO record VALUES (?,?,?,?,?,?)', rows)
    hyp, ref, dec = [], [], set()
    for r in records:
        for i, h in enumerate(r.get('hypotheses') or [], 1):
            hyp.append((r['id'], i, _en(h), _zh(h)))
        for x in r.get('references') or []:
            if isinstance(x, dict) and isinstance(x.get('path'), str):
                ref.append((r['id'], x['path'], x.get('role')))
                dec.update((r['id'], n) for n in x.get('declarations') or [] if isinstance(n, str))
        for law in r.get('laws') or []:
            if isinstance(law, dict):
                dec.update((r['id'], n) for n in law.get('declarations') or [] if isinstance(n, str))
    conn.executemany('INSERT INTO record_hypothesis VALUES (?,?,?,?)', hyp)
    conn.executemany('INSERT INTO record_reference VALUES (?,?,?)', ref)
    conn.executemany('INSERT INTO record_declaration VALUES (?,?)', sorted(dec))
    conn.executemany('INSERT INTO core_declaration VALUES (?)', [(n,) for n in sorted(src['core'])])

    graph = src['graph'] or {'nodes': [], 'edges': []}
    nodes = {n['id']: n for n in graph['nodes']}
    conn.executemany('INSERT INTO graph_node VALUES (?,?,?,?,?,?,?)', [
        (n['id'], n.get('type'), n.get('record'), n.get('chapter'), n.get('anchor'), n.get('name') or n.get('title') or n.get('unit'),
         n.get('region')) for n in graph['nodes']])
    conn.executemany('INSERT INTO graph_edge VALUES (?,?,?)', [(e['from'], e['to'], e.get('type')) for e in graph['edges']])
    homes = set()
    for e in graph['edges']:
        if e.get('type') == 'states' and e['to'].startswith('record:'):
            s = nodes.get(e['from']) or {}
            homes.add((e['to'][len('record:'):], s.get('chapter'), s.get('anchor')))
    conn.executemany('INSERT INTO record_home VALUES (?,?,?)', sorted(homes))

    data = src['atlas'] or {'dynamics': [], 'correspondences': []}
    dyn, drec, ddec, exits, trans, dtests = [], set(), set(), [], [], []
    for d in data['dynamics']:
        dyn.append((d['id'], d['family'], _en(d['name']), _zh(d['name']), d.get('base'), d.get('standing_without_record'),
                    int('premises' in d)))
        for r in d.get('records') or []:
            drec.add((d['id'], r, 'records'))
        for h in d.get('hypotheses') or []:
            drec.add((d['id'], h['record'], 'hypothesis'))
        for s in d.get('standing') or []:
            drec.add((d['id'], s['record'], 'standing'))
        for n in d.get('declarations') or []:
            core_name = n if n in src['core'] or 'Becoming.' + n not in src['core'] else 'Becoming.' + n  # as the chapters write it
            ddec.add((d['id'], n, core_name, int(core_name in src['core'])))
        for i, x in enumerate(d.get('exits') or [], 1):
            to = x.get('to')
            exits.append((d['id'], i, to if isinstance(to, str) else None, _en(to) if isinstance(to, dict) else None,
                          x.get('law'), x.get('strength'), x.get('source'), ','.join(x['drops']) if 'drops' in x else None))
            drec.update((d['id'], r, 'exit') for r in x.get('records') or [])
        for i, t in enumerate(d.get('transitions') or [], 1):
            ends = t.get('between') or {}
            trans.append((d['id'], i, t.get('kind'), _en(t.get('condition')),
                          int(ends.get('from') is not None and ends.get('to') is not None)))
            drec.update((d['id'], r, 'transition') for r in t.get('records') or [])
        for t in d.get('tests') or []:
            dtests.append((d['id'], t.get('path'), t.get('thesis'), t.get('state')))
    conn.executemany('INSERT INTO dynamic VALUES (?,?,?,?,?,?,?)', dyn)
    conn.executemany('INSERT INTO dynamic_record VALUES (?,?,?)', sorted(drec))
    conn.executemany('INSERT INTO dynamic_declaration VALUES (?,?,?,?)', sorted(ddec))
    conn.executemany('INSERT INTO exit VALUES (?,?,?,?,?,?,?,?)', exits)
    conn.executemany('INSERT INTO transition VALUES (?,?,?,?,?)', trans)
    conn.executemany('INSERT INTO dynamic_test VALUES (?,?,?,?)', dtests)

    cw, targets = [], []
    for c in data.get('correspondences') or []:
        cw.append((c['id'], c.get('domain'), c.get('group'), c.get('relation'), c.get('carried')))
        for i, t in enumerate(c.get('targets') or [], 1):
            anchor = t.get('anchor')
            mark = anchor.partition('#')[2] if isinstance(anchor, str) else ''
            home = mark[2:] if mark.startswith('r-') and mark[2:] in by_id else None
            targets.append((c['id'], i, t.get('record'), anchor, t.get('role'), home))
    conn.executemany('INSERT INTO correspondence VALUES (?,?,?,?,?)', cw)
    conn.executemany('INSERT INTO crosswalk_target VALUES (?,?,?,?,?,?)', targets)

    tests, bases, said = [], [], []
    texts = {r['id']: ' '.join(_english(r.get(f)) for f in MENTION_FIELDS) for r in records}
    for n, t in enumerate(src['tests'], 1):
        folder = t.get('folder') or ''
        tests.append((n, t.get('id'), t.get('name'), t.get('thesis'), folder, posixpath.dirname(folder), t.get('outcome'),
                      t.get('frozen'), t.get('run')))
        for b in base_ids(t.get('id') or ''):
            bases.append((n, b))
            pattern = mentions(b)
            said.extend((n, rid) for rid, body in texts.items() if pattern.search(body))
    conn.executemany('INSERT INTO test VALUES (?,?,?,?,?,?,?,?,?)', tests)
    conn.executemany('INSERT INTO test_base_id VALUES (?,?)', bases)
    conn.executemany('INSERT INTO test_mention VALUES (?,?)', sorted(set(said)))

    premises = (src['coverage'].get('premises') or {}).get('items') or []
    live_hyp = [(r, i, en) for r, i, en, _ in hyp if by_id[r].get('status') not in NOT_LIVE]
    pr, pw, ph = [], [], []
    for p in premises:
        pid = 'k3-' + slug(p['name'])
        pr.append((pid, p['name'], p.get('pattern'), p.get('kind')))
        for role in ('witnesses', 'meets', 'unrefuted', 'calibration'):  # a logical premise lists the last three instead
            pw.extend((pid, w, role) for w in p.get(role) or [])
        name = re.compile(r'(?<![A-Za-z])' + re.escape(p['name']) + r'(?![A-Za-z])', re.I)
        try:
            lean = re.compile(p['pattern']) if p.get('pattern') else None
        except re.error:
            lean = None
        for r, i, en in live_hyp:
            if name.search(en):
                ph.append((pid, r, i, 'name'))
            if lean and lean.search(en):
                ph.append((pid, r, i, 'pattern'))
    conn.executemany('INSERT INTO premise VALUES (?,?,?,?)', pr)
    conn.executemany('INSERT INTO premise_witness VALUES (?,?,?)', pw)
    conn.executemany('INSERT INTO premise_hypothesis VALUES (?,?,?,?)', ph)

    if full:
        catalogue = _read(CATALOGUE) or {}
        contents = catalogue.get('contents_by_sha256') or {}
        rows = []
        for f in catalogue.get('files') or []:
            if f.get('role') != 'working-source':
                continue
            for x in (contents.get(f.get('sha256')) or {}).get('declarations') or []:
                rows.append((f['path'], f['role'], x.get('kind'), x.get('name'), x.get('qualified_name_hint')))
        conn.executemany('INSERT INTO catalogue_declaration VALUES (?,?,?,?,?)', rows)
        fts = [('record', r['id'], 'statement', _en(r.get('statement'))) for r in records]
        fts += [('record', r, f'hypothesis {i}', en) for r, i, en, _ in hyp]
        fts += [('dynamic', d['id'], 'mechanism', _en(d.get('mechanism'))) for d in data['dynamics']]
        fts += [('correspondence', c['id'], 'sense', _en(c.get('sense'))) for c in data.get('correspondences') or []]
        fts += [('correspondence', c['id'], 'reading', _en(c.get('reading'))) for c in data.get('correspondences') or []]
        fts += [('test', t.get('id'), 'gloss', t.get('gloss') or '') for t in src['tests']]
        conn.executemany('INSERT INTO text_fts VALUES (?,?,?,?)', fts)
    conn.commit()


# --- measuring -----------------------------------------------------------------------------------------------------

def _one(conn, sql, *args):
    return conn.execute(sql, args).fetchone()[0]


def _all(conn, sql, *args):
    return conn.execute(sql, args).fetchall()


TEST_FOLDER_JOIN = "(dt.path = t.directory OR dt.path = t.folder OR t.folder LIKE dt.path || '/%' OR dt.path LIKE t.directory || '/%')"
TEST_REFERENCE_JOIN = "(rr.path = t.folder OR rr.path LIKE t.directory || '/%')"


def measure(conn: sqlite3.Connection) -> dict:
    """Every count and list the page shows, from the index alone."""
    m = {}
    q = lambda sql, *a: _one(conn, sql, *a)  # noqa: E731
    # Exits and transitions.
    m['dynamics'] = q('SELECT count(*) FROM dynamic')
    m['exits'] = q('SELECT count(*) FROM exit')
    m['exits_to_dynamic'] = q('SELECT count(*) FROM exit WHERE to_dynamic IS NOT NULL')
    m['exits_to_text'] = q('SELECT count(*) FROM exit WHERE to_text IS NOT NULL')
    m['exits_nowhere'] = q('SELECT count(*) FROM exit WHERE to_dynamic IS NULL AND to_text IS NULL')
    m['exits_witness'] = q("SELECT count(*) FROM exit WHERE strength = 'witness'")
    m['exits_dangling'] = _all(conn, 'SELECT dynamic, idx, to_dynamic FROM exit WHERE to_dynamic IS NOT NULL '
                                     'AND to_dynamic NOT IN (SELECT id FROM dynamic)')
    m['no_exit'] = _all(conn, 'SELECT family, id FROM dynamic WHERE id NOT IN (SELECT dynamic FROM exit) ORDER BY family, id')
    m['by_family'] = _all(conn, """
        SELECT d.family, count(DISTINCT d.id),
               sum(CASE WHEN (SELECT count(*) FROM exit e WHERE e.dynamic = d.id) = 0 THEN 1 ELSE 0 END),
               (SELECT count(*) FROM exit e JOIN dynamic x ON x.id = e.dynamic WHERE x.family = d.family),
               (SELECT count(*) FROM exit e JOIN dynamic x ON x.id = e.dynamic WHERE x.family = d.family AND (e.to_dynamic IS NOT NULL OR e.to_text IS NOT NULL)),
               (SELECT count(*) FROM exit e JOIN dynamic x ON x.id = e.dynamic WHERE x.family = d.family AND e.strength = 'witness'),
               (SELECT count(*) FROM transition t JOIN dynamic x ON x.id = t.dynamic WHERE x.family = d.family)
        FROM dynamic d GROUP BY d.family ORDER BY d.family""")
    m['destinations'] = _all(conn, 'SELECT e.dynamic, e.idx, e.to_dynamic, e.to_text, e.strength FROM exit e '
                                   'WHERE e.to_dynamic IS NOT NULL OR e.to_text IS NOT NULL ORDER BY e.dynamic, e.idx')
    m['transitions'] = q('SELECT count(*) FROM transition')
    m['transitions_between'] = q('SELECT count(*) FROM transition WHERE between_named = 1')
    m['exits_with_drops'] = q('SELECT count(*) FROM exit WHERE drops IS NOT NULL')
    m['dynamics_premises_read'] = q('SELECT count(*) FROM dynamic WHERE premises_read = 1')
    # Tests.
    m['tests'] = q('SELECT count(*) FROM test')
    m['test_folders_shared'] = _all(conn, 'SELECT directory, group_concat(id, \'; \') FROM test GROUP BY directory HAVING count(*) > 1 ORDER BY directory')
    shared = {d for d, _ in m['test_folders_shared']}
    rows = []
    for row, tid, folder, directory, outcome in _all(conn, 'SELECT row, id, folder, directory, outcome FROM test ORDER BY row'):
        dyn = [x for (x,) in _all(conn, f'SELECT DISTINCT dt.dynamic FROM dynamic_test dt, test t WHERE t.row = ? AND {TEST_FOLDER_JOIN} ORDER BY 1', row)]
        rec = [x for (x,) in _all(conn, f'SELECT DISTINCT rr.record FROM record_reference rr, test t WHERE t.row = ? AND {TEST_REFERENCE_JOIN} ORDER BY 1', row)]
        said = [x for (x,) in _all(conn, 'SELECT DISTINCT record FROM test_mention WHERE row = ? ORDER BY 1', row)]
        rows.append({'row': row, 'id': tid, 'folder': folder, 'outcome': outcome, 'shared': directory in shared,
                     'dynamics': dyn, 'records': rec, 'mentioned': said})
    m['test_rows'] = rows
    m['tests_record_exact'] = sum(1 for r in rows if r['records'] and not r['shared'])
    m['tests_record_ambiguous'] = sum(1 for r in rows if r['records'] and r['shared'])
    m['tests_record_mention_only'] = sum(1 for r in rows if not r['records'] and r['mentioned'])
    m['tests_record_none'] = sum(1 for r in rows if not r['records'] and not r['mentioned'])
    m['tests_dynamic_exact'] = sum(1 for r in rows if r['dynamics'] and not r['shared'])
    m['tests_dynamic_ambiguous'] = sum(1 for r in rows if r['dynamics'] and r['shared'])
    m['tests_dynamic_none'] = sum(1 for r in rows if not r['dynamics'])
    m['tests_nothing'] = sum(1 for r in rows if not r['records'] and not r['mentioned'] and not r['dynamics'])
    m['dynamic_test_links'] = q('SELECT count(*) FROM dynamic_test')
    m['dynamic_test_links_ambiguous'] = q(f'SELECT count(*) FROM dynamic_test dt WHERE (SELECT count(*) FROM test t WHERE {TEST_FOLDER_JOIN}) > 1')
    m['dynamic_test_links_unmatched'] = _all(conn, f'SELECT dynamic, path FROM dynamic_test dt WHERE NOT EXISTS (SELECT 1 FROM test t WHERE {TEST_FOLDER_JOIN}) ORDER BY 1, 2')
    # The crosswalk.
    m['correspondences'] = q('SELECT count(*) FROM correspondence')
    m['targets'] = q('SELECT count(*) FROM crosswalk_target')
    m['targets_record'] = q('SELECT count(*) FROM crosswalk_target WHERE record IS NOT NULL')
    m['targets_home_only'] = q('SELECT count(*) FROM crosswalk_target WHERE record IS NULL AND home_record IS NOT NULL')
    m['targets_section_only'] = q('SELECT count(*) FROM crosswalk_target WHERE record IS NULL AND home_record IS NULL')
    m['targets_conflict'] = _all(conn, 'SELECT correspondence, idx, record, home_record FROM crosswalk_target '
                                       'WHERE record IS NOT NULL AND home_record IS NOT NULL AND record != home_record ORDER BY 1, 2')
    reach = """CREATE TEMP VIEW cw_reach AS
        SELECT DISTINCT t.correspondence, dr.dynamic, CASE WHEN t.record IS NOT NULL THEN 'named' ELSE 'home' END AS by
        FROM crosswalk_target t JOIN dynamic_record dr ON dr.record = coalesce(t.record, t.home_record)"""
    conn.execute('DROP VIEW IF EXISTS cw_reach')
    conn.execute(reach)
    m['cw_reach_named'] = q("SELECT count(DISTINCT correspondence) FROM cw_reach WHERE by = 'named'")
    m['cw_reach_named_own'] = _all(conn, """SELECT count(DISTINCT t.correspondence), count(DISTINCT dr.dynamic) FROM crosswalk_target t
        JOIN dynamic_record dr ON dr.record = t.record AND dr.via = 'records'""")[0]
    m['cw_no_target'] = q('SELECT count(*) FROM correspondence WHERE id NOT IN (SELECT correspondence FROM crosswalk_target)')
    m['cw_no_target_by_carried'] = _all(conn, 'SELECT carried, count(*) FROM correspondence WHERE id NOT IN (SELECT correspondence FROM crosswalk_target) GROUP BY carried ORDER BY 2 DESC')
    m['cw_no_record_target'] = q('SELECT count(*) FROM correspondence WHERE id IN (SELECT correspondence FROM crosswalk_target) '
                                 'AND id NOT IN (SELECT correspondence FROM crosswalk_target WHERE record IS NOT NULL OR home_record IS NOT NULL)')
    m['cw_reach_named_dynamics'] = q("SELECT count(DISTINCT dynamic) FROM cw_reach WHERE by = 'named'")
    m['cw_reach'] = q('SELECT count(DISTINCT correspondence) FROM cw_reach')
    m['cw_reach_dynamics'] = q('SELECT count(DISTINCT dynamic) FROM cw_reach')
    m['cw_by_domain'] = _all(conn, """
        SELECT c.domain, count(*),
               sum(CASE WHEN c.id IN (SELECT correspondence FROM cw_reach) THEN 1 ELSE 0 END),
               (SELECT count(*) FROM crosswalk_target t JOIN correspondence x ON x.id = t.correspondence WHERE x.domain = c.domain),
               (SELECT count(*) FROM crosswalk_target t JOIN correspondence x ON x.id = t.correspondence
                 WHERE x.domain = c.domain AND (t.record IS NOT NULL OR t.home_record IS NOT NULL))
        FROM correspondence c GROUP BY c.domain ORDER BY c.domain""")
    m['dynamics_no_correspondence'] = q('SELECT count(*) FROM dynamic WHERE id NOT IN (SELECT dynamic FROM cw_reach)')
    # The atlas and the theory graph.
    m['graph_nodes'] = q('SELECT count(*) FROM graph_node')
    m['graph_types'] = _all(conn, 'SELECT type, count(*) FROM graph_node GROUP BY type ORDER BY 2 DESC')
    m['graph_atlas_nodes'] = q("SELECT count(*) FROM graph_node WHERE type IN ('dynamic', 'correspondence', 'test', 'premise', 'exit', 'transition')")
    m['dynamics_with_record'] = q('SELECT count(DISTINCT dynamic) FROM dynamic_record')
    m['dynamics_in_graph'] = q("SELECT count(DISTINCT dr.dynamic) FROM dynamic_record dr JOIN graph_node n ON n.record = dr.record AND n.type = 'result'")
    m['dynamics_without_record'] = _all(conn, 'SELECT family, id, standing_without_record FROM dynamic WHERE id NOT IN (SELECT dynamic FROM dynamic_record) ORDER BY family, id')
    # Declarations.
    m['core'] = q('SELECT count(*) FROM core_declaration')
    m['dynamic_declarations'] = q('SELECT count(DISTINCT name) FROM dynamic_declaration')
    m['dynamic_declarations_core'] = q('SELECT count(DISTINCT name) FROM dynamic_declaration WHERE in_core = 1')
    m['dynamic_declarations_unrecorded'] = q("""
        SELECT count(*) FROM dynamic_declaration dd WHERE NOT EXISTS (
          SELECT 1 FROM dynamic_record dr JOIN record_declaration rd ON rd.record = dr.record
          WHERE dr.dynamic = dd.dynamic AND rd.name IN (dd.name, dd.full))""")
    m['dynamic_declaration_pairs'] = q('SELECT count(*) FROM dynamic_declaration')
    m['declarations_several_records'] = q("""
        SELECT count(*) FROM (SELECT DISTINCT dd.name FROM dynamic_declaration dd
          WHERE (SELECT count(DISTINCT rd.record) FROM record_declaration rd WHERE rd.name IN (dd.name, dd.full)) > 1)""")
    m['record_declarations'] = q('SELECT count(DISTINCT name) FROM record_declaration')
    m['record_declarations_core'] = q('SELECT count(DISTINCT rd.name) FROM record_declaration rd JOIN core_declaration c ON c.name = rd.name')
    # Records the atlas's dynamics do not cite.
    live_theorems = "SELECT id FROM record WHERE live = 1 AND kind = 'theorem'"
    m['live_records'] = q('SELECT count(*) FROM record WHERE live = 1')
    m['live_theorems'] = q(f'SELECT count(*) FROM ({live_theorems})')
    m['cited'] = q(f'SELECT count(DISTINCT record) FROM dynamic_record WHERE record IN ({live_theorems})')
    m['cited_by_records_field'] = q(f"SELECT count(DISTINCT record) FROM dynamic_record WHERE via = 'records' AND record IN ({live_theorems})")
    uncited = f'SELECT id FROM ({live_theorems}) WHERE id NOT IN (SELECT record FROM dynamic_record WHERE record IS NOT NULL)'
    m['uncited'] = q(f'SELECT count(*) FROM ({uncited})')
    m['uncited_crosswalk'] = q(f'SELECT count(*) FROM ({uncited}) WHERE id IN (SELECT coalesce(record, home_record) FROM crosswalk_target WHERE coalesce(record, home_record) IS NOT NULL)')
    m['uncited_by_family'] = _all(conn, f"""
        SELECT r.family, count(*), sum(CASE WHEN r.id IN ({uncited}) THEN 1 ELSE 0 END)
        FROM record r WHERE r.id IN ({live_theorems}) GROUP BY r.family ORDER BY r.family""")
    home = "coalesce((SELECT min(h.chapter) FROM record_home h WHERE h.record = r.id), '')"
    m['uncited_by_chapter'] = _all(conn, f"""
        SELECT {home} AS chapter, count(*), sum(CASE WHEN r.id IN ({uncited}) THEN 1 ELSE 0 END)
        FROM record r WHERE r.id IN ({live_theorems}) GROUP BY chapter ORDER BY chapter""")
    m['uncited_records'] = _all(conn, f"""
        SELECT {home} AS chapter, r.id, r.id IN (SELECT coalesce(record, home_record) FROM crosswalk_target WHERE coalesce(record, home_record) IS NOT NULL)
        FROM record r WHERE r.id IN ({uncited}) ORDER BY chapter, r.id""")
    m['records_several_homes'] = _all(conn, 'SELECT record, count(*) FROM record_home GROUP BY record HAVING count(*) > 1 ORDER BY record')
    m['records_no_home'] = q(f"SELECT count(*) FROM ({live_theorems}) WHERE id NOT IN (SELECT record FROM record_home)")
    hyp = _all(conn, 'SELECT count(*), count(DISTINCT en) FROM record_hypothesis h JOIN record r ON r.id = h.record WHERE r.live = 1')[0]
    m['hypotheses'], m['hypothesis_wordings'] = hyp
    # The pilots.
    m['pilot_tests'] = [r for r in rows if set(base_ids(r['id'] or '')) & set(PILOT_TESTS)]
    m['premises'] = []
    def matched(pid, by):
        return _all(conn, 'SELECT count(*), count(DISTINCT record) FROM premise_hypothesis WHERE premise = ? AND by = ?', pid, by)[0]
    for pid, name, pattern, kind in _all(conn, 'SELECT id, name, pattern, kind FROM premise ORDER BY rowid'):
        dyn = q("""SELECT count(DISTINCT dr.dynamic) FROM premise_hypothesis p JOIN dynamic_record dr ON dr.record = p.record AND dr.via = 'hypothesis'
                   WHERE p.premise = ?""", pid)
        witnesses = _all(conn, 'SELECT count(*), sum(CASE WHEN declaration IN (SELECT name FROM core_declaration) THEN 1 ELSE 0 END) '
                               'FROM premise_witness WHERE premise = ?', pid)[0]
        m['premises'].append({'id': pid, 'name': name, 'kind': kind, 'by_name': matched(pid, 'name'), 'by_pattern': matched(pid, 'pattern'), 'dynamics': dyn,
                              'witnesses': witnesses[0], 'witnesses_core': witnesses[1] or 0})
    m['premise_hypotheses'] = q('SELECT count(*) FROM (SELECT DISTINCT record, idx FROM premise_hypothesis)')
    m['premise_hypotheses_several'] = q('SELECT count(*) FROM (SELECT record, idx FROM premise_hypothesis GROUP BY record, idx HAVING count(DISTINCT premise) > 1)')
    return m


