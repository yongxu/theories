def render(records, atlas_json: str | None, graph_json: str | None) -> tuple[dict, list[str]]:
    """The page and errors, for research.py render and check, from this render's atlas data and graph."""
    try:
        src = load(records, atlas_json, graph_json)
        if not src['atlas'] or not src['graph']:
            return {}, ['atlas index: no atlas data or theory graph to read']
        conn = sqlite3.connect(':memory:')
        build(conn, src)
        body = page(measure(conn), src['atlas'], src['families'])
        conn.close()
    except (ValueError, KeyError, TypeError, sqlite3.Error) as exc:
        return {}, [f'atlas index: {exc!r}']
    return {REPORT: body}, []


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--db', default=DB, help=f'where to write the index (default {DB}, which the repository ignores)')
