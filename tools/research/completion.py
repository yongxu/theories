# --- Lean sources (R30's parser, reduced) -------------------------------------------------------------------

def _strip_comments(src: str) -> str:
    out, i, n, depth, in_str = [], 0, len(src), 0, False
    while i < n:
        c = src[i]
        if depth == 0 and not in_str and src.startswith('--', i):
            j = src.find('\n', i)
            j = n if j < 0 else j
            out.append(' ' * (j - i))
            i = j
            continue
        if not in_str and src.startswith('/-', i):
            depth += 1
            out.append('  ')
            i += 2
            continue
        if depth > 0:
            if src.startswith('-/', i):
                depth -= 1
                out.append('  ')
                i += 2
                continue
            out.append('\n' if c == '\n' else ' ')
            i += 1
            continue
        if c == '"' and (i == 0 or src[i - 1] != '\\') and not (i > 0 and src[i - 1] == "'"):
            in_str = not in_str
        out.append(c)
        i += 1
    return ''.join(out)


_KW = r'(theorem|lemma|def|abbrev|structure|inductive|class|instance|opaque|axiom)'
_DECL = re.compile(r'^(?P<mods>(?:@\[[^\]]*\]\s*)?(?:(?:private|protected|noncomputable|partial|nonrec|unsafe)\s+)*)'
                   + _KW + r'\b\s*(?P<name>[^\s:({\[]*)', re.M)


def _split(text: str, kind: str):
    depth = 0
    for i, c in enumerate(text):
        if c in '([{⟨':
            depth += 1
        elif c in ')]}⟩':
            depth -= 1
        elif depth <= 0:
            if text.startswith(':=', i):
                return text[:i], text[i + 2:]
            if re.match(r'\swhere\b', text[i:i + 7]):
                return text[:i], text[i:]
            if c == '\n' and re.match(r'\n\s*\|', text[i:]):
                return text[:i], text[i:]
    return text, ''


def parse_module(path: Path) -> list[dict]:
    lines = _strip_comments(path.read_text(encoding='utf-8')).split('\n')
    # stack entries: (kind, name, variable binders declared in that scope, namespaces opened in it)
    stack, decls, cur, outer, outer_opens = [], [], None, [], []
    var = None
    for line in lines:
        s = line.strip()
        top = not line.startswith(' ')
        if var is not None and not top and s:
            var.append(s)
            continue
        var = None
        m = re.match(r'^namespace\s+(\S+)', s)
        if m and top:
            stack.append(('ns', m.group(1), [], []))
            continue
        m = re.match(r'^section\b\s*(\S*)', s)
        if m and top:
            stack.append(('sec', m.group(1), [], []))
            continue
        if re.match(r'^end\b', s) and top:
            if stack:
                stack.pop()
            continue
        m = _DECL.match(line)
        if m:
            name = m.group('name')
            ns = '.'.join(x[1] for x in stack if x[0] == 'ns' and x[1])
            full = name[len('_root_.'):] if name.startswith('_root_.') else (f'{ns}.{name}' if ns and name else name or ns)
            scope = [b for x in stack for b in x[2]] + outer
            opens = [o for x in stack for o in x[3]] + outer_opens
            cur = {'kind': m.group(2), 'full': full, 'text': [line], 'variables': list(scope), 'opens': opens}
            decls.append(cur)
            continue
        if top and s.startswith('variable'):
            var = (stack[-1][2] if stack else outer)
            var.append(s[len('variable'):])
            cur = None
            continue
        m = re.match(r'^open\s+(.*)$', s)
        if m and top and ' in' not in m.group(1):
            names = [o for o in re.split(r'\s+', re.sub(r'\(.*?\)|hiding.*|renaming.*', '', m.group(1))) if re.match(r'^[A-Z][\w.]*$', o)]
            (stack[-1][3] if stack else outer_opens).extend(names)
            cur = None
            continue
        if top and re.match(r'^(open|universe|set_option|attribute|#|import|noncomputable section|mutual|deriving)\b', s):
            cur = None
            continue
        if cur is not None:
            cur['text'].append(line)
    for d in decls:
        d['statement'], d['proof'] = _split('\n'.join(d.pop('text')), d['kind'])
    return decls


_BINDER = re.compile(r'[({\[⦃]([^(){}\[\]⦃⦄]*)[)}\]⦄]')


def reading(d: dict) -> str:
    """The text a premise or choice is looked for in: the statement, the namespace of its name (a law stated as
    `Flow.Balances.x` takes the balance it is stated on), and the `variable` binders in scope whose names the
    statement mentions, or which mention such a name (instance binders)."""
    st = d.get('statement', '')
    words = set(re.findall(r"[\w']+", st))
    ns = d.get('full', '').rsplit('.', 1)[0].replace('.', ' ')
    kept = []
    for line in d.get('variables', []):
        for b in _BINDER.findall(line):
            names, _, typ = b.partition(':')
            named = set(re.findall(r"[\w']+", names)) if typ else set()
            if (named & words) or (not typ and set(re.findall(r"[\w']+", b)) & words):
                kept.append(b)
    return _flat(' '.join([st, ns] + kept))


# --- inputs -------------------------------------------------------------------------------------------------

def _json(rel: str):
    return json.loads((ROOT / rel).read_text())


@lru_cache(maxsize=1)
def sources() -> dict:
    """Full name -> {module, layer, kind, statement, proof} for every declaration of the receipt's pure modules."""
    receipt = _json(RECEIPT)
    layer = {m['module']: m['layer'] for m in receipt['modules']}
    listed = {d['name']: m['module'] for m in receipt['modules'] for d in m['declarations']}
    out = {}
    for module, rel in receipt['source_paths'].items():
        if layer.get(module) not in PURE:
            continue
        for d in parse_module(ROOT / LEAN_ROOT / rel):
            if d['full'] in listed:
                out[d['full']] = {**d, 'module': listed[d['full']], 'layer': layer[listed[d['full']]]}
    # A declaration the receipt lists that the parser did not place keeps its module and layer.
    for name, module in listed.items():
        out.setdefault(name, {'full': name, 'kind': '?', 'statement': '', 'proof': '', 'module': module, 'layer': layer[module]})
    return out


def _flat(text: str) -> str:
    return re.sub(r'\s+', ' ', text).strip()


