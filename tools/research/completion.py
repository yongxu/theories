def validate(cov: dict, decls: dict, record_ids: set) -> list[str]:
    errors = []
    for key in ('rows', 'premises', 'representation', 'enclosure', 'ethics_chain', 'open_register', 'statuses'):
        if key not in cov:
            errors.append(f'coverage: missing "{key}"')
    if errors:
        return errors
    seen = set()
    for row in cov['rows']:
        rid = row.get('id')
        if rid in seen:
            errors.append(f'coverage: row {rid} listed twice')
        seen.add(rid)
        if row.get('status') not in cov['statuses']:
            errors.append(f'coverage: row {rid}: unknown status {row.get("status")}')
        if not row.get('declarations'):
            errors.append(f'coverage: row {rid}: no central declarations')
        for name in row.get('declarations', []):
            if name not in decls:
                errors.append(f'coverage: row {rid}: {name} is not a declaration of the core receipt')
        for r in row.get('records', []):
            if r not in record_ids:
                errors.append(f'coverage: row {rid}: no record {r}')
    axes = collections.Counter(r.get('axis') for r in cov['rows'])
    for axis, n in (('phase', 5), ('differentiation', 6), ('domain', 6)):
        if axes[axis] != n:
            errors.append(f'coverage: {n} {axis} rows expected, {axes[axis]} found')
    named = [w for p in cov['premises']['items'] for w in p['witnesses']]
    named += [w for p in cov['premises']['items'] for k in ('meets', 'unrefuted', 'calibration') for w in p.get(k, [])]
    named += [x for x in cov['ethics_chain']['steps']]
    named += [i for row in cov['rows'] for v in row.get('instances', {}).values() for i in v]
    named += [x for c in cov.get('unity', {}).get('constructions', []) for x in c['declarations']]
    named += [x[k] for x in cov['representation']['natural_number_laws'] for k in ('law', 'dense') if x.get(k)]
    for name in named:
        if name not in decls:
            errors.append(f'coverage: {name} is not a declaration of the core receipt')
    for law in cov.get('master_laws', []):
        for a in law.get('anchors', []):
            if a not in decls:
                errors.append(f'coverage: master law {law.get("id")}: anchor {a} is not a declaration of the core')
    return errors


def k1(cov, decls, conn):
    findings = []
    classes = conn.get('theorems', {})
    for row in cov['rows']:
        for name in row['declarations']:
            d = decls.get(name)
            if d is None:
                continue
            if d['layer'] not in ('core', 'foundation'):
                findings.append(f'{row["id"]}: {name} is in the {d["layer"]} ring, not the core')
            cls = classes.get(name)
            if cls and cls.startswith('apart'):
                findings.append(f'{row["id"]}: {name} stands apart from both base families ({cls})')
        if row['status'] != 'proved':
            findings.append(f'{row["id"]}: status {row["status"]}')
    return findings


OWN_MODULE = 'statement on the base only through a law of its own module'


def k2(cov, decls, conn):
    """Every central declaration in the main component and either stated on a base family (directly or through
    its own module's definitions) or a general law with a named base-family instance whose proof reaches it; the
    World family reaching the Process family by definition, and every other direction by a named construction
    (definitions are acyclic, so two families cannot each reach the other by definition)."""
    findings = []
    outside = set(conn.get('components', {}).get('theorems_outside_the_main_component', []))
    classes = conn.get('theorems', {})
    for row in cov['rows']:
        instances = row.get('instances', {})
        for name in row['declarations']:
            if name in outside:
                findings.append(f'{row["id"]}: {name} lies outside the main dependency component')
            cls = classes.get(name)
            if cls is None or cls in STATEMENT_CLASSES or cls == OWN_MODULE:
                continue
            good = [i for i in instances.get(name, []) if classes.get(i) in STATEMENT_CLASSES and reaches(decls, i, name)]
            if not good:
                findings.append(f'{row["id"]}: {name}: its statement is not on a base family ({cls}) and no base-family '
                                'instance reaching it is listed' + (f' (listed: {", ".join(instances[name])})' if instances.get(name) else ''))
    unity = cov.get('unity', {})
    reach = conn.get('families_reach_each_other', {})
    built = {c['direction']: c for c in unity.get('constructions', [])}
    for direction, holds in reach.items():
        if holds:
            continue
        if direction in unity.get('definitional', []):
            findings.append(f'families_reach_each_other: {direction} is false, and it is asked by definition')
        elif direction not in built:
            findings.append(f'families_reach_each_other: {direction} is false and no construction is listed')
    return findings


def _central(cov):
    return [(row['id'], name) for row in cov['rows'] for name in row['declarations']]


def _binders(statement: str) -> str:
    """The binder groups of a statement: what precedes the colon, at bracket depth zero, that opens its type."""
    m = re.match(r'\s*(?:@\[[^\]]*\]\s*)?(?:(?:private|protected|noncomputable)\s+)*(?:theorem|lemma|def|abbrev)\s+\S+', statement)
    rest = statement[m.end():] if m else statement
    depth = 0
    for i, ch in enumerate(rest):
        if ch in '([{⦃':
            depth += 1
        elif ch in ')]}⦄':
            depth -= 1
        elif ch == ':' and depth == 0 and not rest[i + 1:i + 2] == '=':
            return rest[:i]
    return rest


def exchange_forms(cov, decls):
    """K3's tying premises: each central statement whose binders take one has a form over the exchange, a declaration whose
    proof reaches the statement and whose binders use none of the tying premises. Returns findings, the forms
    found, and the premises the forms still take (each a state of the law or the law's own)."""
    pr = cov['premises']
    tying = {p['name']: p['pattern'] for p in pr['items'] if p['name'] in pr.get('tying', [])}
    forms = pr.get('exchange_forms', {})
    findings, found, kept = [], {}, collections.defaultdict(set)
    for rid, name in _central(cov):
        if name in found:
            continue
        taken = [n for n, pat in tying.items() if re.search(pat, _binders(decls.get(name, {}).get('statement', '')))]
        if not taken:
            continue
        form = forms.get(name)
        if not form:
            findings.append(f'{name}: takes {", ".join(taken)} and lists no form over the exchange')
            continue
        if form not in decls:
            findings.append(f'{name}: its form over the exchange {form} is not a declaration of the receipt')
            continue
        hyp = _binders(decls[form].get('statement', ''))
        left = [n for n, pat in tying.items() if re.search(pat, hyp)]
        if left:
            findings.append(f'{name}: its form over the exchange {form} still takes {", ".join(left)}')
            continue
        if not reaches(decls, form, name):
            findings.append(f'{name}: the proof of its form over the exchange {form} does not use it')
            continue
        found[name] = form
        for p in pr['items']:
            if p['name'] not in tying and re.search(p['pattern'], hyp):
                kept[p['name']].add(form)
    reading_ = pr.get('reading')
    if reading_:
        for k in ('declaration', 'gives'):
            if reading_.get(k) and reading_[k] not in decls:
                findings.append(f'the reading {reading_["name"]}: {reading_[k]} is not a declaration of the receipt')
        for k in ('meets', 'fails'):
            if not reading_.get(k):
                findings.append(f'the reading {reading_["name"]}: no declaration listed that {k[:-1]}s it')
            for w in reading_.get(k, []):
                if w not in decls:
                    findings.append(f'the reading {reading_["name"]}: {w} is not a declaration of the receipt')
    return findings, found, {k: sorted(v) for k, v in kept.items()}


def k3(cov, decls):
    findings, used = [], collections.defaultdict(list)
    for rid, name in _central(cov):
        st = reading(decls.get(name, {}))
        for p in cov['premises']['items']:
            if re.search(p['pattern'], st):
                used[p['name']].append(name)
    for p in cov['premises']['items']:
        if p.get('kind') == 'logical':
            missing = [k for k in ('meets', 'unrefuted', 'calibration') if not p.get(k)]
            if p['name'] in used and missing:
                findings.append(f'{p["name"]}: a logical premise used by {len(set(used[p["name"]]))} central statement(s) '
                                f'without {", ".join(missing)} listed')
            continue
        if p['name'] in used and not p['witnesses']:
            findings.append(f'{p["name"]}: used by {len(set(used[p["name"]]))} central statement(s) '
                            f'({", ".join(sorted(set(used[p["name"]]))[:3])}{", ..." if len(set(used[p["name"]])) > 3 else ""}), '
                            'no witnesses meeting and failing it listed' + (f'; {p["note"]}' if p.get('note') else ''))
    return findings, {k: sorted(set(v)) for k, v in used.items()}


def k4(cov, decls):
    findings, tags = [], {}
    for rid, name in _central(cov):
        st = reading(decls.get(name, {}))
        tags[name] = [c['name'] for c in cov['representation']['choices'] if re.search(c['pattern'], st)]
    for law in cov['representation']['natural_number_laws']:
        if not law.get('dense'):
            findings.append(f'{law["law"]}: no form over dense amounts or counterexample ({law.get("note", "")})')
        elif law.get('kind') not in ('form', 'counterexample'):
            findings.append(f'{law["law"]}: {law["dense"]} is listed without saying whether it is a form or a counterexample')
    return findings, tags


def k5(cov, decls, chapter):
    findings, found = [], collections.defaultdict(set)
    section0 = chapter.split('## 0. Premise card', 1)[-1].split('\n## ', 1)[0]
    params = cov['enclosure']['parameters']
    for p in params:
        if f'`{p["section0"]}' not in section0:
            findings.append(f'{p["name"]}: chapter section 0 does not state {p["section0"]}')
    for rid, name in _central(cov):
        st = reading(decls.get(name, {}))
        for p in params:
            if re.search(p['pattern'], st):
                found[p['name']].add(name)
    return findings, {k: sorted(v) for k, v in found.items()}


def _references(decls):
    """Each declaration's proof references, resolved as Lean resolves names: an unqualified or qualified name
    against the declaration's namespace and each enclosing one, and in the namespaces its scope opens, dropping projections after a qualified name
    (`Foo.bar_iff.mpr`); otherwise a qualified name (field notation after a
    variable, `W.law`) by its last components where exactly one declaration ends with them."""
    by_last = collections.defaultdict(set)
    for full in decls:
        by_last[full.rsplit('.', 1)[-1]].add(full)
    ident = re.compile(r"(?<![\w.'])([A-Za-z_][\w'?]*(?:\.[A-Za-z_][\w'?]*)*)")

    def resolve(tok, ns, opens=()):
        parts = ns.split('.') if ns else []
        comps = tok.split('.')
        # the whole name, then a qualified name with projections after it dropped (`Foo.bar_iff.mpr`)
        for k in [len(comps)] + list(range(len(comps) - 1, 1, -1)):
            name = '.'.join(comps[:k])
            for i in range(len(parts), -1, -1):
                cand = '.'.join(parts[:i] + [name])
                if cand in decls:
                    return cand
                for o in opens:
                    cand = '.'.join(parts[:i] + [o, name])
                    if cand in decls:
                        return cand
        head, _, rest = tok.partition('.')
        if rest:
            hits = [f for f in by_last.get(rest.rsplit('.', 1)[-1], ()) if f.endswith('.' + rest)]
            if len(hits) == 1:
                return hits[0]
        return None

    @lru_cache(maxsize=None)
    def refs(full):
        ns = full.rsplit('.', 1)[0] if '.' in full else ''
        opens = tuple(decls[full].get('opens', ()))
        out = {r for tok in ident.findall(decls[full].get('proof', '')) if (r := resolve(tok, ns, opens))}
        out.discard(full)
        return frozenset(out)
    return refs


def reaches(decls, start, target, limit=40000):
    refs = _references(decls)
    seen, todo = {start}, [start]
    while todo and len(seen) < limit:
        cur = todo.pop()
        for nxt in refs(cur):
            if nxt == target:
                return True
            if nxt not in seen:
                seen.add(nxt)
                todo.append(nxt)
    return False


def k6(cov, decls):
    """The last step, the conclusion, reaches every earlier step through its proof, so every step is used in
    one derivation of it, rooted at the first (the evaluation row); every normative hypothesis their statements
    use is named. A step need not reach the step listed before it: lemmas joined by a later step are one
    derivation too."""
    findings, links = [], []
    steps = cov['ethics_chain']['steps']
    for i, b in enumerate(steps[1:], 1):
        links.append((b, [a for a in steps[:i] if reaches(decls, b, a)]))
    last = steps[-1]
    for a in steps[:-1]:
        if not reaches(decls, last, a):
            findings.append(f'the conclusion {last} does not reach {a} through its proof')
    used = set()
    for name in steps:
        st = reading(decls.get(name, {}))
        for h in cov['ethics_chain']['normative_hypotheses']:
            if re.search(h['pattern'], st):
                used.add(h['name'])
    return findings, links, sorted(used)


def k7(cov, chapter):
    findings, items = [], []
    sec = chapter.split('### 8.1 Open items, ranked', 1)
    if len(sec) < 2:
        return ['chapter: section 8.1 not found'], items
    body = sec[1].split('\n### ', 1)[0].split('\n## ', 1)[0]
    classes = cov['open_register']['classes']
    for m in re.finditer(r'^(\d+)\. \*\*([^*]+)\*\* \(([^)]*)\)\.(.*)$', body, re.M):
        n, title, rest = int(m.group(1)), m.group(2).strip(), m.group(4)
        cls = re.split(r'[;,]', m.group(3))[0].strip()  # the class, before any remark ("; the formal part ...")
        items.append({'n': n, 'title': title, 'class': cls})
        if cls not in classes:
            findings.append(f'item {n} ({title}): class "{cls}" is not one of {", ".join(classes)}')
        if '*Open:*' not in rest and cls != 'philosophical warrant':
            findings.append(f'item {n} ({title}): no open part stated')
    numbers = [i['n'] for i in items]
    if numbers != list(range(1, len(numbers) + 1)):
        findings.append(f'items not numbered 1..{len(numbers)}: {numbers}')
    for title, k in collections.Counter(i['title'] for i in items).items():
        if k > 1:
            findings.append(f'item "{title}" listed {k} times')
    open_refs = {n for row in cov['rows'] for n in row.get('open_items', [])}
    for n in sorted(open_refs - set(numbers)):
        findings.append(f'coverage names open item {n}, which section 8.1 does not have')
    return findings, items


def evaluate() -> dict:
    cov = _json(COVERAGE)
    decls = sources()
    conn = _json(CONNECTIVITY)
    chapter = (ROOT / CHAPTER).read_text()
    record_ids = {p.stem for p in (ROOT / RECORDS).glob('*.json')}
    errors = validate(cov, decls, record_ids)
    if errors:
        return {'errors': errors}
    f3, used = k3(cov, decls)
    fx, forms, kept = exchange_forms(cov, decls)
    f3 = f3 + fx
    f4, tags = k4(cov, decls)
    f5, params = k5(cov, decls, chapter)
    f6, links, normative = k6(cov, decls)
    f7, items = k7(cov, chapter)
    criteria = {
        'K1': k1(cov, decls, conn), 'K2': k2(cov, decls, conn), 'K3': f3, 'K4': f4, 'K5': f5, 'K6': f6, 'K7': f7,
    }
    receipt = _json(RECEIPT)
    return {
        'errors': [],
        'receipt': receipt.get('utc'), 'connectivity_commit': conn.get('commit'),
        'connectivity_receipt': conn.get('core_receipt_at_commit'),
        'met': {k: not v for k, v in criteria.items()}, 'findings': criteria,
        'rows': cov['rows'], 'natural_number_laws': cov['representation']['natural_number_laws'], 'premises_used': used, 'exchange_forms': forms, 'exchange_kept': kept, 'exchange_reading': cov['premises'].get('reading'), 'logical_premises': [p for p in cov['premises']['items'] if p.get('kind') == 'logical'], 'modelling': tags, 'parameters': params,
        'chain_start': cov['ethics_chain']['steps'][0], 'chain': links, 'normative_hypotheses': normative, 'open_items': items,
        'master_laws': {'laws': cov['master_laws'], 'measured': conn.get('master_laws')} if cov.get('master_laws') else None,
    }


