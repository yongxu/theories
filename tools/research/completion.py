def render() -> tuple[dict, list[str]]:
    """Pages to write and errors, for research.py render and check."""
    result = evaluate()
    if result['errors']:
        return {}, ['completion criterion: ' + e for e in result['errors']]
    return {REPORT: render_report(result)}, []


