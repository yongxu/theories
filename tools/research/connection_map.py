def _en(value):
    return registry.en(value) if value else None


def _home_of(graph: dict) -> dict:
    """Each record's home sections, from the graph's `states` edges."""
    homes = {}
    for e in graph['edges']:
        if e['type'] == 'states':
            homes.setdefault(e['to'].removeprefix('result:'), []).append(e['from'].removeprefix('section:'))
    return {k: sorted(v) for k, v in homes.items()}


def _warp_of(path: str) -> str | None:
    if path.startswith(REVIEW):
        return 'review'
    return next((i for i, p, _ in WARP if p == path), None)


def _record_of_anchor(anchor: str | None, results: dict) -> str | None:
    """The record an anchor states: a home anchor `r-<id>`, or a link to the record's own page."""
    if not anchor:
        return None
    path, _, mark = anchor.partition('#')
    if mark.startswith('r-') and mark[2:] in results:
        return mark[2:]
    if path.startswith(atlas_tool.RECORDS + '/'):
        stem = Path(path).stem
        return stem if stem in results else None
    return None


def _section_title(anchor: str) -> str:
    """A section's name, for a target that is a section and no record: the heading at its anchor, or the first words after
    it, else the anchor."""
    path, _, mark = anchor.partition('#')
    file = ROOT / path
    fallback = f'{Path(path).name}#{mark}' if mark else Path(path).name
    if not mark or not file.is_file():
        return fallback
    lines = file.read_text(encoding='utf-8').splitlines()
    for n, line in enumerate(lines):
        heading = re.match(r'#{1,6}\s+(.+?)\s*$', line)
        if f'<a id="{mark}"' in line or (heading and reading_catalogue.slug(heading.group(1)) == mark):
            rest = (heading.group(1) if heading else next((x for x in lines[n + 1:n + 4] if x.strip()), ''))
            words = re.sub(r'\*\*|`|\[|\]\([^)]*\)|<[^>]+>|^#+\s*', '', rest).strip()
            return (words[:90].rsplit(' ', 1)[0] + '…') if len(words) > 90 else (words or fallback)
    return fallback


def _entry(e: dict, homes: dict, results: dict) -> dict:
    targets, warps = [], []
    for t in e['targets']:
        record = t.get('record') or _record_of_anchor(t.get('anchor'), results)
        paths = [t['anchor'].partition('#')[0]] if t.get('anchor') else []
        if not paths or paths[0].startswith(atlas_tool.RECORDS + '/'):
            paths = [h.partition('#')[0] for h in homes.get(record, [])]
        found = [w for w in (_warp_of(p) for p in paths) if w]
        node = results.get(record) or {}
        targets.append({'record': record, 'anchor': t.get('anchor') or (homes.get(record) or [None])[0], 'says': _en(t['says']),
                        'status': node.get('status'), 'kind': node.get('kind'), 'title': node.get('title'), 'role': t['role'], 'part': t.get('part')})
        if t['role'] == CARRIES:
            warps += found
    source = e['source']
    return {'id': e['id'], 'name': _en(e['name']), 'group': e['group'], 'carried': e['carried'], 'relation': e['relation'],
            'agreement_of': e['agreement_of'], 'same_as': e['same_as'], 'sense': _en(e['sense']), 'quote': e['quote'], 'reading': _en(e['reading']), 'work': source['work'],
            'locator': source['locator'], 'basis': source['basis'], 'account_adds': _en(e['account_adds']),
            'source_adds': _en(e['source_adds']), 'searched': (e['absence'] or {}).get('searched'),
            'read': (e['absence'] or {}).get('read'), 'targets': targets, 'warps': sorted(set(warps))}


def _meeting_points(entries: list, results: dict) -> tuple[list, int]:
    """Where readings of more than one group meet: the same record or section, each read against it apart. Returns those
    and how many targets were read by one group only, so what is left out is counted."""
    points = {}
    for e in entries:
        if e['carried'] in ABSENT:
            continue
        for t in e['targets']:
            key = t['record'] or t['anchor']
            if not key or t['role'] != CARRIES:
                continue
            p = points.setdefault(key, {'key': key, 'title': t['title'] or _section_title(key), 'status': t['status'], 'kind': t['kind'],
                                        'anchor': t['anchor'], 'readings': []})
            p['readings'].append({'entry': e['id'], 'group': e['group'], 'relation': e['relation'], 'says': t['says']})
    shared, single = [], 0
    for p in points.values():
        groups = {r['group'] for r in p['readings']}
        if len(groups) < 2:
            single += 1
            continue
        p['groups'] = len(groups)
        p['differ'] = len({r['relation'] for r in p['readings']}) > 1
        shared.append(p)
    shared.sort(key=lambda p: (-p['groups'], not p['differ'], p['key']))
    return shared, single


def _distinct(entries: list) -> int:
    """How many claims the entries state, an entry and what it is `same_as` counting once."""
    parent = {e['id']: e['id'] for e in entries}

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    for e in entries:
        for other in e['same_as'] or []:
            if other in parent:
                parent[find(e['id'])] = find(other)
    return len({find(e['id']) for e in entries})


def _bars(rows: tuple, counts: dict) -> list[dict]:
    return [{'key': k, 'label': label, 'gloss': gloss, 'n': counts.get(k, 0)} for k, label, gloss in rows if counts.get(k, 0)]


def payload(atlas: dict, graph: dict, shared: dict, base: str | None = BASE) -> dict:
    """What the page reads, computed once here so that the page's script only draws."""
    results = {n['record']: n for n in graph['nodes'] if n['type'] == 'result'}
    homes = _home_of(graph)
    entries = [_entry(e, homes, results) for e in atlas['correspondences']]
    groups = []
    for g in atlas['correspondence_groups']:
        held = [e for e in entries if e['group'] == g['id']]
        groups.append({'id': g['id'], 'title': _en(g['title']), 'domain': g['domain'], 'kind': g['kind'], 'summary': _en(g['summary']),
                       'side': 'folders' if g['domain'] == atlas_tool.EARLIER else 'domains', 'read': g['read'], 'skimmed': g['skimmed'],
                       'searched': g['searched'], 'not_mapped': g['not_mapped'], 'coverage': g['coverage'], 'n': len(held),
                       'loose': sum(e['carried'] in ABSENT for e in held), 'by_carried': g['by_carried'], 'by_relation': g['by_relation'],
                       'by_agreement_of': g['by_agreement_of'],
                       'from_knowledge': sum(e['basis'] == 'ai-knowledge' for e in held)})
    used = Counter(w for e in entries if e['carried'] not in ABSENT for w in e['warps'])
    warp = [{'id': i, 'path': p, 'title': t, 'n': used[i]} for i, p, t in WARP if used[i]]
    if used['review']:
        warp.append({'id': 'review', 'path': REVIEW + 'README.md', 'title': 'Review dossiers', 'n': used['review']})
    points, single = _meeting_points(entries, results)
    by_type = Counter(n['type'] for n in graph['nodes'])
    edges = Counter(e['type'] for e in graph['edges'])
    boundary, reach = shared['boundary'], shared['central_reach']['counts']
    standings = [{'title': title, 'n': boundary['groups'].get(key, 0), 'rows': _bars(rows, boundary['counts'])} for title, key, rows in STANDINGS
                 if boundary['groups'].get(key, 0)]
    carried = Counter(e['carried'] for e in entries)
    relation = Counter(e['relation'] for e in entries if e['relation'] and e['carried'] not in ABSENT)
    agreement_of = Counter(e['agreement_of'] for e in entries if e['agreement_of'] and e['carried'] not in ABSENT)
    return {'base': base, 'entries': entries, 'groups': groups, 'warp': warp, 'points': points, 'single': single,
            'relations': atlas['vocabulary']['relations'], 'carried': atlas['vocabulary']['carried'],
            'totals': {'entries': len(entries), 'folders': sum(g['side'] == 'folders' for g in groups),
                       'domains': sum(g['side'] == 'domains' for g in groups), 'carried': dict(carried), 'relation': dict(relation),
                       'agreement_of': dict(agreement_of), 'distinct': _distinct(entries),
                       'loose': sum(carried[k] for k in ABSENT), 'from_knowledge': sum(e['basis'] == 'ai-knowledge' for e in entries),
                       'unwarped': sum(1 for e in entries if e['carried'] not in ABSENT and not e['warps'])},
            'standings': standings, 'declarations': sum(g['n'] for g in standings), 'reach': _bars(REACH, reach),
            'corpus': theory_graph.corpus_counts(graph), 'nodes': dict(by_type), 'edges': dict(edges),
            'dynamics': len(atlas['dynamics']), 'checks': atlas.get('crosswalk_checks')}


def _blob(data: dict) -> str:
    """The data as text safe inside a script element (no `<` at all, so neither `</script` nor `<!--` can end or
    change it), and safe from the render's link check, which reads every `](`."""
    return json.dumps(data, ensure_ascii=False, separators=(',', ':')).replace('<', '\\u003c').replace('](', ']\\u0028')


def _body(data: dict) -> str:
    return f'{BODY}\n<script type="application/json" id="cx-data">{_blob(data)}</script>\n<script>{SCRIPT}</script>\n'


def fragment(data: dict) -> str:
    """The page without a document skeleton, for a host that supplies one."""
    return f'<title>{TITLE}</title>\n<meta name="claude:viewport-fit-sides" content="cover">\n<style>{CSS}</style>\n{_body(data)}'


def page(data: dict) -> str:
    """The whole document: its title and style in its head."""
    return ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
            f'<meta name="viewport" content="width=device-width, initial-scale=1">\n<title>{TITLE}</title>\n{GENERATED}\n'
            f'<style>{CSS}</style>\n</head>\n<body>\n{_body(data)}</body>\n</html>\n')


def site_map(out_dir: str | Path, link_base: str, site_paths: dict[str, str] | None = None) -> Path:
    """Write OUT_DIR/map.html for a site and return its path. A link that leaves the map goes to `link_base` followed by
    the repository path, `link_base` ending in / (a permalink prefix such as https://github.com/<owner>/<repo>/blob/<sha>/,
    or a relative path to a copy of the repository); a repository path in `site_paths` goes instead to the URL the site
    gives it (relative to map.html, or absolute), the link's #anchor kept. The page reads the atlas's, the graph's and
    the shared laws' data as rendered in this checkout, so a site is built after a render."""
    if not isinstance(link_base, str) or not link_base.endswith('/'):
        raise ValueError(f'link_base must be a string ending in /: {link_base!r}')
    bad = [k for k, v in (site_paths or {}).items() if not isinstance(k, str) or '#' in k or not isinstance(v, str)]
    if bad:
        raise ValueError(f'site_paths maps repository paths, without #anchor, to URL strings: {bad[:3]!r}')
    atlas_data = json.loads((ROOT / atlas_tool.DATA).read_text(encoding='utf-8'))
    graph = json.loads((ROOT / theory_graph.GRAPH).read_text(encoding='utf-8'))
    data = payload(atlas_data, graph, _shared(), base=link_base)
    data['site'] = dict(sorted((site_paths or {}).items()))
    out = Path(out_dir) / 'map.html'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(page(data), encoding='utf-8')
    return out


def _shared() -> dict:
    return json.loads((ROOT / registry.SHARED_LAWS).read_text(encoding='utf-8'))


def render(atlas_json: str, graph_json: str) -> dict:
    return {PAGE: page(payload(json.loads(atlas_json), json.loads(graph_json), _shared()))}


