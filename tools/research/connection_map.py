    from tools.research import spine
    data = payload(json.loads(atlas_json), json.loads(graph_json), _shared(), bases=spine.edge_bases())
    out = {PAGE: page(data), OVERVIEW: overview_svg(data), OVERVIEW_ZH: overview_svg(data, 'zh')}
