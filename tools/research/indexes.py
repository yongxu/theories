    ('Reviews', lambda n: 'REVIEW' in n and n.endswith('.md')),
    ('Plans', lambda n: 'PLAN' in n and n.endswith('.md')),
    ('Integrations', lambda n: n.endswith('-INTEGRATION.md')),
