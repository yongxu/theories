"""Generated directory indexes: chapters, studies, the root-foundation study, sources, directives.

`research.py render` writes these pages through the guarded writer (navigation.write_views), so
they carry a "Generated by" header, an entry in the generated manifest and the same overwrite
guard as the other views. Every page is read off the repository as it stands: the files on
disk, the move receipts, the canonical chapter's table of where the earlier chapters stand and
the directive register. Nothing here edits a source, and nothing inside `sources/` is written
except `sources/README.md`.

A page that existed as hand-written prose before it became generated is adopted only when its
bytes equal the sha256 recorded under `indexes.adopted_pages` in the research config (its prose
was read and carried into the generator); any other existing bytes stop the render as an
unincorporated edit.
"""
