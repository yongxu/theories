def studies_index(root: Path = ROOT, planned: frozenset = frozenset()) -> str:
    page = STUDIES + '/README.md'
    files = files_under(STUDIES, root)
    live = [p for p in files if path_roles.role(p) in ('live', 'generated', 'evidence') and p != page]
    history = [p for p in files if path_roles.role(p) == 'history']
    lines = ['# Research studies', '', marker('Edit the studies, not this page.'), '', *[x for p in STUDIES_LEAD for x in (p, '')],
             '## Live studies', '',
             'Live counts every file outside a `history/` folder, frozen run evidence included; history is listed separately below.', '',
             '| Study | Entry | Live files | Parts | History files |', '|---|---|---:|---|---:|']
    tops = sorted({p.split('/')[2] for p in files if p.count('/') >= 3})
    unentered = []
    for top in tops:
        base = f'{STUDIES}/{top}'
        mine = [p for p in live if p.startswith(base + '/')]
        old = [p for p in history if p.startswith(base + '/')]
        parts = sorted({p.split('/')[3] for p in mine if p.count('/') >= 4 and p.split('/')[3] != 'history'})
        entry = next((e for e in (base + '/README.md', base + '/INDEX.md') if (root / e).exists()), None)
        entry_cell = link(entry, page, title(entry, root) or 'README') if entry else '—'
        part_cells = []
        for part in parts:
            sub = f'{base}/{part}'
            sub_entry = next((e for e in (sub + '/INDEX.md', sub + '/README.md') if (root / e).exists() or e in planned), None)
            label = f'{part}/ ({sum(p.startswith(sub + "/") for p in mine)})'
            part_cells.append(link(sub_entry, page, label) if sub_entry else f'`{label}`')
        lines.append(f'| `{top}/` | {entry_cell} | {len(mine)} | {" · ".join(part_cells) or "—"} | {len(old)} |')
        if not entry:
            docs = [p for p in mine if p.count('/') == 3 and p.endswith('.md')]
            unentered.append((top, docs))
    for top, docs in unentered:
        if docs:
            lines += ['', f'### {top}', '', 'No README; its top-level documents:', '']
            lines += [f'- {link(d, page, Path(d).name)}: {cell(title(d, root))}' for d in docs]
    folders = sorted({re.match(r'(.*?/history)(/|$)', p).group(1) for p in history})
    lines += ['', '## History', '',
              'Retired study material, bytes unchanged. Each history folder has a `MANIFEST.json` (written by the move tool) where the move receipts created it; read its entries for the reason and former path of each file.', '',
              '| History folder | Files | Manifest |', '|---|---:|---|']
    for folder in folders:
        count = sum(p.startswith(folder + '/') for p in history)
        manifest = next((m for m in (folder + '/MANIFEST.json', folder + '/INDEX.md') if (root / m).exists()), None)
        lines.append(f'| `{folder[len(STUDIES) + 1:]}/` | {count} | ' + (link(manifest, page, Path(manifest).name) if manifest else '—') + ' |')
    retired = files_under('_process/history', root)
    if retired:
        groups = Counter(p.split('/')[2] for p in retired if p.count('/') >= 3)
        lines += ['', 'Studies retired as a whole are under [`_process/history/`](../history/):', '',
                  '| Retired folder | Files |', '|---|---:|']
        lines += [f'| `{name}/` | {n} |' for name, n in sorted(groups.items())]
    lines += ['', 'Rerun `make research-render` after a study is added or a batch moved to history.', '']
    return '\n'.join(lines)


