def reader_list(root: Path = ROOT) -> list[str]:
    """The eight chapters as a reader meets them: in reading order, each by its title, what it covers (the theory graph's
    region of its results), how many results it states and its reading time (RW, 8 November 2026)."""
    from tools.research import navigation, theory_graph
    lines = ['## The eight chapters', '', 'In reading order; the numbering is for reading, not an order of proof.', '',
             '| | Chapter | What its results concern | Results stated | Reading time |', '|---|---|---|---|---|']
    for k, (name, region) in enumerate(READING_ORDER, 1):
        f = root / CHAPTERS / name
        if not f.is_file():
            continue
        text = f.read_text()
        t = title(CHAPTERS + '/' + name, root) + (' (the classical texts: what they read out, how it is tested and where they '
                                                   'diverge; in Chinese)' if name.startswith('06-') else '')
        # a result is a record anchored at its home; a chapter also keeps the anchors of former record names, so that
        # old links resolve, and those are not counted (the theory graph's regions count the same records)
        stated = len({a for a in re.findall(r'<a id="r-([^"]+)"', text) if (root / RECORDS / f'{a}.json').is_file()})
        lines.append(f'| {k} | [{cell(t)}]({name}) | {cell(theory_graph.REGION_TITLES[region])} | {stated} | '
                     f'{navigation.reading_time(text)} |')
    return lines + ['']


def chapters_index(root: Path = ROOT, generated: set[str] | None = None) -> str:
    page = CHAPTERS + '/README.md'
    generated = set() if generated is None else generated
    table = chapter_table(root)
    names = sorted(p.name for p in (root / CHAPTERS).glob('*.md') if p.name != 'README.md')
    order = {'canonical': 0, 'chapter': 0, 'reference': 1, 'kept': 2, 'generated': 3, 'Chinese edition': 4}
    rows = []
    for name in names:
        status, note = chapter_status(name, table, generated)
        rows.append((order[status], name, status, table.get(name, ('', ''))[0] if status not in ('canonical', 'chapter') else status.capitalize(), note))
    counts = Counter(r[2] for r in rows)
    from tools.research import navigation
    lines = ['# Chapters of the Theory of Becoming', '', marker('Edit the chapters or the move receipts, not this page.'), '',
             navigation.nav_line(page), '',
             f'The [overview](../THE-THEORY-OF-BECOMING.md) states the theory in one account, and [the one page](../ONE-PAGE.md) in a page. The eight numbered chapters below state every result once, in its home section, anchored by its record id; [the theory graph](../results/THEORY-GRAPH.md) joins sections, results, Lean modules and texts. The chapters they replace are in history (below), bytes unchanged.', '',
             ] + reader_list(root) + [
             'Status: **chapter** is one of the eight chapters of the theory; **canonical** is the entry that states the theory; **reference** keeps material moved out of a chapter; **kept** is a live chapter kept at its own scope; **generated** is written by `make research-render`; **Chinese edition** is a `NAME.zh.md` split from a bilingual original, not maintained in step with the English file, which governs.', '',
             '## Files in this directory', '',
             ', '.join(f'{counts[k]} {k}' for k in sorted(counts, key=lambda k: order[k])) + '.', '',
             '| File | Title | Status | Role | Note |', '|---|---|---|---|---|']
    for _, name, status, kind, note in sorted(rows):
        lines.append(f'| [{name}]({name}) | {cell(title(CHAPTERS + "/" + name, root))} | {status} | {cell(kind) or "—"} | {cell(note)} |')
    moved = moved_chapters(root)
    lines += ['', '## Chapters moved to history', '',
              f'{len(moved)} files that were in this directory were moved, bytes unchanged, by the move receipts in [`_process/architecture/moves/`](../../../_process/architecture/moves/). Each is kept at its original scope as a record of argument; the receipts give the reason per batch.', '']
    reasons = defaultdict(list)
    for item in moved:
        reasons[(item['batch'], item['reason'])].append(item)
    for (batch, reason), items in sorted(reasons.items()):
        lines += [f'**{batch}** ({len(items)} file{"s" if len(items) != 1 else ""}): {cell(reason)}', '']
    lines += ['| Former path | Now at | Batch |', '|---|---|---|']
    for item in moved:
        former = item['old'][len(CHAPTERS) + 1:]
        now = item['now']
        lines.append(f'| `{former}` | ' + (link(now, page, now.split('theories/becoming/')[-1]) if (root / now).exists() else f'`{now}` (not present)') + f' | {item["batch"]} |')
    lines += ['', 'Rerun `make research-render` after a chapter is added, split or moved.', '']
    return '\n'.join(lines)


def receipts(root: Path = ROOT) -> list[tuple[str, dict]]:
    out = []
    for path in moves.receipt_files(root):
        try:
            data = json.loads(path.read_text())
        except (OSError, ValueError):
            continue
        if isinstance(data, dict):
            out.append((data.get('batch') or path.stem, data))
    return out


def moved_chapters(root: Path = ROOT) -> list[dict]:
    items = []
    for batch, data in receipts(root):
        for f in data.get('files', []):
            old, new = f.get('old_path', ''), f.get('new_path', '')
            if old.startswith(CHAPTERS + '/') and not (root / old).exists():
                now = moves.later_path(old, root) or new
                items.append({'old': old, 'now': now, 'batch': batch, 'reason': f.get('reason', '')})
    return sorted(items, key=lambda x: x['old'])


