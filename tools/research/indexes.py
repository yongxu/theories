KIND_RULES = [
    ('correction', r'correct|redirect|objection|critic|not right|wrong|纠正'),
    ('decision', r'decision|decid|choice|chose|select|fold|approv|agree|\bgo\b|confirm|accept|opt'),
    ('clarification', r'clarif|explan|meaning|reading|answer'),
    ('question', r'question|\bwhy\b|whether|\?'),
    ('direction', r'instruction|direct|request|priority|goal|plan|continu|next|proceed|scope|aim|start|focus'),
    ('assessment', r'assessment|review|comparison|soundness|audit|analysis|evaluation'),
    ('conversation', r'conversation|session|exchange|founding|export|takeover|transcript|chat'),
]


def kind_of(text: str) -> str:
    low = text.lower()
    return next((kind for kind, pattern in KIND_RULES if re.search(pattern, low)), 'record')


def register_labels(root: Path = ROOT) -> dict[str, str]:
    """Source path -> link text of its entry in the directive register."""
    out = {}
    try:
        body = (root / DIRECTIVE_REGISTER).read_text()
    except OSError:
        return out
    base = (root / DIRECTIVE_REGISTER).parent
    for m in re.finditer(r'\[([^\]\n]+)\]\((\.\./sources/[^)#\s]+)(?:#[^)\s]*)?\)', body):
        path = os.path.normpath(base / m.group(2))
        rel = os.path.relpath(path, root)
        out.setdefault(rel, m.group(1))
    return out


def directive_records(root: Path = ROOT) -> list[dict]:
    labels = register_labels(root)
    groups = sorted(p.name for p in (root / SOURCES).iterdir() if p.is_dir() and any(('sources/' + p.name).startswith(g) for g in DIRECTIVE_GROUPS))
    out = []
    for g in groups:
        for p in files_under(f'{SOURCES}/{g}', root):
            name = Path(p).name
            if name.startswith('.'):
                continue
            head = title(p, root) if p.endswith('.md') else ''
            label = labels.get(p)
            attachment = p.count('/') > 2
            kind = 'attachment' if attachment else kind_of(label.removeprefix("Ren's ") if label else name + ' ' + head)
            out.append({'path': p, 'group': g, 'date': date_of(name) or date_of(p.split('/')[2]), 'title': head or name,
                        'kind': kind, 'register': label})
    return sorted(out, key=lambda r: (r['date'] or '0000', r['path']))


def directive_index(root: Path = ROOT) -> str:
    page = DIRECTIVE_INDEX
    rows = directive_records(root)
    kinds = Counter(r['kind'] for r in rows)
    lines = ['# Directive index', '', marker('Edit the source records or the directive register, not this page.'), '',
             f'Every record in the directive groups {", ".join("`" + g.split("/")[1] + "*`" for g in DIRECTIVE_GROUPS)} of [sources](../sources/README.md): {len(rows)} files, newest first. The [directive register](RESEARCH-DIRECTIVES.md) curates the authorizations among them and is incomplete; read the record itself when an authorization matters. The records keep Ren\'s words verbatim; an AI-authored section is labelled, its earlier text in git history.', '',
             '**Kind** is a heuristic read from the register entry\'s wording where the register lists the record, else from the file name and title: ' + ', '.join(f'{k} {n}' for k, n in kinds.most_common()) + '. It is a finding aid, not a reading of the record; who said what is settled only by the record.', '',
             '| Date | Record | Kind | Title | In register |', '|---|---|---|---|---|']
    for r in reversed(rows):
        name = r['path'].split('/', 2)[2]
        lines.append(f'| {r["date"]} | {link(r["path"], page, name)} | {r["kind"]} | {cell(r["title"])} | {"yes" if r["register"] else ""} |')
    lines.append('')
    return '\n'.join(lines)


