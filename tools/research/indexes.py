def render(root: Path = ROOT, generated: set[str] | None = None) -> dict[str, str]:
    """Repository path -> page body for every index."""
    _INVENTORY.pop(str(root), None)
    if generated is None:
        manifest = root / '_process/architecture/generated-manifest.json'
        try:
            generated = set(json.loads(manifest.read_text()).get('files', {}))
        except (OSError, ValueError):
            generated = set()
    return {
        CHAPTERS + '/README.md': chapters_index(root, generated),
        STUDIES + '/README.md': studies_index(root, frozenset({ROOT_FOUNDATION + '/INDEX.md'})),
        ROOT_FOUNDATION + '/INDEX.md': root_foundation_index(root),
        ROOT_FOUNDATION + '/REVIEWS.md': reviews_ledger(root),
        SOURCES + '/README.md': sources_readme(root),
        DIRECTIVE_INDEX: directive_index(root),
    }


def adopted(root: Path = ROOT) -> dict[str, str]:
    """Hand-written pages whose reviewed bytes the generator replaces: path -> sha256 (config
    `indexes.adopted_pages`). Passed to the guarded writer as the expected prior version."""
    pages = config(root).get('adopted_pages', {})
    return {p: h for p, h in pages.items() if isinstance(p, str) and isinstance(h, str)} if isinstance(pages, dict) else {}
