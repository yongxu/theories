def stated_date(path: str, root: Path = ROOT) -> str:
    """The first date a document states in its opening lines (`17 October 2026`, `2026-10-17` or `2026年10月17日`)."""
    months = 'January February March April May June July August September October November December'.split()
    try:
        head = '\n'.join((root / path).read_text(errors='replace').splitlines()[:25])
    except OSError:
        return ''
    m = re.search(r'\b(20\d\d)-(\d\d)-(\d\d)\b|\b(\d{1,2}) (' + '|'.join(months) + r') (20\d\d)\b'
                  r'|(20\d\d)年(\d{1,2})月(\d{1,2})日', head)
    if not m:
        return ''
    if m.group(1):
        return '-'.join(m.group(1, 2, 3))
    if m.group(7):
        return f'{m.group(7)}-{int(m.group(8)):02d}-{int(m.group(9)):02d}'
    return f'{m.group(6)}-{months.index(m.group(5)) + 1:02d}-{int(m.group(4)):02d}'


def root_foundation_files(root: Path = ROOT) -> tuple[list[str], list[str]]:
    """(top-level files, subdirectories) of the root-foundation study, scratch excluded."""
    files = files_under(ROOT_FOUNDATION, root)
    top = [p for p in files if p.count('/') == ROOT_FOUNDATION.count('/') + 1]
    subdirs = sorted({p.split('/')[ROOT_FOUNDATION.count('/') + 1] for p in files if p.count('/') > ROOT_FOUNDATION.count('/') + 1})
    return top, subdirs


def root_foundation_index(root: Path = ROOT) -> str:
    page = ROOT_FOUNDATION + '/INDEX.md'
    top, subdirs = root_foundation_files(root)
    names = {Path(p).name for p in top}
    skip = {'INDEX.md', 'REVIEWS.md'}
    groups = defaultdict(list)
    for p in top:
        name = Path(p).name
        if name in skip or (name.endswith('.zh.md') and name[:-6] + '.md' in names):
            continue
        kind = next(k for k, test in ROOT_KINDS if test(name))
        groups[kind].append(p)
    lines = ['# Root-foundation study: file index', '', marker('Edit the study files, not this page.'), '',
             f'Every file of the study, by kind. The study\'s [overview](README.md) is the generated navigation page; the [review ledger](REVIEWS.md) lists the reviews with their dates. A Chinese edition (`NAME.zh.md`) is linked beside its English file. {len(top)} files at the top level; subfolders are listed at the end.', '']
    for kind, _ in ROOT_KINDS:
        items = groups.get(kind)
        if not items:
            continue
        lines += [f'## {kind}', '']
        if kind.endswith('(JSON)') or kind == 'Scripts' or kind == 'Other files':
            lines += [' · '.join(link(p, page, Path(p).name) for p in items), '']
            continue
        lines += ['| File | Title |', '|---|---|']
        for p in items:
            name = Path(p).name
            zh = name[:-3] + '.zh.md'
            extra = f' · [Chinese edition]({zh})' if zh in names else ''
            lines.append(f'| [{name}]({name}){extra} | {cell(title(p, root))} |')
        lines.append('')
    if subdirs:
        lines += ['## Subfolders', '', '| Folder | Files |', '|---|---:|']
        files = files_under(ROOT_FOUNDATION, root)
        for d in subdirs:
            lines.append(f'| `{d}/` | {sum(p.startswith(ROOT_FOUNDATION + "/" + d + "/") for p in files)} |')
        lines.append('')
    lines += ['Retired files of this study are in [its history folder](../history/root-foundation/) (manifest there).', ''] if (root / ROOT_FOUNDATION).parent.joinpath('history/root-foundation').exists() else []
    return '\n'.join(lines)


def reviews_ledger(root: Path = ROOT) -> str:
    page = ROOT_FOUNDATION + '/REVIEWS.md'
    top, _ = root_foundation_files(root)
    names = {Path(p).name for p in top}
    reviews = [p for p in top if 'REVIEW' in Path(p).name and p.endswith('.md') and not p.endswith('.zh.md') and Path(p).name != 'REVIEWS.md']
    history_dir = Path(ROOT_FOUNDATION).parent / 'history' / 'root-foundation'
    old = [p for p in files_under(str(history_dir), root) if 'REVIEW' in Path(p).name and p.endswith('.md') and not p.endswith('.zh.md')]
    rows = sorted(((stated_date(p, root), p) for p in reviews), key=lambda x: (x[0] or '9999', x[1]))
    lines = ['# Root-foundation study: review ledger', '', marker('Edit the reviews, not this page.'), '',
             'The reviews of this study, by the date each states in its opening lines (blank where none is stated). A review is evidence about the work it reviews; repeated reviews are not further results. See the [file index](INDEX.md) for the rest of the study.', '',
             '| Date | Review | Title |', '|---|---|---|']
    for date, p in rows:
        name = Path(p).name
        zh = name[:-3] + '.zh.md'
        extra = f' · [Chinese edition]({zh})' if zh in names else ''
        lines.append(f'| {date} | [{name}]({name}){extra} | {cell(title(p, root))} |')
    if old:
        lines += ['', '## Reviews kept in history', '', f'{len(old)} earlier reviews were moved, bytes unchanged, to the study\'s history folder:', '',
                  '| Date | Review | Title |', '|---|---|---|']
        for date, p in sorted(((stated_date(p, root), p) for p in old), key=lambda x: (x[0] or '9999', x[1])):
            lines.append(f'| {date} | {link(p, page, Path(p).name)} | {cell(title(p, root))} |')
    lines.append('')
    return '\n'.join(lines)


