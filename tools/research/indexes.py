def source_groups(root: Path = ROOT) -> list[dict]:
    """Every directory directly under sources/, with a number alias: a number two groups share
    gets a / b in name order (15a, 15b; 32a, 32b; 36a, 36b)."""
    dirs = sorted(p.name for p in (root / SOURCES).iterdir() if p.is_dir() and not p.name.startswith('.') and p.name != '__pycache__')
    numbers = Counter(re.match(r'(\d+)-', d).group(1) for d in dirs if re.match(r'\d+-', d))
    seen = Counter()
    files = files_under(SOURCES, root)
    out = []
    for d in dirs:
        m = re.match(r'(\d+)-', d)
        alias = ''
        if m:
            n = m.group(1)
            alias = n + ('abcdefgh'[seen[n]] if numbers[n] > 1 else '')
            seen[n] += 1
        mine = [p for p in files if p.startswith(f'{SOURCES}/{d}/')]
        readme = f'{SOURCES}/{d}/README.md'
        out.append({'dir': d, 'alias': alias, 'files': len(mine), 'readme': readme if (root / readme).exists() else None,
                    'title': title(readme, root) if (root / readme).exists() else '',
                    'dates': sorted({date_of(Path(p).name) for p in mine if date_of(Path(p).name)})})
    return out


def sources_readme(root: Path = ROOT) -> str:
    page = SOURCES + '/README.md'
    groups = source_groups(root)
    numbered_groups = [g for g in groups if g['alias']]
    named = [g for g in groups if not g['alias']]
    lines = ['# Sources', '', marker('Ren\'s words and the imported originals in sources/ are kept verbatim, AI-authored sections labelled; this page is the only generated file here.'), '',
             'Original material and its provenance: Ren\'s writings and directions, exported conversations, imported papers and data. Ren\'s words and the imported originals here are kept verbatim and are never moved; an AI-authored section of a record is labelled, and is changed only where it would mislead the next reader, its earlier text kept in git history; corrections and readings live in the studies and theory chapters that cite them. The hand-kept [provenance manifest](SOURCES.md) records each import with its scope; the [directive index](../_process/DIRECTIVE-INDEX.md) lists the directive records of groups 15 and 16, and the [directive register](../_process/RESEARCH-DIRECTIVES.md) curates the authorizations among them.', '',
             f'{len(groups)} groups: {len(numbered_groups)} numbered and {len(named)} named by subject. Where two numbered groups share a number, the alias adds a letter in name order.', '',
             '## Numbered groups', '', '| Alias | Group | Description | Files | Dated files |', '|---|---|---|---:|---|']
    for g in numbered_groups + [None] + named:
        if g is None:
            lines += ['', '## Groups named by subject', '', '| Group | Description | Files | Dated files |', '|---|---|---:|---|']
            continue
        target = g['readme'] or f'{SOURCES}/{g["dir"]}'
        label = link(target, page, g['dir'] + '/') if g['readme'] else f'`{g["dir"]}/`'
        span = (g['dates'][0] + (' to ' + g['dates'][-1] if g['dates'][-1] != g['dates'][0] else '')) if g['dates'] else ''
        row = f'| {label} | {cell(g["title"]) or "—"} | {g["files"]} | {span} |'
        lines.append((f'| {g["alias"]} ' if g['alias'] else '') + row)
    lines += ['', 'Descriptions are the first heading of each group\'s README, where it has one. Rerun `make research-render` after an import.', '']
    return '\n'.join(lines)


