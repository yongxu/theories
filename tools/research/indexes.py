def marker(what: str) -> str:
    return f'<!-- Generated by tools/research/research.py render (tools/research/indexes.py). {what} -->'


# ------------------------------------------------------------------ helpers

def config(root: Path = ROOT) -> dict:
    data = path_roles.load_config(root).get('indexes')
    return data if isinstance(data, dict) else {}


_INVENTORY: dict = {}


def inventory(root: Path = ROOT) -> list[str]:
    """Tracked and untracked (not ignored) files, read once per render (see `render`)."""
    if str(root) not in _INVENTORY:
        _INVENTORY[str(root)] = moves.inventory(root)
    return _INVENTORY[str(root)]


def files_under(prefix: str, root: Path = ROOT) -> list[str]:
    """Tracked and untracked (not ignored) files below `prefix`, scratch excluded."""
    found = [p for p in inventory(root) if p.startswith(prefix.rstrip('/') + '/')]
    return sorted(p for p in found if (root / p).is_file() and path_roles.role(p) != 'scratch')


def link(target: str, page: str, label: str) -> str:
    path, sep, fragment = target.partition('#')
    rel = os.path.relpath(ROOT / path, (ROOT / page).parent)
    rel = rel + sep + fragment
    return f'[{cell(label)}](<{rel}>)' if ' ' in rel else f'[{cell(label)}]({rel})'


def cell(text: str) -> str:
    return str(text).replace('|', '\\|').replace('\n', ' ').strip()


def title(path: str, root: Path = ROOT) -> str:
    """The first `# ` heading of a Markdown file, in English where it is a 'Chinese / English' pair."""
    try:
        with (root / path).open(encoding='utf-8', errors='replace') as stream:
            for n, line in enumerate(stream):
                if line.startswith('# '):
                    text = re.sub(r'<[^>]+>', '', line[2:]).strip()
                    return english(text)
                if n > 40:
                    break
    except OSError:
        pass
    return ''


def date_of(name: str) -> str:
    m = re.match(r'(\d{4}-\d{2}-\d{2})', name)
    return m.group(1) if m else ''


def edition(path: str) -> str | None:
    """`NAME.md` for a Chinese edition `NAME.zh.md`."""
    return path[:-len('.zh.md')] + '.md' if path.endswith('.zh.md') else None


