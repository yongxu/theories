def discover(glob: str) -> list[str]:
    command = ["rg", "--files", "--hidden", "--no-ignore", "-0", "-g", glob]
    for directory in EXCLUDED:
        command += ["-g", f"!**/{directory}/**"]
    result = subprocess.run(command, cwd=ROOT, check=True, capture_output=True)
    return sorted(x.decode("utf-8") for x in result.stdout.split(b"\0") if x)


SCRUB_NEXT = {"code": re.compile(r'/-|--|"'), "comment": re.compile(r"/-|-/"), "string": re.compile(r'\\|"')}


def scrub(source: str) -> str:
    """Blank nested comments and strings while retaining offsets and line breaks."""
    out = []
    i = 0
    depth = 0
    string = False
    n = len(source)

    def blank(j: int, k: int) -> None:
        out.append(re.sub(r"[^\n]", " ", source[j:k]))

    while i < n:
        mode = "comment" if depth else "string" if string else "code"
        match = SCRUB_NEXT[mode].search(source, i)
        stop = match.start() if match else n
        if mode == "code":
            out.append(source[i:stop])
        else:
            blank(i, stop)
        if not match:
            break
        token = match.group()
        if mode == "comment":
            depth += 1 if token == "/-" else -1
            blank(stop, stop + 2)
            i = stop + 2
        elif mode == "string":
            if token == '"':
                string = False
                blank(stop, stop + 1)
                i = stop + 1
            else:
                blank(stop, min(stop + 2, n))
                i = stop + 2
        elif token == "/-":
            depth = 1
            blank(stop, stop + 2)
            i = stop + 2
        elif token == "--":
            end = source.find("\n", stop)
            end = n if end == -1 else end
            blank(stop, end)
            i = end
        else:
            string = True
            blank(stop, stop + 1)
            i = stop + 1
    return "".join(out)


def parse_lean(raw: bytes) -> dict:
    source = raw.decode("utf-8")
    clean = scrub(source)
    declarations = []
    imports = []
    scopes = []
    for number, line in enumerate(clean.splitlines(), 1):
        if match := re.match(r"^\s*import\s+(.+)$", line):
            imports.extend(match.group(1).split())
        if match := re.match(r"^\s*(namespace|section|mutual)\b\s*(\S*)", line):
            scopes.append((match.group(1), match.group(2)))
        elif match := re.match(r"^\s*end(?:\s+(\S+))?\s*$", line):
            if scopes:
                scopes.pop()
        if match := DECL.match(line):
            name = match.group("name")
            namespace = ".".join(s[1] for s in scopes if s[0] == "namespace")
            qualified = name[len("_root_."):] if name.startswith("_root_.") else ".".join(filter(None, (namespace, name)))
            declarations.append({"kind": match.group("kind"), "name": name, "qualified_name_hint": qualified, "line": number})
    return {
        "byte_size": len(raw),
        "line_count": len(source.splitlines()),
        "imports": imports,
        "declarations": declarations,
        "declaration_counts": dict(sorted(Counter(d["kind"] for d in declarations).items())),
        "textual_markers": {
            token: [clean.count("\n", 0, m.start()) + 1 for m in re.finditer(r"\b" + token + r"\b", clean)]
            for token in ("sorry", "admit", "axiom", "native_decide", "unsafe")
        },
        "print_axioms_commands": len(re.findall(r"#print\s+axioms\b", clean)),
    }


def role(path: str, content: dict) -> str:
    return path_role(path) or ("audit-driver" if not content["declarations"] and content["print_axioms_commands"] else "working-source")


def path_role(path: str) -> str | None:
    """The role a path alone decides, or None where the file's content decides."""
    parts = Path(path).parts
    if parts[0] == "sources":
        return "imported-archive"
    if parts[0] == "drafts":
        return "historical-draft"
    # This package's README and evidence/manifest.json identify a frozen parent
    # semantic-source capture. Its omitted #print commands change the bytes,
    # but do not make it another working proof module. Keep the exception narrow:
    # an arbitrary directory named "evidence" is not necessarily a snapshot.
    if path.endswith("/reason-consumer/transport/evidence/RecipientReasons.lean"):
        return "saved-copy"
    if any(p == "development" or (p.endswith("-development") and p != "valuation-development") or p.startswith("attempt-") or p in ("review-history", "review-probe-authority") for p in parts[:-1]) or parts[0] == "_process":
        return "development-attempt"
    # Retired material (a component named `history`, as in tools/research/paths.py) is a saved
    # copy wherever it sits, including Lean run folders moved to `<lean root>/history/`.
    if any(p == "history" for p in parts[:-1]):
        return "saved-copy"
    if any(
        p in ("sources", "runs", "snapshots", "source-snapshots", "verification", "verification-history", "isolated", "build", "nondual-independent-logs", "legacy-replays")
        or p.endswith(("-runs", "-verification", "-checks"))
        or re.fullmatch(r"\d{10,}|\d{8}T\d{6}.*Z", p)
        for p in parts[:-1]
    ):
        return "saved-copy"
    return None


@lru_cache(maxsize=1)
def receipt_layers() -> dict:
    """Repository path -> (receipt layer, receipt sha256) for the core receipt's modules."""
    path = LEAN_RECEIPT
    try:
        config = json.loads((ROOT / "_process/research-config.json").read_text())
        path = config.get("lean_receipt", path) if isinstance(config.get("lean_receipt", path), str) else path
    except (OSError, ValueError):
        pass
    try:
        data = json.loads((ROOT / path).read_text())
    except (OSError, ValueError):
        return {}
    lean_root = Path(path).parent.parent
    out = {}
    for module in data.get("modules", []):
        name, layer = module.get("module"), module.get("layer")
        source = data.get("source_paths", {}).get(name)
        if isinstance(source, str) and layer in RECEIPT_GROUPS:
            out[(lean_root / source).as_posix()] = (layer, data.get("source_sha256", {}).get(name))
    return out


def group(path: str) -> str:
    if path in receipt_layers():
        return RECEIPT_GROUPS[receipt_layers()[path][0]]
    if "/universal-ethics/" in path:
        return "ethics"
    if path.startswith("experiments/valuation-development/"):
        return "valuation"
    if "/inquiry-root/" in path:
        return "inquiry"
    if "/lean/conditional/" in path:
        return "renewal"
    if "/lean/learning/" in path or "/systems-complexity/" in path:
        return "learning"
    if "/mathematical-abstraction/" in path:
        return "abstraction"
    if "/noninstrumental-concern/" in path or path.startswith("experiments/recipient-value-learning/"):
        return "concern"
    if path.startswith("experiments/shared-renewal-capability/"):
        return "shared"
    if "/generative-basis/lean/" in path:
        return "core"
    return "other"


@lru_cache(maxsize=None)
def local_link(doc: str, target: str) -> str | None:
    target = target.strip("<>")
    parsed = urlsplit(target)
    if parsed.scheme or parsed.netloc or not parsed.path:
        return None
    resolved = (ROOT / doc).parent.joinpath(unquote(parsed.path)).resolve()
    try:
        relative = resolved.relative_to(ROOT).as_posix()
    except ValueError:
        return None
    return relative if resolved.exists() else None


def documents() -> tuple[dict, dict]:
    docs = {}
    backlinks = defaultdict(list)
    for path in discover("*.md"):
        if path.startswith("theories/becoming/results/"):
            continue
        if not (path.startswith(("theories/", "_process/research/", "experiments/")) or "/" not in path):
            continue
        body = (ROOT / path).read_text(encoding="utf-8")
        targets = sorted({resolved for m in LINK.finditer(body) if (resolved := local_link(path, m.group(1))) and not resolved.startswith("theories/becoming/results/")})
        if not targets:
            continue
        title = next((line.lstrip("# ").strip() for line in body.splitlines() if line.startswith("# ")), Path(path).name)
        docs[path] = {"title": title, "local_links": targets}
        for target in targets:
            if target.endswith(".lean"):
                backlinks[target].append(path)
    return docs, backlinks


def nearest_readme(path: str, docs: dict) -> str | None:
    parent = Path(path).parent
    while parent != Path("."):
        candidate = (parent / "README.md").as_posix()
        if candidate in docs:
            return candidate
        parent = parent.parent
    return None


def href(path: str, line: int | None = None) -> str:
    link = os.path.relpath(ROOT / path, OUT)
    return link + (f"#L{line}" if line else "")


def mdlink(label: str, path: str, line: int | None = None) -> str:
    return f"[{label}]({href(path, line)})"


def anchor(path: str) -> str:
    return "module-" + hashlib.sha256(path.encode()).hexdigest()[:12]


def catalogue() -> tuple[dict, dict]:
    docs, backlinks = documents()
    contents = {}
    files = []
    for path in discover("*.lean"):
        # A saved copy is bound by its own run's receipt; it is not read or listed, so a
        # checker run leaves the catalogue unchanged.
        if path_role(path) == "saved-copy":
            continue
        raw = (ROOT / path).read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        if digest not in contents:
            contents[digest] = parse_lean(raw)
        content = contents[digest]
        readme = nearest_readme(path, docs)
        refs = sorted(backlinks.get(path, []))
        files.append({
            "path": path,
            "sha256": digest,
            "role": role(path, content),
            "group": group(path),
            **({"receipt_layer": receipt_layers()[path][0], "receipt_bytes_match": receipt_layers()[path][1] == digest} if path in receipt_layers() else {}),
            "package_readme": readme,
            "direct_documentation_links_from": refs,
            "proof_status": "not_assessed_by_catalogue",
        })
    duplicates = defaultdict(list)
    for file in files:
        duplicates[file["sha256"]].append(file["path"])
    active = [f for f in files if f["role"] in ("working-source", "audit-driver")]
    stats = {
        "lean_paths": len(files),
        "distinct_byte_contents": len(contents),
        "byte_identical_duplicate_groups": sum(len(paths) > 1 for paths in duplicates.values()),
        "roles": dict(sorted(Counter(f["role"] for f in files).items())),
        "working_named_theorem_lemma_occurrences": sum(sum(d["kind"] in ("theorem", "lemma") for d in contents[f["sha256"]]["declarations"]) for f in active),
        "working_explicit_named_declaration_occurrences": sum(len(contents[f["sha256"]]["declarations"]) for f in active),
        "working_groups": dict(sorted(Counter(f["group"] for f in active).items())),
    }
    used_docs = {ref for f in active for ref in f["direct_documentation_links_from"]}
    used_docs.update(f["package_readme"] for f in active if f["package_readme"])
    source_index = {
        "schema_version": 1,
        "generated_by": SCRIPT,
        "scope": "Existing Markdown documentation with parsed inline links to working Lean files, and their nearest package READMEs. Reference-style links and code-form mentions are not parsed. Links are documentary associations, not checked proof correspondence. Generated results/ documents are excluded.",
        "documents": {path: docs[path] for path in sorted(used_docs)},
    }
    manifest = {
        "schema_version": 1,
        "generated_by": SCRIPT,
        "coverage": {
            "discovery": "rg --files --hidden --no-ignore -g '*.lean' with excluded directory components below; untracked and ignored files are included; saved copies (the path rule in path_role: run, check, snapshot and verification folders) are not read or listed, each being bound by its own run's receipt",
            "excluded_directory_components": list(EXCLUDED),
            "symlinks": "ripgrep default: directory symlinks are not followed",
            "declaration_scan": "Comment/string-aware, line-start explicit theorem/lemma/def/abbrev/structure/inductive/opaque/axiom/constant declarations. Namespace qualification is a textual hint. Generated constructors/projections/instances and anonymous examples are not enumerated as named declarations.",
            "validation": "Documentary inventory only. No Lean compilation, axiom audit, receipt hash binding or mathematical/ethical correspondence verification is performed. SHA-256 is calculated from every indexed file's actual bytes.",
            "classification": "Path-based documentary roles; working-source is not a claim of accepted, complete, canonical or checked status. A file containing only #print axioms and no inventoried named declarations is an audit-driver.",
        },
        "statistics": stats,
        "files": files,
        "contents_by_sha256": dict(sorted(contents.items())),
        "byte_identical_groups": {sha: paths for sha, paths in sorted(duplicates.items()) if len(paths) > 1},
    }
    return manifest, source_index


def doc_links(file: dict, sources: dict) -> str:
    refs = file["direct_documentation_links_from"]
    # A theory's own argument outranks generated navigation that merely lists it.
    generated = set(json.loads(MANIFEST.read_text())["files"])
    canonical = sorted((r for r in refs if r.startswith("theories/")), key=lambda r: (r in generated, r))
    research = sorted((r for r in refs if r.startswith("_process/")), key=lambda r: ("INTEGRATION" not in r, "MATH" not in r, "ARGUMENT" not in r, r))
    chosen = canonical[:1] + research[:1]
    readme = file["package_readme"]
    if readme and readme not in chosen:
        chosen.append(readme)
    links = []
    for path in chosen:
        label = "Theory" if path.startswith("theories/") else "Study" if path.startswith("_process/") else "Package notes"
        links.append(mdlink(label, path))
    if not refs and readme:
        links.append("No direct module-documentation link found")
    if "receipt_layer" in file:
        links.append(f"Core receipt: {file['receipt_layer']} layer, " + ("bytes as checked" if file["receipt_bytes_match"] else "changed since the receipt"))
    return " · ".join(links) or "No direct documentation link found"


def concept_entry(entry: str) -> str:
    """The conceptual entry of a group, labelled as history when it is an earlier chapter."""
    target = current(entry)
    path, _, fragment = target.partition("#")
    label = Path(path).stem + (f" §{fragment.split('-')[0]}" if fragment else "")
    note = " (earlier chapter, kept in history at its original scope)" if "/history/" in "/" + path else ""
    return f"[{label}]({href(path)}{'#' + fragment if fragment else ''}){note}"


