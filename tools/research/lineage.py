def cell(text):
    return (text or '').replace('|', '\\|').replace('\n', ' ')


def quote_line(path, quote, named=None):
    """The line of `path` where `quote` stands (whitespace collapsed, Markdown marks dropped): the named line where it
    holds the quotation; else, of the lines holding the whole quotation (or, for one spanning lines, its first line),
    the one nearest the named line; else of those holding its first 48 characters; else None."""
    text = _read(path) if quote else None
    if not text:
        return None
    lines = [norm(line) for line in text.split('\n')]
    whole, head = norm(quote).strip(), norm(quote)[:48].strip()
    if named and 1 <= named <= len(lines) and head and head in lines[named - 1]:
        return named
    for part in (whole, head):
        found = [i for i, line in enumerate(lines, 1) if part and part in line]
        if found:
            return min(found, key=lambda i: abs(i - named)) if named else found[0]
    return None


def evidence_link(e, here, words):
    """An evidence entry as a link to its line (`?plain=1` shows a Markdown source's lines): the line where its quotation
    stands now, found in the file, so the link follows the file as it moves; else the line its locator names."""
    if e.get('private'):
        return f'`{e["path"]}` ({words["not_in_repository"]})'
    target = link(e['path'], here)
    locator = e.get('locator') or ''
    zh = bool(words.get('sources_n'))  # the Chinese edition
    if e.get('commit'):  # read as of the commit that landed it, which no relative link reaches
        if zh:
            return f'提交 `{e["commit"]}` 中的 `{e["path"]}`' + (f'（{cell(zh_locator(locator))}）' if locator else '')
        return f'`{e["path"]}` at commit `{e["commit"]}`' + (f' ({cell(locator)})' if locator else '')
    if e['path'] in UNRENDERED:  # changed by commits that render nothing, so a line there would not stay true
        return f'[`{e["path"]}`]({target})' + ((f'（{cell(zh_locator(locator))}）' if zh else f' ({cell(locator)})') if locator else '')
    named = re.search(r'\blines? (\d+)', locator)
    found = quote_line(e['path'].split('#', 1)[0], e.get('quote'), int(named.group(1)) if named else None)
    line = found or (int(named.group(1)) if named else None)
    if found and named and re.match(r'line \d+\b', locator[named.start():]):
        locator = locator[:named.start()] + f'line {found}' + locator[named.end():]
    if line and '#' not in target:
        target += ('?plain=1' if e['path'].endswith('.md') else '') + f'#L{line}'
    if zh:  # the common locator words in Chinese
        locator = zh_locator(locator)
        return f'[`{e["path"]}`]({target})' + (f'（{cell(locator)}）' if locator else '')
    return f'[`{e["path"]}`]({target})' + (f' ({cell(locator)})' if locator else '')


def zh_locator(locator):
    """A locator's common English words in Chinese form: line numbers, "same heading", a heading it stands under, and
    full-width punctuation; its other words are left as written, which the page says."""
    locator = re.sub(r'\blines (\d+)[–-](\d+)', r'第 \1–\2 行', locator)
    locator = re.sub(r'\bline (\d+)', r'第 \1 行', locator)
    locator = re.sub(r"(^|, )under ('## [^']*')", r'\1在 \2 标题下', locator)
    locator = locator.replace('same heading', '同一标题下')
    return locator.replace(', ', '，').replace(' (', '（').replace('(', '（').replace(')', '）')


def link(path, page):
    rel = os.path.relpath(path.split('#', 1)[0], Path(page).parent)
    return rel + ('#' + path.split('#', 1)[1] if '#' in path else '')


def page(s, lang, weeks, undated, by_folder, totals):
    words = s['words'][lang]
    here = PAGE[lang]
    other = PAGE['zh' if lang == 'en' else 'en']
    cut = s['cut']
    # Each edition opens with its fronts' navigation line (the generated pages' NAV in English, zh_fronts' line in
    # Chinese), its time on a line below.
    head = ([zh_fronts.nav_line(here), '', '*{time}*'] if lang == 'zh' else
            [' · '.join(navigation.link(p, here, label) for p, label in navigation.NAV), '',
             f'[{words["other_language"]}]({os.path.basename(other)}) · {{time}}'])
    lines = [HEADER, '', f'# {words["title"]}', ''] + head + ['',
             words['intro'].format(commits=f'{cut["commits"]:,}' if lang == 'en' else cut['commits'],
                                   date=cut['date_' + lang], commit=cut['commit'][:9]), '']
    if words.get('arc'):
        lines += [words['arc'], '']
    number = {p['id']: n for n, p in enumerate(s['points'], 1)}
    label_of = {p['id']: p['label'] for p in s['points']}
    origin_of = {p['id']: p.get('origin') for p in s['points']}
    if s.get('phases'):
        lines += [f'## {words["brief_heading"]}', '', words['brief_intro'], '']
        for ph in s['phases']:
            nums = [number[i] for i in ph['points']]
            kinds = Counter(label_of[i] for i in ph['points'])
            labels = (words['all_label'].format(label=s['labels'][next(iter(kinds))][lang]) if len(kinds) == 1 else
                      ('，' if lang == 'zh' else ', ').join(f'{n} {s["labels"][k][lang]}' for k, n in kinds.items()))
            if s.get('origins'):
                made = Counter(origin_of[i] for i in ph['points'])
                labels += ('；' if lang == 'zh' else '; ') + ('，' if lang == 'zh' else ', ').join(
                    f'{made[k]} {s["origins"][k]["short_" + lang]}' for k in ORIGINS if made.get(k))
            tail = words['phase_tail'].format(first=min(nums), last=max(nums), labels=labels)
            if lang == 'zh':
                lines.append(f'- **{ph["name"][lang]}**（{ph["from"]} – {ph["to"]}）。{ph["what"][lang]}{tail}')
            else:
                lines.append(f'- **{ph["name"][lang]}** ({ph["from"]} – {ph["to"]}). {ph["what"][lang]} {tail}')
        lines.append('')
    lines += [f'![{words["title"]}]({os.path.basename(SVG[lang])})', '', words['labels_intro'], '']
    colon = '：' if lang == 'zh' else ': '
    count = Counter(p['label'] for p in s['points'])
    for key in LABELS:
        n = count.get(key, 0)
        shown = n if n else words['none_so_far']
        lines.append(f'- **{s["labels"][key][lang]}**' + (f'（{shown}）' if lang == 'zh' else f' ({shown})') + f'{colon}{s["labels"][key]["means_" + lang]}')
    if s.get('origins'):
        made = Counter(p.get('origin') for p in s['points'])
        lines += ['', words['origins_intro'].format(total=len(s['points'])), '']
        for key in ORIGINS:
            o, n = s['origins'][key], made.get(key, 0)
            shown = n if n else words['none_so_far']
            lines.append(f'- **{o[lang]}**' + (f'（{shown}）' if lang == 'zh' else f' ({shown})') + f'{colon}{o["means_" + lang]}')
    for key in ('coverage', 'chosen', 'strands'):
        if words.get(key):
            lines += ['', words[key].format(crosswalk=os.path.relpath(CROSSWALK_PAGE_ZH if lang == 'zh' else CROSSWALK_PAGE, Path(here).parent),
                                            folders=os.path.relpath('theories/README.md', Path(here).parent), **strand_counts(s))]
    lines += ['', words['hb_note'], '']
    for th in threads_of(s):
        lines += ['', f'## {th["title"][lang]}', '', th['intro'][lang], '']
        for pid in th['points']:  # bullets: a Markdown numbered list would renumber them from its first
            p = next(x for x in s['points'] if x['id'] == pid)
            comma, stop = ('，', '。') if lang == 'zh' else (', ', '.')
            lines.append(f'- **{number[pid]}.** **{p["date"]}{comma}{cell(p["title"][lang])}{stop}** {p["what"][lang]}')
        lines.append('')
    part = '\n'.join(lines)
    lines += [f'## {words["points_heading"]}', ''] + ([words['sources_note'], ''] if lang == 'zh' else []) + [
              f'| # | {words["date"]} | {words["what"]} | {words["evidence"]} | {words["label"]} |'
              + (f' {words["origin"]} |' if s.get('origins') else ''), '|---:|---|---|---|---|' + ('---|' if s.get('origins') else '')]
    sources = []
    for n, p in enumerate(s['points'], 1):
        links = list(dict.fromkeys(evidence_link(e, here, words) for e in p['evidence']))  # one place cited once
        ev = ('；' if lang == 'zh' else '; ').join(links)
        stop = '。' if lang == 'zh' else '.'
        shown = ev if lang == 'en' else f'[{words["sources_n"].format(n=len(links))}](#src-{n})'
        lines.append(f'| {n} | {p["date"]} | **{cell(p["title"][lang])}{stop}** {cell(p["what"][lang])} | {shown} | '
                     f'{s["labels"][p["label"]][lang]} |' + (f' {s["origins"][p["origin"]][lang]} |' if s.get('origins') else ''))
        sources.append(f'- <a id="src-{n}"></a>**{n}.** {ev}')
    if lang == 'zh':
        lines += ['', f'### {words["sources_list"]}', ''] + sources
    lines.append('')
    if s.get('renames'):
        lines += [f'## {words["renames_heading"]}', '', words['renames_intro'], '',
                  f'| {words["date"]} | {words["from"]} | {words["to"]} | {words["where"]} | {words["evidence"]} | {words["label"]} |',
                  '|---|---|---|---|---|---|']
        for r in s['renames']:
            lines.append(f'| {r["date"]} | {cell(r["from"])} | {cell(r["to"])} | {cell(r["where"][lang])} | '
                         f'[`{r["evidence_path"]}`]({link(r["evidence_path"], here)}) | {s["labels"][r["label"]][lang]} |')
        lines.append('')
    if totals:
        order = s['carried_order']
        lines += [f'## {words["folders_heading"]}', '',
                  words['folders_intro'].format(total=sum(totals.values()),
                                                index=link('theories/README.md', here),
                                                crosswalk=link('theories/becoming/results/atlas/CROSSWALK.md', here)), '',
                  '| ' + ' | '.join(s['carried_words'][c][lang] for c in order) + ' |',
                  '|' + '---:|' * len(order),
                  '| ' + ' | '.join(str(totals.get(c, 0)) for c in order) + ' |', '']
    if s.get('papers'):
        lines += [f'## {words["papers_heading"]}', '', words['papers_intro'], '',
                  f'| {words["paper"]} | {words["date"]} | {words["claimed"]} | {words["stands"]} | {words["label"]} |',
                  '|---|---|---|---|---|']
        for p in s['papers']:
            paths = ', '.join(f'[`{x}`]({link(x, here)})' for x in p['paths'])
            lines.append(f'| {cell(p["title"])} ({paths}) | {p["date"]} | {cell(p["claimed"][lang])} | {cell(p["stands"][lang])} | '
                         f'{s["labels"][p["label"]][lang]} |')
        lines.append('')
    if weeks:
        lines += [f'## {words["growth_heading"]}', '',
                  words['growth_intro'].format(total=sum(weeks.values()), undated=undated), '',
                  f'| {words["week_of"]} | {words["entries"]} |', '|---|---:|']
        for monday, n in weeks.items():
            lines.append(f'| {monday.isoformat()} | {n} |')
        lines.append('')
    lines += [f'## {words["sources_heading"]}', '', words['sources']]
    body = '\n'.join(lines).rstrip() + '\n'
    full, first = navigation.reading_time(body), navigation.reading_time(part)
    if lang == 'zh':
        full, first = full.replace(' minutes', ' 分钟').replace('a minute', '一分钟'), first.replace(' minutes', ' 分钟').replace('a minute', '一分钟')
    return body.replace('{time}', words['reading_time'].format(full=full, first=first), 1)


def render():
    """(pages, errors)."""
    s = spec()
    if not s:
        return {}, []  # no lineage yet: nothing to write
    errors = check(s)
    if errors:
        return {}, errors
    weeks, undated = history_by_week()
    by_folder, totals = crosswalk_outcomes()
    out = {}
    for lang in ('en', 'zh'):
        out[PAGE[lang]] = page(s, lang, weeks, undated, by_folder, totals)
        try:
            out[SVG[lang]] = svg(s, lang, weeks)
        except ValueError as error:  # titles that would cross: stop the render, naming them
            return {}, [str(error)]
    return out, []
