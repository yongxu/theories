"""The lineage (board item RW (c)): how the account grew, from the earlier writings to the live account.

Writes `theories/LINEAGE.md` and `theories/LINEAGE.zh.md`, and a time line of the turning points in each language
(`theories/lineage.svg`, `theories/lineage.zh.svg`), from the curated `theories/becoming/results/data/lineage.json`
and counts read from the tree:

- the records' history entries by week (each entry's leading date, "28 October 2026: …" or "2026-10-13: …");
- what the crosswalk found of each earlier folder (its entries by outcome);
- the commit count, held in the data with the date and commit it was cut at, never read from "now", so a render on
  any later tree writes the same page.

Each turning point carries one evidence label: public (a tracked file states it), private (only private or
unpublished material states it, which a public text cites), or reconstruction (no source states it; it is
inferred, by an AI or by a synthesis such as the September timeline). An evidence path the tree lacks, a quotation
its file no longer holds, a point out of date order or an unknown label is an error, as a broken record is.
The time axis compresses the years before 2026 and widens September to November 2026.
"""
from __future__ import annotations

import datetime as dt
import json
import os
import re
from collections import Counter
from pathlib import Path
from xml.sax.saxutils import escape

from tools.research import registry

ROOT = registry.ROOT
DATA = 'theories/becoming/results/data/lineage.json'
PAGE = {'en': 'theories/LINEAGE.md', 'zh': 'theories/LINEAGE.zh.md'}
SVG = {'en': 'theories/lineage.svg', 'zh': 'theories/lineage.zh.svg'}
RECORDS = 'theories/becoming/results/records'
CORRESPONDENCES = 'theories/becoming/results/atlas/entries/correspondences.json'
LABELS = ('public', 'private', 'reconstruction')
HEADER = ('<!-- Generated by tools/research/research.py render (tools/research/lineage.py) from '
          'theories/becoming/results/data/lineage.json, the records and the crosswalk; edit those, not this page. -->')
MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November',
          'December']
DATED = re.compile(r'^\s*(?:(\d{1,2}) (' + '|'.join(MONTHS) + r') (20\d\d)|(20\d\d)-(\d\d)-(\d\d))\b')
W, H = 1300, 560
INK, MUTED, FAINT, PAPER, THREAD = '#1c1917', '#57534e', '#a8a29e', '#fcfcfb', '#2a78d6'
FONT = {'en': 'Helvetica, Arial, sans-serif',
        'zh': "'PingFang SC', 'Hiragino Sans GB', 'Noto Sans CJK SC', 'Microsoft YaHei', sans-serif"}


def _read(path):
    p = ROOT / path
    return p.read_text(encoding='utf-8') if p.is_file() else None


def spec():
    return json.loads(_read(DATA) or '{}')


def parse_date(text):
    """'2026-10-23', '2026-10' or '2024' as (date, precision); precision is 'day', 'month' or 'year'."""
    parts = [int(p) for p in text.split('-')]
    if len(parts) == 3:
        return dt.date(*parts), 'day'
    if len(parts) == 2:
        return dt.date(parts[0], parts[1], 1), 'month'
    return dt.date(parts[0], 1, 1), 'year'


def norm(text):
    return re.sub(r'\s+', ' ', re.sub(r'[*`]', '', text or ''))


def check(s):
    errors = []
    previous = None
    ids = set()
    for p in s.get('points', []):
        where = f'lineage.json: point {p.get("id")}'
        if p.get('id') in ids:
            errors.append(f'{where}: id repeated')
        ids.add(p.get('id'))
        try:
            day, _ = parse_date(p['date'])
        except (KeyError, ValueError, TypeError):
            errors.append(f'{where}: bad date {p.get("date")!r}')
            continue
        if previous and day < previous:
            errors.append(f'{where}: out of date order')
        previous = day
        if p.get('label') not in LABELS:
            errors.append(f'{where}: unknown label {p.get("label")!r}')
        for lang in ('en', 'zh'):
            if not (p.get('title', {}).get(lang) and p.get('what', {}).get(lang)):
                errors.append(f'{where}: no {lang} title or text')
        errors += evidence_errors(where, p.get('evidence', []))
    for r in s.get('renames', []):
        if r.get('label') not in LABELS:
            errors.append(f'lineage.json: rename {r.get("from")} → {r.get("to")}: unknown label {r.get("label")!r}')
        errors += evidence_errors(f'lineage.json: rename {r.get("from")} → {r.get("to")}',
                                  [{'path': r.get('evidence_path'), 'quote': r.get('quote')}])
    for p in s.get('papers', []):
        for path in p.get('paths', []) + p.get('stands_basis', []):
            if not (ROOT / path.split('#', 1)[0]).exists():
                errors.append(f'lineage.json: paper {p.get("id")}: no such path {path}')
        if p.get('label') not in LABELS:
            errors.append(f'lineage.json: paper {p.get("id")}: unknown label {p.get("label")!r}')
    for t in s.get('thread', {}).get('points', []):
        if t not in ids:
            errors.append(f'lineage.json: the thread names no point {t}')
    cut = s.get('cut', {})
    if not (cut.get('date_en') and cut.get('date_zh') and isinstance(cut.get('commits'), int) and cut.get('commit')):
        errors.append('lineage.json: the commit count needs its date, count and commit')
    return errors


def evidence_errors(where, evidence):
    errors = []
    for e in evidence:
        path = (e.get('path') or '').split('#', 1)[0]
        if e.get('private'):
            continue  # a private path is named, not read: it is not in the tree
        text = _read(path)
        if text is None:
            if not (ROOT / path).is_dir():
                errors.append(f'{where}: no such path {path}')
            continue
        if e.get('quote') and norm(e['quote']) not in norm(text):
            errors.append(f'{where}: {path} no longer holds {e["quote"]!r}')
    return errors


def history_by_week():
    """Record history entries by the Monday of their week, and how many carry no leading date."""
    weeks, undated = Counter(), 0
    for f in sorted((ROOT / RECORDS).glob('*.json')):
        for h in json.loads(f.read_text(encoding='utf-8')).get('history', []):
            m = DATED.match(h.get('en', '') if isinstance(h, dict) else str(h))
            if not m:
                undated += 1
                continue
            if m.group(1):
                day = dt.date(int(m.group(3)), MONTHS.index(m.group(2)) + 1, int(m.group(1)))
            else:
                day = dt.date(int(m.group(4)), int(m.group(5)), int(m.group(6)))
            weeks[day - dt.timedelta(days=day.weekday())] += 1
    return dict(sorted(weeks.items())), undated


def crosswalk_outcomes():
    """Entries of the crosswalk by earlier folder (or domain) and outcome."""
    text = _read(CORRESPONDENCES)
    if not text:
        return {}, Counter()
    data = json.loads(text)
    entries = data.get('correspondences', data) if isinstance(data, dict) else data
    by, total = {}, Counter()
    for e in entries:
        by.setdefault(e.get('group', ''), Counter())[e.get('carried', '')] += 1
        total[e.get('carried', '')] += 1
    return by, total


# The time axis: the years before 2026 compressed, September to November 2026 widened.
def axis(s):
    segments = []
    x = 60.0
    for seg in s['axis']:
        start, _ = parse_date(seg['from'])
        end, _ = parse_date(seg['to'])
        width = (W - 120) * seg['share']
        segments.append((start, end, x, x + width, seg))
        x += width
    return segments


def x_of(day, segments):
    for start, end, x0, x1, _ in segments:
        if start <= day <= end:
            span = (end - start).days or 1
            return x0 + (x1 - x0) * (day - start).days / span
    return segments[-1][3] if day > segments[-1][1] else segments[0][2]


def svg(s, lang, weeks):
    words = s['words'][lang]
    segments = axis(s)
    base = 300
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" '
           f'aria-labelledby="lineage-title" font-family="{FONT[lang]}">',
           f'<title id="lineage-title">{escape(words["title"])}</title>',
           f'<rect x="0.5" y="0.5" width="{W - 1}" height="{H - 1}" rx="10" fill="{PAPER}" stroke="#d6d3d1"/>',
           t(28, 40, words['title'], 20, 'bold'), t(28, 62, words['subtitle'], 12.5, fill=MUTED)]
    # segments and their ticks
    for i, (start, end, x0, x1, seg) in enumerate(segments):
        shade = '#f0eee9' if i % 2 == 0 else '#f7f5f0'
        out.append(f'<rect x="{x0:.1f}" y="{base - 150}" width="{x1 - x0:.1f}" height="210" fill="{shade}"/>')
        out.append(t((x0 + x1) / 2, base - 158, seg['label'][lang], 11.5, 'bold', 'middle', MUTED))
        for tick in seg['ticks']:
            day, _ = parse_date(tick)
            x = x_of(day, segments)
            out.append(f'<line x1="{x:.1f}" y1="{base}" x2="{x:.1f}" y2="{base + 6}" stroke="{MUTED}"/>')
            out.append(t(x, base + 20, tick_label(tick, lang), 10.5, anchor='middle', fill=MUTED))
    out.append(f'<line x1="60" y1="{base}" x2="{W - 60}" y2="{base}" stroke="{INK}" stroke-width="1.5"/>')
    # growth in the records, by week, below the axis
    if weeks:
        top = max(weeks.values())
        for monday, n in weeks.items():
            x = x_of(monday, segments)
            h = 50 * n / top
            out.append(f'<rect x="{x:.1f}" y="{base + 28:.1f}" width="6" height="{h:.1f}" fill="{FAINT}"/>')
        out.append(t(W - 60, base + 92, words['growth'].format(top=top), 10.5, anchor='end', fill=MUTED))
    # the points, numbered, in lanes above the axis
    lanes = []
    thread = set(s.get('thread', {}).get('points', []))
    marks = {}
    for n, p in enumerate(s['points'], 1):
        day, _ = parse_date(p['date'])
        x = x_of(day, segments)
        lane = next((i for i, last in enumerate(lanes) if x - last >= 22), len(lanes))
        if lane == len(lanes):
            lanes.append(x)
        lanes[lane] = x
        y = base - 18 - 22 * lane
        marks[p['id']] = (x, y)
        out.append(f'<line x1="{x:.1f}" y1="{base}" x2="{x:.1f}" y2="{y:.1f}" stroke="{FAINT}" stroke-width="0.8"/>')
        fill = {'public': INK, 'private': '#ffffff', 'reconstruction': '#ffffff'}[p['label']]
        dash = ' stroke-dasharray="2.5 2"' if p['label'] == 'reconstruction' else ''
        ring = f' stroke="{THREAD}" stroke-width="2.4"' if p['id'] in thread else f' stroke="{INK}" stroke-width="1.2"'
        out.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="9" fill="{fill}"{ring}{dash}/>')
        out.append(t(x, y + 3.5, str(n), 9, 'bold', 'middle', '#ffffff' if p['label'] == 'public' else INK))
    path = [marks[i] for i in s.get('thread', {}).get('points', []) if i in marks]
    if len(path) > 1:
        d = 'M' + ' L'.join(f'{x:.1f},{y - 12:.1f}' for x, y in path)
        out.append(f'<path d="{d}" fill="none" stroke="{THREAD}" stroke-width="1.6" stroke-dasharray="5 3"/>')
    # legend
    y = H - 92
    for i, key in enumerate(LABELS):
        x = 60 + 300 * i
        dash = ' stroke-dasharray="2.5 2"' if key == 'reconstruction' else ''
        fill = INK if key == 'public' else '#ffffff'
        out.append(f'<circle cx="{x + 9}" cy="{y - 4}" r="8" fill="{fill}" stroke="{INK}" stroke-width="1.2"{dash}/>')
        out.append(t(x + 24, y, s['labels'][key][lang], 11.5))
    out.append(f'<circle cx="{60 + 9}" cy="{y + 22}" r="8" fill="#ffffff" stroke="{THREAD}" stroke-width="2.4"/>')
    out.append(t(84, y + 26, words['thread_legend'], 11.5))
    out.append(t(28, H - 22, words['footer'], 10.5, fill=MUTED))
    out.append('</svg>')
    return '\n'.join(out) + '\n'


def tick_label(tick, lang):
    day, precision = parse_date(tick)
    if precision == 'year':
        return str(day.year)
    if precision == 'month':
        return f'{day.year}-{day.month:02d}' if day.month == 1 else (f'{day.month}月' if lang == 'zh' else MONTHS[day.month - 1][:3])
    return f'{day.month}月{day.day}日' if lang == 'zh' else f'{day.day} {MONTHS[day.month - 1][:3]}'


def t(x, y, body, size=12, weight='normal', anchor='start', fill=INK):
    bold = ' font-weight="bold"' if weight == 'bold' else ''
    return f'<text x="{x:.1f}" y="{y:.1f}" font-size="{size}"{bold} text-anchor="{anchor}" fill="{fill}">{escape(body)}</text>'


def cell(text):
    return (text or '').replace('|', '\\|').replace('\n', ' ')


def link(path, page):
    rel = os.path.relpath(path.split('#', 1)[0], Path(page).parent)
    return rel + ('#' + path.split('#', 1)[1] if '#' in path else '')


def page(s, lang, weeks, undated, by_folder, totals):
    words = s['words'][lang]
    here = PAGE[lang]
    other = PAGE['zh' if lang == 'en' else 'en']
    cut = s['cut']
    lines = [HEADER, '', f'# {words["title"]}', '',
             f'[{words["other_language"]}]({os.path.basename(other)}) · {words["reading_time"]}', '',
             words['intro'].format(commits=f'{cut["commits"]:,}' if lang == 'en' else cut['commits'],
                                   date=cut['date_' + lang], commit=cut['commit'][:9]), '',
             f'![{words["title"]}]({os.path.basename(SVG[lang])})', '',
             words['labels_intro'], '']
    for key in LABELS:
        lines.append(f'- **{s["labels"][key][lang]}**: {s["labels"][key]["means_" + lang]}')
    lines += ['', f'## {words["points_heading"]}', '',
              f'| # | {words["date"]} | {words["what"]} | {words["evidence"]} | {words["label"]} |', '|---:|---|---|---|---|']
    for n, p in enumerate(s['points'], 1):
        ev = '; '.join(f'[`{e["path"]}`]({link(e["path"], here)})' + (f' ({cell(e["locator"])})' if e.get('locator') else '')
                       if not e.get('private') else f'`{e["path"]}` ({words["not_in_repository"]})' for e in p['evidence'])
        lines.append(f'| {n} | {p["date"]} | **{cell(p["title"][lang])}.** {cell(p["what"][lang])} | {ev} | '
                     f'{s["labels"][p["label"]][lang]} |')
    th = s.get('thread', {})
    if th:
        lines += ['', f'## {th["title"][lang]}', '', th['intro'][lang], '']
        number = {p['id']: n for n, p in enumerate(s['points'], 1)}
        for pid in th['points']:
            p = next(x for x in s['points'] if x['id'] == pid)
            lines.append(f'{number[pid]}. **{p["date"]}, {cell(p["title"][lang])}.** {p["what"][lang]}')
        lines.append('')
    if s.get('renames'):
        lines += [f'## {words["renames_heading"]}', '', words['renames_intro'], '',
                  f'| {words["date"]} | {words["from"]} | {words["to"]} | {words["where"]} | {words["evidence"]} | {words["label"]} |',
                  '|---|---|---|---|---|---|']
        for r in s['renames']:
            lines.append(f'| {r["date"]} | {cell(r["from"])} | {cell(r["to"])} | {cell(r["where"][lang])} | '
                         f'[`{r["evidence_path"]}`]({link(r["evidence_path"], here)}) | {s["labels"][r["label"]][lang]} |')
        lines.append('')
    if totals:
        order = s['carried_order']
        lines += [f'## {words["folders_heading"]}', '',
                  words['folders_intro'].format(total=sum(totals.values()),
                                                index=link('theories/README.md', here),
                                                crosswalk=link('theories/becoming/results/atlas/CROSSWALK.md', here)), '',
                  '| ' + ' | '.join(s['carried_words'][c][lang] for c in order) + ' |',
                  '|' + '---:|' * len(order),
                  '| ' + ' | '.join(str(totals.get(c, 0)) for c in order) + ' |', '']
    if s.get('papers'):
        lines += [f'## {words["papers_heading"]}', '', words['papers_intro'], '',
                  f'| {words["paper"]} | {words["date"]} | {words["claimed"]} | {words["stands"]} | {words["label"]} |',
                  '|---|---|---|---|---|']
        for p in s['papers']:
            paths = ', '.join(f'[`{x}`]({link(x, here)})' for x in p['paths'])
            lines.append(f'| {cell(p["title"])} ({paths}) | {p["date"]} | {cell(p["claimed"][lang])} | {cell(p["stands"][lang])} | '
                         f'{s["labels"][p["label"]][lang]} |')
        lines.append('')
    if weeks:
        lines += [f'## {words["growth_heading"]}', '',
                  words['growth_intro'].format(total=sum(weeks.values()), undated=undated), '',
                  f'| {words["week_of"]} | {words["entries"]} |', '|---|---:|']
        for monday, n in weeks.items():
            lines.append(f'| {monday.isoformat()} | {n} |')
        lines.append('')
    lines += [f'## {words["sources_heading"]}', '', words['sources']]
    return '\n'.join(lines).rstrip() + '\n'


def render():
    """(pages, errors)."""
    s = spec()
    if not s:
        return {}, []  # no lineage yet: nothing to write
    errors = check(s)
    if errors:
        return {}, errors
    weeks, undated = history_by_week()
    by_folder, totals = crosswalk_outcomes()
    out = {}
    for lang in ('en', 'zh'):
        out[PAGE[lang]] = page(s, lang, weeks, undated, by_folder, totals)
        out[SVG[lang]] = svg(s, lang, weeks)
    return out, []
