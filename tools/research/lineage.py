def threads_of(s):
    """The followed threads: the data's `threads`, or a single `thread`; each with its ring's colour."""
    found = s.get('threads') or ([s['thread']] if s.get('thread') else [])
    return [{**th, 'colour': th.get('colour', THREAD)} for th in found]


def _read(path):
    p = ROOT / path
    return p.read_text(encoding='utf-8') if p.is_file() else None


_AT = {}


def _read_at(commit, path):
    """A file as of a commit (`git show`), or None where git or the commit cannot give it."""
    if (commit, path) not in _AT:
        try:
            out = subprocess.run(['git', '-C', str(ROOT), 'show', f'{commit}:{path}'], capture_output=True, timeout=60)
            _AT[(commit, path)] = out.stdout.decode('utf-8') if out.returncode == 0 else None
        except (OSError, subprocess.SubprocessError):
            _AT[(commit, path)] = None
    return _AT[(commit, path)]


