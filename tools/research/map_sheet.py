def build(d: dict) -> dict:
    """Joins the four files: resolves each path's steps and each test's arrows, and counts what is on the map."""
    geo = geometry(d); geo['bands'] = d['sheet']['bands']
    P = geo['P']; bykey = {p['key']: p for p in P}
    def find(ref):
        return bykey.get(ref) or bykey['>'.join(reversed(ref.split('>')))]
    paths = []
    for path in d['paths']['paths']:
        path = json.loads(json.dumps(path)); n = 0
        for f in ('shows_en', 'shows_zh', 'known', 'cast'): path.setdefault(f, [])
        inside = _inside(geo, path.get('bands'))
        cset, pset, tones, badges = [], [], {}, []
        for S in path['sections']:
            for st in S['steps']:
                n += 1; st['n'] = n; st['tone'] = S['tone']; st['refs'] = []
                for ref in st['on']:
                    if ref.startswith('box:'):
                        st['refs'].append({'c': ref[4:]}); cset.append(ref[4:]); tones.setdefault(ref[4:], S['tone'])
                    elif ref.startswith('stay:'):
                        st['refs'].append({'stay': ref[5:]}); cset.append(ref[5:]); tones.setdefault(ref[5:], S['tone'])
                    else:
                        p = find(ref); st['refs'].append({'p': p['id']}); pset.append(p['id']); cset += [p['from'], p['to']]; tones.setdefault(p['id'], S['tone'])
                r = st['refs'][0]
                if 'p' in r:
                    p = next(p for p in P if p['id'] == r['p']); at = p['mid']
                    if p['far'] and not (inside(p['from']) and inside(p['to'])):     # the arrow is a stub here: number it at the stub
                        tip = p['tips'][0 if inside(p['from']) else 1]; at = (tip[0] - 12, tip[1])
                else:
                    b = geo['boxes'][r.get('c') or r['stay']]; at = (b['x'] - G['BW'] / 2 + 3, b['y'] - G['BH'] / 2 + 3)
                st['soft'] = 'p' in r and p['kind'] in ('needs', 'built', 'reading')   # needs a further premise, or is a built example or a reading: a hollow number
                badges.append((n, S['tone'], at, st['soft']))
        path.update(cset=sorted(set(cset)), pset=sorted(set(pset)), tones=tones, badges=badges, n=n)
        paths.append(path)
    tests = []
    for t in d['laid']['tests']:
        t = json.loads(json.dumps(t))
        slots = collections.Counter()   # each mark at a box takes the next place along its top edge
        def slot(box):
            slots[box] += 1
            return slots[box] - 1
        gave_pins = {g['pin'] for g in t.get('gave', []) if 'pin' in g}
        for i, pin in enumerate(t['pins']):
            pin['n'] = i + 1; pin['k'] = sum(1 for x in t['pins'][:i] if x['at'] == pin['at'])
            pin['s'] = slot(pin['at'])
            if i + 1 in gave_pins: pin['gs'] = slot(pin['at'])
            if pin.get('found_at'): pin['fs'] = slot(pin['found_at'])
        if t.get('view'): t['view']['s'] = slot(t['view']['at'])
        t['used_ids'] = [bykey[k]['id'] for k in t.get('used', [])]
        t['gave'] = [{'pin': g['pin']} if 'pin' in g else {'p': bykey[g['passage']]['id']} for g in t.get('gave', [])]
        ys = [geo['boxes'][x]['y'] for x in [p['at'] for p in t['pins']] + [p['found_at'] for p in t['pins'] if p.get('found_at')] + ([t['view']['at']] if t.get('view') else [])]
        ys += [geo['boxes'][e]['y'] for i in t['used_ids'] for e in (next(p for p in P if p['id'] == i)['from'], next(p for p in P if p['id'] == i)['to'])]
        t['bands'] = [b['id'] for b in d['sheet']['bands'] if geo['band_box'][b['id']][0] <= max(ys) and geo['band_box'][b['id']][1] >= min(ys)]
        tests.append(t)
    ways = [w for p in P for w in [p] + p.get('more', [])]
    counts = {'boxes': len(geo['boxes']), 'rows': len(geo['ri']), 'arrows': len(P), 'stays': len(d['passages']['stays']),
              'two': sum(1 for p in P if p.get('readers') == 2 and p['laws']), 'one': sum(1 for p in P if p.get('readers') == 1 and p['laws']), 'nolean': sum(1 for p in P if not p['laws']),
              'anchored': sum(1 for b in geo['boxes'].values() if b.get('anchors')), 'tests': len(tests), 'paths': len(paths),
              'names': sum(len(b.get('known_en') or []) + len(b.get('unlike_en') or []) for b in geo['boxes'].values()),
              'named': sum(1 for b in geo['boxes'].values() if b.get('known_en') or b.get('unlike_en')),
              'kinds': dict(collections.Counter(p['kind'] for p in P)), 'ways': len(ways),
              'further': len(ways) - len(P), 'further2': sum(1 for p in P for w in p.get('more', []) if w.get('readers') == 2), 'further1': sum(1 for p in P for w in p.get('more', []) if w.get('readers') == 1),
              'with_further': sum(1 for p in P if p.get('more')), 'records': len({rec for t in tests for rec in (t.get('records') or [t['test']])}), 'drawn': sum(1 for p in P if not p['far'])}
    along = collections.Counter()
    last_band = d['sheet']['bands'][-1]['id']
    for p in P:
        a, b = geo['boxes'][p['from']], geo['boxes'][p['to']]
        if p['kind'] in ('line', 'same') or a['row'] != b['row'] or geo['rows'][a['row']]['band'] == last_band: continue
        along[('right' if b['col'] > a['col'] else 'left') + '/' + p['kind']] += 1
    counts['along'] = dict(sorted(along.items()))
    return dict(d=d, geo=geo, paths=paths, tests=tests, counts=counts, dyn_names={})


