            p['d'] = _rounded(pts, 7); p['h1'] = _arrowhead(pb, (0, s))
            p['mid'] = (gx, (y1 + y2) / 2); p['bar'] = _bar(p['mid'], (0, 1), 6); p['tagpos'] = (gx + 10, p['mid'][1] + 4)
            ta, tb = (pa[0], pa[1] + s * 12), (pb[0], pb[1] - s * 12)
            p['stub'] = ('M%.1f %.1f L%.1f %.1f' % (pa + ta), _arrowhead(ta, (0, s), 5), 'M%.1f %.1f L%.1f %.1f' % (tb + pb), _arrowhead(pb, (0, s), 5))
