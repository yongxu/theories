def lean_names(lean_dir=None) -> set:
    """Last components of every declaration in the Lean sources, for checking that a named theorem exists."""
    names = set()
    pat = re.compile(r'^\s*(?:private\s+|protected\s+|noncomputable\s+)*(?:theorem|lemma|def|abbrev|structure|inductive|class|instance)\s+([^\s:({\[]+)', re.M)
    for base, dirs, files in os.walk(str(lean_dir or ROOT / LEAN)):
        dirs[:] = [x for x in dirs if not x.startswith('.')]
        for f in files:
            if f.endswith('.lean'):
                names.update(m.group(1).split('.')[-1] for m in pat.finditer(Path(base, f).read_text(encoding='utf-8')))
    return names


def validate(d: dict, dyn_ids=None, test_ids=None, lean=None) -> list:
    """What must hold of the data before anything is drawn. Returns a list of errors."""
    E = []
    sheet, P, paths, laid = d['sheet'], d['passages'], d['paths'], d['laid']
    bands = [b['id'] for b in sheet['bands']]
    rows = {r['id']: r for r in sheet['rows']}
    seen_bands = []
    for r in sheet['rows']:
        if r['band'] not in bands: E.append('row %s: unknown band %s' % (r['id'], r['band']))
        if not seen_bands or seen_bands[-1] != r['band']:
            if r['band'] in seen_bands: E.append('row %s: the rows of band %s are not together' % (r['id'], r['band']))
            seen_bands.append(r['band'])
    for kind, things in (('band', sheet['bands']), ('row', sheet['rows']), ('box', sheet['boxes']), ('path', paths['paths']), ('test', laid['tests'])):
        for x in things:
            if not ID.match(str(x.get('id', ''))): E.append('%s %r: an id is letters, digits, dots, dashes and underscores' % (kind, x.get('id')))
    E += ['%s: %r holds markup characters ("<" or "](")' % (name, v[:40]) for name in ('sheet', 'passages', 'paths', 'laid') for v in _strings(d[name]) if '<' in v or '](' in v]
    boxes, cells = {}, {}
    for b in sheet['boxes']:
        if b['id'] in boxes: E.append('box %s: listed twice' % b['id'])
        boxes[b['id']] = b
        if b['row'] not in rows: E.append('box %s: unknown row %s' % (b['id'], b['row']))
        if not 1 <= b['col'] <= NCOL: E.append('box %s: column %s' % (b['id'], b['col']))
        if (b['row'], b['col']) in cells: E.append('box %s: shares a cell with %s' % (b['id'], cells[(b['row'], b['col'])]))
        cells[(b['row'], b['col'])] = b['id']
        for f in ('en', 'zh', 'says_en', 'says_zh', 'eg_en', 'eg_zh'):
            if not b.get(f, '').strip(): E.append('box %s: no %s' % (b['id'], f))
        if PERSON_EN.search(b['en']) or PERSON_ZH.search(PERSON_ZH_OK.sub('', b['zh'])): E.append('box %s: its name uses a word that fits only a person' % b['id'])
        for dn in b.get('dynamics', []):
            if dyn_ids is not None and dn not in dyn_ids: E.append('box %s: %s is not a dynamic of the atlas' % (b['id'], dn))
    for w in sheet['web']:
        for r in w['rows']:
            if r not in rows: E.append('web: unknown row %s' % r)
    seen = set()
    for p in P['passages']:
        k = key(p)
        if k in seen: E.append('passage %s: listed twice' % k)
        seen.add(k)
        if p['from'] not in boxes or p['to'] not in boxes: E.append('passage %s: unknown box' % k); continue
        if p['from'] == p['to']: E.append('passage %s: from a box to itself; say it under stays' % k)
        for w in [p] + p.get('more', []):
            if w['kind'] not in KINDS: E.append('passage %s: unknown kind %s' % (k, w['kind']))
            if not w.get('en', '').strip() or not w.get('zh', '').strip(): E.append('passage %s: a sentence is missing' % k)
            if w.get('laws') and not w.get('readers'): E.append('passage %s: names a theorem and no reader has set its sentence against the Lean' % k)
            elif w.get('laws') and w['readers'] not in (1, 2): E.append('passage %s: readers is 1 or 2' % k)
            if w is not p and (PERSON_EN.search(w.get('en', '')) or PERSON_ZH.search(PERSON_ZH_OK.sub('', w.get('zh', '')))): E.append('passage %s: a further way uses a word that fits only a person' % k)
            if not w.get('laws') and w['kind'] in ('law', 'line', 'needs', 'built'): E.append('passage %s: drawn as %s and names no theorem' % (k, w['kind']))
            for law in w.get('laws', []):
                if lean is not None and law.split('.')[-1] not in lean: E.append('passage %s: %s is not a declaration in the Lean' % (k, law))
        if not p.get('tag_en', '').strip() or not p.get('tag_zh', '').strip(): E.append('passage %s: no tag' % k)
        for f in ('tag_en', 'en'):
            if PERSON_EN.search(p.get(f, '')): E.append('passage %s: %s uses a word that fits only a person' % (k, f))
        for f in ('tag_zh', 'zh'):
            if PERSON_ZH.search(PERSON_ZH_OK.sub('', p.get(f, ''))): E.append('passage %s: %s uses a word that fits only a person' % (k, f))
    for s in P['stays']:
        if s['at'] not in boxes: E.append('stay: unknown box %s' % s['at'])
    ids = set()
    for path in paths['paths']:
        if path['id'] in ids: E.append('path %s: listed twice' % path['id'])
        ids.add(path['id'])
        if not path.get('bands'): E.append('path %s: no bands' % path['id'])
        for b in path.get('bands', []):
            if b not in bands: E.append('path %s: unknown band %s' % (path['id'], b))
        n, on = 0, set()
        for S in path['sections']:
            if S['tone'] not in TONES: E.append('path %s: unknown tone %s' % (path['id'], S['tone']))
            for st in S['steps']:
                n += 1
                if not st.get('say_en', '').strip() or not st.get('say_zh', '').strip(): E.append('path %s step %d: not told' % (path['id'], n))
                if not st.get('on'): E.append('path %s step %d: stands on nothing' % (path['id'], n))
                for ref in st.get('on', []):
                    on.update([ref[4:]] if ref.startswith('box:') else [ref[5:]] if ref.startswith('stay:') else ref.split('>'))
                    if ref.startswith('box:'):
                        if ref[4:] not in boxes: E.append('path %s step %d: unknown box %s' % (path['id'], n, ref))
                    elif ref.startswith('stay:'):
                        if not any(s['at'] == ref[5:] for s in P['stays']): E.append('path %s step %d: nothing is said of staying at %s' % (path['id'], n, ref[5:]))
                    elif ref not in seen and '>'.join(reversed(ref.split('>'))) not in seen: E.append('path %s step %d: no passage %s' % (path['id'], n, ref))
                if st.get('eg') and st['eg'] not in boxes: E.append('path %s step %d: unknown box %s' % (path['id'], n, st['eg']))
                if st.get('test') and st['test']['case'] not in {t['id'] for t in laid['tests']}: E.append('path %s step %d: unknown test %s' % (path['id'], n, st['test']['case']))
        for c in path.get('cast', []):
            if not all(c.get(f, '').strip() for f in ('en', 'zh', 'says_en', 'says_zh')): E.append('path %s: an entry of its cast is not filled' % path['id'])
        for k in path.get('known', []):
            if k['at'] not in on: E.append('path %s: a name it gives stands at %s, which is not on the path' % (path['id'], k['at']))
            elif not boxes.get(k['at'], {}).get('known_en'): E.append('path %s: a name it gives stands at %s, which carries no name others gave' % (path['id'], k['at']))
            if not k.get('en', '').strip() or not k.get('zh', '').strip(): E.append('path %s: a name it gives is empty' % path['id'])
    tids = set()
    for t in laid['tests']:
        if t['id'] in ids or t['id'] in tids: E.append('test %s: its id is used twice' % t['id'])
        tids.add(t['id'])
        if not t.get('pins') or not t.get('test'): E.append('test %s: no pins, or no test named' % t['id']); continue
        if t.get('setting') not in ('built', 'field'): E.append('test %s: its setting is built or field' % t['id'])
        for f in ('en', 'zh', 'line_en', 'line_zh', 'what_en', 'what_zh', 'said_en', 'said_zh', 'seen_en', 'seen_zh', 'broke_en', 'broke_zh'):
            if not t.get(f, '').strip(): E.append('test %s: no %s' % (t['id'], f))
        for rec in t.get('records') or [t['test']]:
            if test_ids is not None and rec not in test_ids: E.append('test %s: %s is not in the tests table' % (t['id'], rec))
        for i, pin in enumerate(t['pins']):
            if pin['at'] not in boxes: E.append('test %s pin %d: unknown box %s' % (t['id'], i + 1, pin['at']))
            if pin.get('found_at') and pin['found_at'] not in boxes: E.append('test %s pin %d: unknown box %s' % (t['id'], i + 1, pin['found_at']))
            if pin['agree'] not in AGREE or pin['how'] not in HOW: E.append('test %s pin %d: agree or how is not a known value' % (t['id'], i + 1))
        for k in t.get('used', []):
            if k not in seen: E.append('test %s: no passage %s' % (t['id'], k))
        for g in t.get('gave', []):
            if 'pin' in g and not 1 <= g['pin'] <= len(t['pins']): E.append('test %s: gave way at a pin it does not have' % t['id'])
            if 'passage' in g and g['passage'] not in seen: E.append('test %s: no passage %s' % (t['id'], g['passage']))
        if t.get('view') and t['view']['at'] not in boxes: E.append('test %s: unknown box %s' % (t['id'], t['view']['at']))
    for b in sheet['boxes']:
        if b['id'] in ids or b['id'].replace('.', '-') in ids | tids: E.append('box %s: its id is also a path or a test' % b['id'])
    return E


