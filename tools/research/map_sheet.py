    tested = collections.defaultdict(list)
    for t in d['laid']['tests']:
        for i, pin in enumerate(t['pins']):
            if t['id'] not in tested[pin['at']]: tested[pin['at']].append(t['id'])
    return dict(W=W, H=H, rows=rows, ri=ri, band_box=band_box, boxes=boxes, P=P, stays=stays, tested=tested)


