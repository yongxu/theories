def _crop(geo: dict, bands) -> tuple:
    """Top and bottom of the picture that shows only these bands (the whole sheet where none are named)."""
    if not bands: return 0, geo['H']
    return max(0, min(geo['band_box'][b][0] for b in bands) - 4), max(geo['band_box'][b][1] for b in bands) + 13


def _inside(geo: dict, bands):
    if not bands: return lambda cid: True
    y0, y1 = _crop(geo, bands)
    return lambda cid: y0 <= geo['boxes'][cid]['y'] <= y1 - 13


