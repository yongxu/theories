def _files(lang: str) -> dict:
    name = lambda p: p.rsplit('/', 1)[1]
    return {'hub': name(PAGE[lang]), 'places': name(PLACES[lang]), 'paths': name(PATHS_PAGE[lang])}


def path_picture_file(path_id: str, lang: str) -> str:
    return '%s/path-%s%s.svg' % (MAP, path_id, '.zh' if lang == 'zh' else '')


def _head(page: str, title: str, lang: str) -> list:
    """A page's title, the generated note and its navigation: the shared line on an English page with a link to its
    Chinese edition, and on a Chinese page the way back to the English one, the Chinese home and the map."""
    rel = lambda target: posixpath.relpath(target, posixpath.dirname(page))
    pairs = {v['en']: v['zh'] for v in (PAGE, PLACES, PATHS_PAGE)}
    if lang == 'zh':
        english = next(en for en, zh in pairs.items() if zh == page)
        return ['# ' + title, '', GENERATED, '', '[English](%s) · [首页](%s) · [地图](%s)' % (rel(english), rel('README.zh.md'), rel(PAGE['zh'])), '']
    return ['# ' + title, '', GENERATED, '', navigation.nav_line(page), '', '[中文](%s)' % rel(pairs[page]), '']


def inputs() -> set:
    return {ROOT / p for p in DATA + (TEMPLATE, DYNAMICS, TESTS)}


def load(root: Path = ROOT):
    """The data, the atlas's dynamics by name and the tests' ids, or the errors."""
    read = lambda path: json.loads((root / path).read_text(encoding='utf-8'))
    try:
        d = {'sheet': read(SHEET), 'passages': read(PASSAGES), 'paths': read(PATHS), 'laid': read(LAID)}
        dyn = {x['id']: (x['name']['en'] if isinstance(x['name'], dict) else x['name']) for x in read(DYNAMICS)}
        tests = {t['id'] for t in read(TESTS)['tests']}
    except (OSError, ValueError, KeyError, TypeError) as e:
        return None, ['%s: the map\'s data cannot be read: %s' % (MAP, e)]
    return (d, dyn, tests), []


def totals(root: Path = ROOT) -> dict:
    """What the account holds in all, counted from the atlas's dynamics and the tests table."""
    dyn = json.loads((root / DYNAMICS).read_text(encoding='utf-8'))
    return {'dynamics': len(dyn), 'exits': sum(len(x.get('exits') or []) for x in dyn), 'transitions': sum(len(x.get('transitions') or []) for x in dyn),
            'all_tests': len(json.loads((root / TESTS).read_text(encoding='utf-8'))['tests'])}


def built_errors(m: dict) -> list:
    """What only the laid-out sheet can show: a path's picture shows its bands, so each box a step stands on lies in
    them, and an arrow that leaves them is one drawn as a stub, which the picture cuts and labels."""
    E, geo = [], m['geo']
    byid = {p['id']: p for p in geo['P']}
    for path in m['paths']:
        inside = _inside(geo, path.get('bands'))
        for sec in path['sections']:
            for st in sec['steps']:
                for r in st['refs']:
                    if 'p' not in r:
                        if not inside(r.get('c') or r['stay']): E.append('path %s step %d: %s lies outside the path\'s bands' % (path['id'], st['n'], r.get('c') or r['stay']))
                        continue
                    p = byid[r['p']]
                    if not (inside(p['from']) or inside(p['to'])): E.append('path %s step %d: the arrow %s lies outside the path\'s bands' % (path['id'], st['n'], p['key']))
                    elif not (inside(p['from']) and inside(p['to'])) and not p['far']:
                        E.append('path %s step %d: the arrow %s leaves the path\'s bands and is drawn in full, so the picture would cut it without a label; name the other band too' % (path['id'], st['n'], p['key']))
    return E


def document(fragment: str) -> str:
    """The page to operate as one document: the fragment's title and styles in the head, the rest in the body."""
    # The site's page takes no font, script or style from elsewhere: the page falls back to the reader's own faces.
    fragment = re.sub(r'<link rel="stylesheet" href="https://fonts\.googleapis\.com[^>]*>\n|<meta name="claude:viewport-fit-sides"[^>]*>\n', '', fragment)
    cut = fragment.index('</style>') + len('</style>')
    return ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
            + GENERATED + '\n<style>:root{color-scheme:light}body{margin:0;font:14px system-ui}img{max-width:100%}[hidden]{display:none!important}</style>\n'
            + fragment[:cut] + '\n</head>\n<body>\n' + fragment[cut:].strip('\n') + '\n</body>\n</html>\n')


def views(m: dict) -> dict:
    """Every view, by its path."""
    out = {INTERACTIVE: document(page(m))}
    below = lambda here: {k: posixpath.relpath(v, posixpath.dirname(here)) for k, v in (('ledger', LEDGER), ('laws', LAWS_PAGE), ('dynamics', DYNAMICS_PAGE), ('cases', CASES_PAGE))}
    for lang in ('en', 'zh'):
        out[PICTURE[lang]] = chart(m['geo'], lang, static=True)
        for p in m['paths']: out[path_picture_file(p['id'], lang)] = path_picture(m, p, lang)
        out[PAGE[lang]] = hub(m, lang, _head(PAGE[lang], '地图' if lang == 'zh' else 'The map', lang), site=SITE + INTERACTIVE, below=below(PAGE[lang]))
        out[PLACES[lang]] = places(m, lang, _head(PLACES[lang], S[lang]['places_title'], lang))
        out[PATHS_PAGE[lang]] = paths_page(m, lang, _head(PATHS_PAGE[lang], S[lang]['paths_title'], lang))
    return out


def render():
    """The views and the errors that stop a render; nothing where the sheet has no data."""
    if not (ROOT / SHEET).is_file():
        return {}, []
    loaded, errors = load()
    if errors:
        return {}, errors
    d, dyn, tests = loaded
    errors = [MAP + ': ' + e for e in validate(d, dyn_ids=set(dyn), test_ids=tests)]
    if errors:
        return {}, errors
    m = build(d); m['dyn_names'] = dyn; m['totals'] = totals()
    errors = [MAP + ': ' + e for e in built_errors(m)]
    if errors:
        return {}, errors
    out = views(m)
    size = len(out[INTERACTIVE].encode('utf-8'))
    if size > MAX_INTERACTIVE:
        return {}, ['%s: %d bytes, over %d: the site takes a page under 2,000,000 bytes' % (INTERACTIVE, size, MAX_INTERACTIVE)]
    return out, []


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description='The map: check its data, or write the map to operate as a page fragment.')
    ap.add_argument('--fragment', metavar='OUT', help='write the map to operate without a document around it (for a host that supplies one)')
    ap.add_argument('--lean', action='store_true', help='also check that every theorem an arrow names is a declaration in the Lean sources')
    args = ap.parse_args(argv)
    loaded, errors = load()
    if not errors:
        d, dyn, tests = loaded
        errors = validate(d, dyn_ids=set(dyn), test_ids=tests, lean=lean_names() if args.lean else None)
    if errors:
        print('\n'.join(errors), file=sys.stderr)
        return 1
    m = build(d); m['dyn_names'] = dyn
    if args.fragment:
        Path(args.fragment).write_text(page(m), encoding='utf-8')
    print(json.dumps(m['counts'], ensure_ascii=False))
    return 0


