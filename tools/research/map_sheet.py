def _wrap(s: str, n: int) -> list:
    out, cur = [], ''
    for w in s.split(' '):
        if cur and len(cur) + 1 + len(w) > n:
            out.append(cur); cur = w
        else:
            cur = (cur + ' ' + w).strip()
    if cur: out.append(cur)
    return out


def _arrowhead(tip, d, size=6.5) -> str:
    dx, dy = d; L = math.hypot(dx, dy) or 1; dx, dy = dx / L, dy / L
    px, py = -dy, dx
    bx, by = tip[0] - dx * size * 1.35, tip[1] - dy * size * 1.35
    return 'M%.1f %.1f L%.1f %.1f L%.1f %.1f Z' % (tip[0], tip[1], bx + px * size * .55, by + py * size * .55, bx - px * size * .55, by - py * size * .55)


def _bar(mid, d, size=6.5) -> str:
    dx, dy = d; L = math.hypot(dx, dy) or 1; px, py = -dy / L, dx / L
    return 'M%.1f %.1f L%.1f %.1f' % (mid[0] + px * size, mid[1] + py * size, mid[0] - px * size, mid[1] - py * size)


def _rounded(pts, r=7.0) -> str:
    pts = [p for i, p in enumerate(pts) if i == 0 or p != pts[i - 1]]
    d = 'M%.1f %.1f' % pts[0]
    def toward(a, b):
        L = math.hypot(b[0] - a[0], b[1] - a[1]) or 1
        t = min(r, L / 2) / L
        return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
    for i in range(1, len(pts) - 1):
        q0, q1 = toward(pts[i], pts[i - 1]), toward(pts[i], pts[i + 1])
        d += ' L%.1f %.1f Q%.1f %.1f %.1f %.1f' % (q0[0], q0[1], pts[i][0], pts[i][1], q1[0], q1[1])
    return d + ' L%.1f %.1f' % pts[-1]


def geometry(d: dict) -> dict:
    """Places every box and routes every arrow. An arrow is drawn in full where it runs along a row, between
    neighbouring rows, or along a clear corridor; any other arrow is a stub at each end, and is routed through
    the gutters between rows and columns when it is lit."""
    sheet = d['sheet']
    GX, CW, BW, BH, RH, BANDH, GAP = (G[k] for k in ('GX', 'CW', 'BW', 'BH', 'RH', 'BANDH', 'GAP'))
    W = GX + NCOL * CW + 6
    rows, ri, band_box, y = {}, [], {}, G['TOP']
    for band in sheet['bands']:
        y0 = y; y += BANDH
        for r in sheet['rows']:
            if r['band'] != band['id']: continue
            rows[r['id']] = dict(r, cy=y + RH / 2, y0=y); ri.append(r['id']); y += RH
        band_box[band['id']] = (y0, y); y += GAP
    H = y - GAP + 4
    boxes, cell = {}, {}
    for b in sheet['boxes']:
        bx = dict(b, x=GX + (b['col'] - 1) * CW + CW / 2, y=rows[b['row']]['cy'])
        boxes[b['id']] = bx; cell[(ri.index(b['row']), b['col'])] = b['id']
    P = [dict(p, id='p%d' % i, key=key(p)) for i, p in enumerate(d['passages']['passages'])]
    both = {(p['from'], p['to']) for p in P}

    def classify(p):
        a, b = boxes[p['from']], boxes[p['to']]
        ra, rb, ca, cb = ri.index(a['row']), ri.index(b['row']), a['col'], b['col']
        if ra == rb:
            return 'adj' if not any((ra, c) in cell for c in range(min(ca, cb) + 1, max(ca, cb))) else 'arc'
        if abs(ra - rb) == 1: return 'near'
        if abs(ca - cb) == 1 and abs(ra - rb) <= 3:   # a corridor: a clear column beside the box, over a few rows
            between = range(min(ra, rb) + 1, max(ra, rb))
            if (ra, cb) not in cell and not any((r, cb) in cell for r in between): return 'ell-to'      # vertical leaves the to-box
            if (rb, ca) not in cell and not any((r, ca) in cell for r in between): return 'ell-from'    # vertical leaves the from-box
        return 'far'
    slots = collections.defaultdict(list)
    for p in P:
        a, b = boxes[p['from']], boxes[p['to']]
        p['cls'] = c = classify(p)
        if c == 'arc':
            side = 'top' if b['x'] > a['x'] else 'bottom'
            slots[(a['id'], side)].append((b['x'], p['id'], 'a')); slots[(b['id'], side)].append((a['x'], p['id'], 'b'))
        elif c in ('near', 'far'):
            down = b['y'] > a['y']
            slots[(a['id'], 'bottom' if down else 'top')].append((b['x'], p['id'], 'a'))
            slots[(b['id'], 'top' if down else 'bottom')].append((a['x'], p['id'], 'b'))
        elif c == 'ell-to':
            slots[(b['id'], 'top' if a['y'] < b['y'] else 'bottom')].append((a['x'], p['id'], 'b'))
        elif c == 'ell-from':
            slots[(a['id'], 'top' if b['y'] < a['y'] else 'bottom')].append((b['x'], p['id'], 'a'))
    off, lane = {}, {}
    for (cid, side), L in slots.items():
        L.sort(); n = len(L); step = min(14, (BW - 26) / max(1, n - 1)) if n > 1 else 0
        for i, (_x, pid, end) in enumerate(L):
            off[(pid, end)] = (i - (n - 1) / 2) * step; lane[(pid, end)] = i
    for p in P:
        a, b, pid, c = boxes[p['from']], boxes[p['to']], p['id'], p['cls']
        oa, ob = off.get((pid, 'a'), 0), off.get((pid, 'b'), 0)
        p['far'] = c == 'far'; p['cross'] = a['row'] != b['row']
        if c == 'adj':
            sgn = 1 if b['x'] > a['x'] else -1
            dy = -9 * sgn if (p['to'], p['from']) in both else 0
            p0, p3 = (a['x'] + sgn * BW / 2, a['y'] + dy), (b['x'] - sgn * BW / 2, b['y'] + dy)
            p['d'] = 'M%.1f %.1f L%.1f %.1f' % (p0 + p3); p['h1'] = _arrowhead(p3, (sgn, 0))
            p['mid'] = ((p0[0] + p3[0]) / 2, p0[1]); p['bar'] = _bar(p['mid'], (1, 0), 7)
            p['tagpos'] = (p['mid'][0], a['y'] - BH / 2 - 6) if sgn > 0 else (p['mid'][0], a['y'] + BH / 2 + 14)
        elif c == 'arc':
            up = b['x'] > a['x']; yy = a['y'] + (-BH / 2 if up else BH / 2)
            p0, p3 = (a['x'] + oa, yy), (b['x'] + ob, yy); cy = yy + (-24 if up else 24)
            p['d'] = 'M%.1f %.1f C%.1f %.1f %.1f %.1f %.1f %.1f' % (p0[0], p0[1], p0[0], cy, p3[0], cy, p3[0], p3[1])
            p['h1'] = _arrowhead(p3, (0, 1 if up else -1)); p['mid'] = ((p0[0] + p3[0]) / 2, yy + (-18 if up else 18)); p['bar'] = _bar(p['mid'], (1, 0), 6)
            p['tagpos'] = (p['mid'][0], p['mid'][1] + (-6 if up else 14))
        elif c == 'near':
            s = 1 if b['y'] > a['y'] else -1
            p0, p3 = (a['x'] + oa, a['y'] + s * BH / 2), (b['x'] + ob, b['y'] - s * BH / 2)
            k = max(14, min(60, abs(p3[1] - p0[1]) * .45)); c1, c2 = (p0[0], p0[1] + s * k), (p3[0], p3[1] - s * k)
            p['d'] = 'M%.1f %.1f C%.1f %.1f %.1f %.1f %.1f %.1f' % (p0 + c1 + c2 + p3); p['h1'] = _arrowhead(p3, (0, s))
            bez = lambda u, i: (1 - u) ** 3 * p0[i] + 3 * (1 - u) ** 2 * u * c1[i] + 3 * (1 - u) * u * u * c2[i] + u ** 3 * p3[i]
            p['mid'] = (bez(.5, 0), bez(.5, 1)); p['bar'] = _bar(p['mid'], (0, 1) if abs(p3[0] - p0[0]) < 40 else (1, 0), 6)
            p['tagpos'] = (p['mid'][0], p['mid'][1] - 6)
        elif c in ('ell-to', 'ell-from'):
            v, h, ov = (b, a, ob) if c == 'ell-to' else (a, b, oa)       # the vertical leg leaves box v; the level leg enters box h at its side
            s = 1 if h['y'] > v['y'] else -1; sg = 1 if h['x'] > v['x'] else -1
            pv, corner, ph = (v['x'] + ov, v['y'] + s * BH / 2), (v['x'] + ov, h['y']), (h['x'] - sg * BW / 2, h['y'])
            pts = [pv, corner, ph] if c == 'ell-from' else [ph, corner, pv]
            p['d'] = _rounded(pts, 10); p['h1'] = _arrowhead(pts[-1], (sg, 0) if c == 'ell-from' else (0, -s))
            p['mid'] = (corner[0], (pv[1] + corner[1]) / 2); p['bar'] = _bar(p['mid'], (0, 1), 6); p['tagpos'] = (corner[0] + 10, p['mid'][1] + 4)
        else:
            s = 1 if b['y'] > a['y'] else -1
            la, lb = min(lane.get((pid, 'a'), 0), 3), min(lane.get((pid, 'b'), 0), 3)
            pa, pb = (a['x'] + oa, a['y'] + s * BH / 2), (b['x'] + ob, b['y'] - s * BH / 2)
            y1, y2 = pa[1] + s * (10 + 5 * la), pb[1] - s * (10 + 5 * lb)
            kcol = b['col'] - 1 if a['col'] < b['col'] else b['col'] if b['col'] < NCOL or a['col'] > b['col'] else b['col'] - 1
