def _L(o, k, lang):
    return o.get(k + '_' + lang) or o.get(k + '_en') or ''


def _nm(o, lang):
    return o['zh'] if lang == 'zh' else o['en']


def _anchor(box_id):
    return 'box-' + box_id.replace('.', '-')


def _arrow(p):
    return ' | ' if p['kind'] == 'line' else ' = ' if p['kind'] == 'same' else ' → '


def _lab(label, lang, alone=False):
    """A bold label: alone on its line, or opening a paragraph."""
    if lang == 'zh': return '**%s：**' % label
    return '**%s.**' % label if alone else '**%s.** ' % label


def _tag(tag, lang):
    """An arrow's tag in bold before its sentence; a tag that asks keeps its own mark."""
    asks = tag[-1:] in '?？!！'
    if lang == 'zh': return '**%s%s**' % (tag, '' if asks else '。')
    return '**%s%s** ' % (tag, '' if asks else '.')


def _note(text, lang):
    return '*（%s）*' % text if lang == 'zh' else ' *(%s)*' % text


def _br(text, lang):
    return '（%s）' % text if lang == 'zh' else ' (%s)' % text


def _col(lang):
    return '：' if lang == 'zh' else ': '


def _stop(text, lang):
    return text.rstrip('.。 ') + ('。' if lang == 'zh' else '.')


def _step_marks(m, st, lang):
    P = {p['id']: p for p in m['geo']['P']}
    r = st['refs'][0]
    k = P[r['p']]['kind'] if 'p' in r else ''
    return _note(S[lang]['kind'][k], lang) if k in ('needs', 'built', 'reading') else ''


def _told(m, path, lang, deep=False, places=''):
    """A path told step by step; with deep, each step is followed by what it stands on."""
    s, boxes, P = S[lang], m['geo']['boxes'], {p['id']: p for p in m['geo']['P']}
    out = []
    for sec in path['sections']:
        out += ['**%s**' % _nm(sec, lang), '']
        for st in sec['steps']:
            line = '%d. %s%s' % (st['n'], _L(st, 'say', lang), _step_marks(m, st, lang))
            if st.get('eg'): line += ('' if lang == 'zh' else ' ') + _L(boxes[st['eg']], 'eg', lang)
            if st.get('test'): line += ' *' + _nm(st['test'], lang) + '*'
            out.append(line)
            if deep:
                for r in st['refs']:
                    if 'c' in r: out.append('    - [%s](%s#%s)' % (_nm(boxes[r['c']], lang), places, _anchor(r['c'])))
                    elif 'stay' in r: out.append('    - [%s](%s#%s)%s%s' % (_nm(boxes[r['stay']], lang), places, _anchor(r['stay']), _col(lang), s['stay_t']))
                    else:
                        p = P[r['p']]
                        out.append('    - [%s](%s#%s)%s[%s](%s#%s)%s%s%s' % (_nm(boxes[p['from']], lang), places, _anchor(p['from']), _arrow(p), _nm(boxes[p['to']], lang), places, _anchor(p['to']),
                                                                         _col(lang), _L(p, 'tag', lang), _note(s['kind'][p['kind']], lang)))
        out.append('')
    return out


def _listed(label, items, lang):
    return label + '：' + '；'.join(items) + '。' if lang == 'zh' else '%s: %s.' % (label, '; '.join(items))


def _known(m, path, lang, places=None):
    """The names a path gives, each a link to the box it stands at where the page of boxes is named."""
    if places is None: return [k[lang] for k in path.get('known', [])]
    return ['[%s](%s#%s)' % (k[lang], places, _anchor(k['at'])) for k in path.get('known', [])]


def _cast(path, lang, fold=False):
    """What is in a path, and the page's own words, set out once before its first step; folded on the page that
    tells the path first, open on the page of paths."""
    if not path.get('cast'): return []
    items = ['- **%s**%s%s' % (_nm(c, lang), _col(lang), _L(c, 'says', lang)) for c in path['cast']]
    if fold: return ['<details><summary>%s</summary>' % S[lang]['cast'], ''] + items + ['', '</details>', '']
    return ['**%s**' % S[lang]['cast'], ''] + items + ['']


def _along(m, lang):
    a = m['counts']['along']
    right = {k[6:]: v for k, v in a.items() if k.startswith('right/')}; left = {k[5:]: v for k, v in a.items() if k.startswith('left/')}
    return S[lang]['along'] % {'r': sum(right.values()), 'rl': right.get('law', 0), 'l': sum(left.values()), 'll': left.get('law', 0), 'ln': left.get('needs', 0), 'lb': left.get('built', 0)}


def _settings(m, lang):
    n = len(m['tests']); field = sum(1 for t in m['tests'] if t.get('setting') == 'field')
    return S[lang]['settings'] % {'n': n, 'built': n - field, 'field': field}


