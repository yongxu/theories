"""Generated mirrors of studies too large for GitHub to render (RW, 8 November 2026).

GitHub renders no Markdown file much over a megabyte. The renewal study is 3.78 MB and its Chinese edition 1.82 MB, and
records, the Lean catalogue and process documents link them. A mirror writes each `##` section of such a file, with the
explicit anchors directly above its heading, to its own page in a generated folder that `_process/research-config.json`
names (`mirrors.folders`, source to folder). A source and its `.zh.md` edition share a folder, the edition's pages
ending in `.zh.md`. Each page holds its section's bytes unchanged except link targets, which are made to point from the
page: a link into a mirrored file goes to the page that now holds its anchor (or its line), or to the folder's index
where it names neither. The index lists every section of every edition in the folder.

A file can keep what remains of a section whose heading is only in its other edition. The renewal study's English file
does, under no heading: its code blocks and tables after the section's anchor. Such a section starts a page too, at the
anchor equal to the other edition's heading, so a link to that anchor lands on what the file keeps of it, and the page
says where the section's heading and text are.

The source stays the source: nothing here changes it, and every render writes the mirror again from it.

`Mirror.section_pages(source)` gives each numbered section the page holding its heading: the first edition, in the
folder's order, that has one. `Mirror.route(source, anchor)` gives the page and anchor where an anchor of a mirrored file
now is. `Mirror.cited(record, source)` gives the sections of a source that a record's history names.
"""
from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field
from functools import lru_cache
import hashlib
import posixpath
import re
from urllib.parse import unquote

from tools.research import moves, navigation

ROOT = navigation.ROOT
PAGE_LIMIT = 1_048_576  # the atlas's and the Lean catalogue's page limit, under what GitHub renders
GENERATED = '<!-- Generated by tools/research/mirror.py from {source}; do not edit. Edit the source, then make research-render. -->'
HEADER_LINES = 4  # the comment, a blank line, the navigation line, a blank line; then the section's own lines
NUMBERED = re.compile(r'(\d+)\.\s')
NUMBERED_HEADING = re.compile(r'^## (\d+)\.\s', re.M)
ANCHOR_LINE = re.compile(r'^<a id="([^"]+)"></a>[ \t]*$')
SETEXT = re.compile(r'^ {0,3}(=+|-+)[ \t]*$')
LIST_ITEM = re.compile(r'^ {0,3}([-*+]|\d+[.)])\s')
LINE_FRAGMENT = re.compile(r'L\d+(-L\d+)?')
MONTHS = 'January|February|March|April|May|June|July|August|September|October|November|December'
NUMBER = r'\d{1,3}(?!\d)(?!\s+(?:' + MONTHS + r')\b)'  # a section number: a year, or a day before its month, is not one
NUMBERS = NUMBER + r'(?:\s*(?:,\s*(?:and\s+)?|and\s+|[–-]\s*)' + NUMBER + r')*'


def citation(stem: str) -> re.Pattern:
    """How a history names a section of the study whose file is `stem`: "study section 358", "study sections 61 and 62",
    "study sections 243–245", "STEM.md, section 221". Group `named` is set where the entry names the file itself. A
    plural takes a list; a singular one number or one range, so that a date after a comma is not read as a section.
    "the naming study, section 7" is another study, and "Main-study section 28" another's shorthand: neither is read."""
    return re.compile(r'(?<![-\w])(?:(?i:study)|(?P<named>' + re.escape(stem) + r'(?:\.zh)?(?:\.md)?[,:]?))'
                      r'\s+(?:(?i:sections)\s+(?P<many>' + NUMBERS + r')|(?i:section)\s+(?P<one>' + NUMBER + r'(?:\s*[–-]\s*' + NUMBER + r')?))')


def folders(config=None) -> dict[str, str]:
    """Mirrored source to its folder, in the configured order (an English source before its edition)."""
    config = navigation.read(navigation.CONFIG) if config is None else config
    return dict(((config.get('mirrors') or {}).get('folders')) or {})


def is_chinese(source: str) -> bool:
    return source.endswith('.zh.md')


def stem_of(source: str) -> str:
    return re.sub(r'(\.zh)?\.md$', '', source.rsplit('/', 1)[-1])


@lru_cache(maxsize=8)
def _mask(text: str) -> str:
    return moves.code_mask(text)


def _lines(text: str) -> list[str]:
    """The lines GitHub numbers, each with its newline."""
    parts = text.split('\n')
    return [p + '\n' for p in parts[:-1]] + ([parts[-1]] if parts[-1] else [])


def heading_offsets(text: str, masked: str | None = None) -> list[tuple[int, str]]:
    """(offset, slug before GitHub's -1, -2 suffixes) of each heading, in order, found as `moves.anchors` finds them:
    ATX and setext, code masked, front matter skipped. `masked` is `moves.code_mask(text)`, where already made."""
    lines = (moves.code_mask(text) if masked is None else masked).split('\n')
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line) + 1)
    start = 0
    if lines and lines[0].strip() == '---':
        for k in range(1, len(lines)):
            if lines[k].strip() in ('---', '...'):
                start = k + 1
                break
    found, previous = [], ''
    for k in range(start, len(lines)):
        line = lines[k]
        m = moves.HEADING.match(line)
        if m:
            found.append((offsets[k], moves.github_slug(m.group(2) or '')))
            previous = ''
            continue
        if previous.strip() and SETEXT.match(line) and not LIST_ITEM.match(previous) \
                and not previous.lstrip().startswith(('|', '>')) and not moves.HEADING.match(previous):
            found.append((offsets[k - 1], moves.github_slug(previous.strip())))
            previous = ''
            continue
        previous = line
    return found


def suffixed(slugs: list[str]) -> list[str]:
    """GitHub's anchors for headings in order: a repeated slug gets -1, -2, ..."""
    counts, out = {}, []
    for slug in slugs:
        n = counts.get(slug, 0)
        counts[slug] = n + 1
        out.append(slug if not n else f'{slug}-{n}')
    return out


def numbered_headings(text: str) -> dict[int, str]:
    """Each numbered `##` heading outside code, to its slug."""
    found = {}
    for line in _lines(_mask(text)):
        m = moves.HEADING.match(line.rstrip('\r\n'))
        if m and len(m.group(1)) == 2 and (n := NUMBERED.match(m.group(2) or '')):
            found.setdefault(int(n.group(1)), moves.github_slug(m.group(2)))
    return found


def ranges(numbers) -> str:
    out = []
    for n in sorted(numbers):
        if out and n == out[-1][1] + 1:
            out[-1][1] = n
        else:
            out.append([n, n])
    return ', '.join(f'{a}–{b}' if a != b else str(a) for a, b in out)


def short(title: str, limit: int = 40) -> str:
    """A label cut at a word, with a mark that it was cut."""
    if len(title) <= limit:
        return title
    return title[:limit].rsplit(' ', 1)[0].rstrip(' ,:;') + '…'


def emit(path: str) -> str:
    """A path as a bare Markdown or HTML target: what either cannot hold, percent-encoded."""
    return re.sub(r'[ ()%#?<>"]', lambda m: '%%%02X' % ord(m.group(0)), path)


@dataclass
class Page:
    source: str
    path: str
    start: int  # offset of the section in the source
    end: int
    first: int  # its first and last line in the source, from 1
    last: int
    number: int | None
    title: str  # the heading's text; empty for a preamble, and for what a file keeps of a section headed only elsewhere
    anchors: dict = field(default_factory=dict)  # anchor in the whole source -> anchor on this page

    @property
    def remnant(self) -> bool:
        return self.number is not None and not self.title


_SPLITS: dict = {}


def split(source: str, text: str, folder: str, foreign: dict[str, int] | None = None) -> list[Page]:
    """The pages of one source: a preamble, then one page from each `##` heading (with the explicit anchor lines directly
    above it) and from each anchor in `foreign` (slug of a numbered heading only another edition has, to its number).
    Headings inside code do not split. Kept for the process by the inputs' hash: records, the render and the Lean catalogue
    each read the mirror."""
    foreign = foreign or {}
    digest = hashlib.sha256((text + repr(sorted(foreign.items()))).encode('utf-8')).hexdigest()
    kept = _SPLITS.get((source, folder))
    if kept is None or kept[0] != digest:  # one version of each source at a time
        kept = _SPLITS[(source, folder)] = (digest, _split(source, text, folder, foreign))
    return kept[1]


def _split(source: str, text: str, folder: str, foreign: dict[str, int]) -> list[Page]:
    lines = _lines(text)
    mask = _mask(text)
    masked = _lines(mask)
    def anchor_of(i):
        m = ANCHOR_LINE.match(masked[i].rstrip('\r\n'))
        return m.group(1) if m else None
    heads = [i for i, line in enumerate(masked) if (m := moves.HEADING.match(line.rstrip('\r\n'))) and len(m.group(1)) == 2]
    marks = {i: foreign[a] for i in range(len(masked)) if (a := anchor_of(i)) in foreign}  # line -> a section headed elsewhere
    starts = {}
    for n, i in enumerate(heads):
        j, floor = i, (heads[n - 1] + 1 if n else 0)
        while j > floor and anchor_of(j - 1) is not None and j - 1 not in marks:
            j -= 1
        starts[j] = i
    starts.update({i: None for i in marks})
    order = sorted(starts)
    bounds = ([0] if not order or order[0] > 0 else []) + order + [len(lines)]
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line))
    suffix = '.zh.md' if is_chinese(source) else '.md'
    pages, used = [], set()
    for a, b in zip(bounds, bounds[1:]):
        head = starts.get(a)
        title = (moves.HEADING.match(lines[head].rstrip('\r\n')).group(2) or '') if head is not None else ''
        m = NUMBERED.match(title)
        number = int(m.group(1)) if m else marks.get(a)
        base = f'{number:03d}' if number is not None else 'preamble' if head is None else (moves.github_slug(title)[:60].strip('-') or 'section')
        name, k = base, 1
        while name in used:
            name, k = f'{base}-{k}', k + 1
        used.add(name)
        pages.append(Page(source, f'{folder}/{name}{suffix}', offsets[a], offsets[b], a + 1, b, number, title))
    # Each anchor of the whole source on the page that holds it: headings renumbered within the page, explicit ids kept.
    heads_all = heading_offsets(text, mask)
    whole = suffixed([s for _, s in heads_all])
    # The id's own offset: a match can begin at an earlier '<' on the page before.
    ids = [(m.start(2), m.group(2)) for m in moves.ANCHOR_ATTR.finditer(mask)]
    for page in pages:
        inside = [(o, s, w) for (o, s), w in zip(heads_all, whole) if page.start <= o < page.end]
        page.anchors.update(zip([w for _, _, w in inside], suffixed([s for _, s, _ in inside])))
        page.anchors.update({i: i for o, i in ids if page.start <= o < page.end})
    return pages


class Mirror:
    """The mirrors of every configured source, read from the tree (or from `texts`, path to text, in tests)."""

    def __init__(self, config=None, root=ROOT, texts=None):
        self.config = navigation.read(navigation.CONFIG) if config is None else config
        self.folders = folders(self.config)
        self.root, self.given = root, texts
        self.texts = {s: (texts[s] if texts is not None else (root / s).read_text(encoding='utf-8')) for s in self.folders}
        headed = {s: numbered_headings(t) for s, t in self.texts.items()}
        self.pages = {}
        for source, text in self.texts.items():
            foreign = {slug: n for e in self.editions(source) if e != source for n, slug in headed[e].items() if n not in headed[source]}
            self.pages[source] = split(source, text, self.folders[source], foreign)
        self.where = {}
        for source, pages in self.pages.items():
            # Where a heading's anchor and an explicit id coincide, a browser goes to the first in the source.
            spots = sorted((p.start, a, p) for p in pages for a in p.anchors)
            first = {}
            for _, anchor, page in spots:
                first.setdefault(anchor, page)
            self.where[source] = {a: (p.path, p.anchors[a]) for a, p in first.items()}
        self._headed_elsewhere: dict[str, set] = {}

    def index(self, source: str) -> str:
        return self.folders[source] + '/README.md'

    def editions(self, source: str) -> list[str]:
        """The sources sharing this source's folder, in the configured order."""
        return [s for s in self.folders if self.folders[s] == self.folders[source]]

    def route(self, source: str, anchor: str):
        """(page, anchor on it) where an anchor of a mirrored source now is, or None if the source has no such anchor.
        Read as the link checker reads one: percent-decoded, then in lower case."""
        where, wanted = self.where.get(source, {}), unquote(anchor)
        return where.get(anchor) or where.get(wanted) or where.get(wanted.lower())

    def line(self, source: str, line: int):
        """(page, line on it) holding a line of a mirrored source, or None."""
        page = next((p for p in self.pages.get(source, []) if p.first <= line <= p.last), None)
        return (page.path, HEADER_LINES + line - page.first + 1) if page else None

    def section_pages(self, source: str) -> dict[int, str]:
        """Each numbered section to the page holding its heading: the first edition in the folder that has one."""
        found = {}
        for edition in self.editions(source):
            for page in self.pages[edition]:
                if page.number is not None and page.title:
                    found.setdefault(page.number, page.path)
        return found

    def first_pages(self, source: str) -> dict[str, str]:
        """Each file a mirrored source links, to the first page whose section links it."""
        found = {}
        for page in self.pages.get(source, []):
            for _, _, raw in moves.links(self.texts[source][page.start:page.end]):
                parts = moves.split_target(raw)
                if parts and parts[0] and (dest := moves.resolve(source, parts[0])):
                    found.setdefault(dest, page.path)
        return found

    @staticmethod
    def citations(record: dict, stem: str) -> list[tuple[list[int], bool]]:
        """Each place a record's history names sections of the study `stem`: its numbers, and whether it names the file."""
        pattern, found = citation(stem), []
        for entry in record.get('history') or []:
            text = entry.get('en', '') if isinstance(entry, dict) else ''
            for m in pattern.finditer(text if isinstance(text, str) else ''):
                spec = m.group('many') or m.group('one')
                numbers = {int(x) for x in re.findall(r'\d+', spec)}
                for a, b in re.findall(r'(\d+)\s*[–-]\s*(\d+)', spec):
                    numbers.update(range(int(a), int(b) + 1))
                found.append((sorted(numbers), bool(m.group('named'))))
        return found

    def headed_elsewhere(self, path: str) -> set:
        """The numbered `##` headings of another Markdown file."""
        if path not in self._headed_elsewhere:
            try:
                text = self.given[path] if self.given is not None and path in self.given else (self.root / path).read_text(encoding='utf-8')
            except OSError:
                text = ''
            self._headed_elsewhere[path] = {int(n) for n in NUMBERED_HEADING.findall(text)}
        return self._headed_elsewhere[path]

    def cited(self, record: dict, source: str) -> list[int]:
        """The sections of `source` a record's history names. "study section N" is the record's own shorthand, and some
        records bind more than one numbered study: a citation that does not name the file, all of whose numbers are `##`
        headings of another study the record binds (a Markdown file under the same research tree; a chapter or a design
        note with numbered headings is not a study), is read as that study's."""
        editions = set(self.editions(source))
        tree = '/'.join(source.split('/')[:2]) + '/'
        others = [p for x in record.get('references') or [] if isinstance(x, dict) and isinstance(p := x.get('path'), str)
                  and p.endswith('.md') and p.startswith(tree) and p not in editions]
        found = set()
        for numbers, named in self.citations(record, stem_of(source)):
            if named or not any(set(numbers) <= self.headed_elsewhere(p) for p in others):
                found.update(numbers)
        return sorted(found)

    def retarget(self, page: Page, body: str, errors: list[str]) -> str:
        """The section's text with every link target the link checker reads made to point from the page."""
        out, last = [], 0
        for start, end, raw in moves.links(body):
            out += [body[last:start], self.target(page, raw, errors)]
            last = end
        return ''.join(out + [body[last:]])

    def target(self, page: Page, raw: str, errors: list[str]) -> str:
        parts = moves.split_target(raw)
        if parts is None:
            return raw
        path, query, fragment = parts
        dest = page.source if not path else moves.resolve(page.source, path)
        if dest is None:
            return raw
        if dest in self.folders:
            names_lines = bool(fragment and LINE_FRAGMENT.fullmatch(fragment))
            spot = self.route(dest, fragment) if fragment and not (names_lines and query == 'plain=1') else None
            if spot is not None:
                dest, fragment = spot
            elif names_lines:
                spots = [self.line(dest, int(n)) for n in re.findall(r'\d+', fragment)]
                if None in spots or len({p for p, _ in spots}) > 1:
                    errors.append(f'{page.path}: {raw} names lines no single page of {dest} holds')
                    return raw
                dest, fragment = spots[0][0], '-'.join(f'L{n}' for _, n in spots)
            elif fragment:
                errors.append(f'{page.path}: {raw} names an anchor {dest} does not have')
                return raw
            else:
                dest, query = self.index(dest), ''
        relative = '' if dest == page.path and fragment and not query else posixpath.relpath(dest or '.', posixpath.dirname(page.path))
        tail = ('?' + query if query else '') + ('#' + fragment if fragment else '')
        return '<' + relative + tail + '>' if raw.startswith('<') else emit(relative) + tail

    def twin(self, page: Page):
        """The same numbered section's page, or the preamble, in another edition."""
        if page.number is None and page.title:
            return None
        return next((p for e in self.editions(page.source) if e != page.source for p in self.pages[e]
                     if p.number == page.number and (p.number is not None or not p.title)), None)

    def keeps(self, page: Page) -> str:
        """What a page holding a section headed only elsewhere has of it: 'anchor' (nothing a reader sees), 'extra' (a line
        outside code that the other edition's page lacks) or 'kept' (only what the other edition has too)."""
        body = self.texts[page.source][page.start:page.end]
        masked = _mask(self.texts[page.source])[page.start:page.end]
        pairs = list(zip(_lines(body), _lines(masked)))
        code = any(raw.strip() and not mask.strip() for raw, mask in pairs)
        text = [raw.strip() for raw, mask in pairs if mask.strip() and not ANCHOR_LINE.match(raw.strip()) and not raw.lstrip().startswith('<!--')]
        if not text and not code:
            return 'anchor'
        twin = self.twin(page)
        other = self.texts[twin.source][twin.start:twin.end] if twin else ''
        held = {line.strip() for line in _lines(other)}
        def absent(line):
            if line in held:
                return False
            if line.startswith('|'):  # a table can keep fewer columns than the other edition: its cells are what must be there
                return any(cell.strip(' -:') and cell.strip() not in other for cell in line.strip('|').split('|'))
            return True
        return 'extra' if any(absent(line) for line in text) else 'kept'

    def nav(self, page: Page, pages: list[Page]) -> str:
        k = pages.index(page)
        name = page.source.rsplit('/', 1)[-1]
        chinese = is_chinese(page.source)
        def label(p):
            return str(p.number) if p.number is not None else ('序' if chinese else 'preamble') if not p.title else short(p.title)
        def step(p):
            return f'[{label(p)}]({posixpath.basename(p.path)})'
        moves_on = (f' · ← {step(pages[k - 1])}' if k else '') + (f' · {step(pages[k + 1])} →' if k + 1 < len(pages) else '')
        twin, base = self.twin(page), None
        if twin is not None:
            base = posixpath.basename(twin.path)
        if chinese:
            where = f'第 {page.number} 节' if page.number is not None else ('序' if not page.title else page.title)
            if twin is None or (twin.remnant and self.keeps(twin) == 'anchor'):
                other = ''
            elif twin.remnant:
                other = f' · [英文文件所留的部分]({base})' + ('（含本版所无的文字）' if self.keeps(twin) == 'extra' else '')
            else:
                other = f' · [英文版]({base})'
            return f'*[{name} 的生成镜像](README.md) · {where}，原文第 {page.first}–{page.last} 行{moves_on}{other}*'
        where = f'section {page.number}' if page.number is not None else ('the preamble' if not page.title else page.title)
        if page.remnant and twin is not None:
            kept = self.keeps(page)
            if kept == 'anchor':
                other = f' · This section\'s heading and text are in the [Chinese edition]({base}); the English file keeps only its anchor here.'
            else:
                other = (f' · This section\'s heading and main text are in the [Chinese edition]({base}); this page holds what the '
                         'English file keeps of it, under no heading.' + (' It also holds lines the Chinese edition does not have.' if kept == 'extra' else ''))
        else:
            other = '' if twin is None else f' · [中文]({base})'
        return f'*[The generated mirror of {name}](README.md) · {where}, lines {page.first}–{page.last} of the source{moves_on}{other}*'

    def page_text(self, page: Page, errors: list[str]) -> str:
        body = self.texts[page.source][page.start:page.end]
        head = '\n'.join([GENERATED.format(source=page.source), '', self.nav(page, self.pages[page.source]), '', ''])
        return head + self.retarget(page, body, errors)

    def index_text(self, folder: str) -> str:
        editions = [s for s in self.folders if self.folders[s] == folder]
        english = next((s for s in editions if not is_chinese(s)), editions[0])
        base = lambda s: s.rsplit('/', 1)[-1]
        named = ' and '.join(f'[{base(s)}]({posixpath.relpath(s, folder)}) ({len(self.texts[s].encode("utf-8")) / 1_000_000:.2f} MB)' for s in editions)
        # One row for each section number, the preamble first, an unnumbered section after the numbered one before it.
        rows = {}
        for s in editions:
            last = 0
            for p in self.pages[s]:
                if p.number is not None:
                    key, last = (p.number, 0, ''), p.number
                else:
                    key = (-1, 0, '') if not p.title else (last, 1, p.title)
                rows.setdefault(key, {})[s] = p
        only = {s: [k[0] for k, r in rows.items() if k[1] == 0 and k[0] >= 0 and s in r and r[s].title
                    and not any(e in r and r[e].title for e in editions if e != s)] for s in editions}
        alone = [(f'section {ranges(only[s])} has a heading' if len(only[s]) == 1 else f'sections {ranges(only[s])} have a heading')
                 + f' only in {base(s)}' for s in editions if only[s] and len(editions) > 1]
        note = ((self.config.get('mirrors') or {}).get('notes') or {}).get(folder)
        lines = [GENERATED.format(source=' and '.join(editions)), '',
                 f'# Mirror of {base(english)}', '',
                 f'A page for each section of {named}: GitHub renders no Markdown file this large. Each page holds what its source '
                 'has at the lines its header names, byte for byte, except link targets, which point from the page: a link to another section goes '
                 'to that section\'s page, and a link to a whole file to this index. Previous and next follow the source\'s order. '
                 'The source is the source, and every render writes this folder again from it.'
                 + (' In the source, ' + '; '.join(alone) + '.' if alone else ''), '']
        lines += [note, ''] if note else []
        lines += ['| § | Section | ' + ' | '.join('中文' if is_chinese(s) else 'English' for s in editions) + ' |',
                  '|---|---|' + '---|' * len(editions)]
        for key in sorted(rows):
            r = rows[key]
            p0 = next((r[s] for s in editions if s in r and r[s].title), None) or next(iter(r.values()))
            title = (NUMBERED.sub('', p0.title, count=1) if p0.number is not None else p0.title) or 'Preamble'
            title = title.replace('|', '\\|')
            def cell(s):
                p = r.get(s)
                if p is None:
                    return '—'
                if p.remnant and self.keeps(p) == 'anchor':
                    return f'[anchor only]({posixpath.basename(p.path)})'
                return f'[{p.last - p.first + 1:,} lines{", no heading" if p.remnant else ""}]({posixpath.basename(p.path)})'
            lines.append(f'| {p0.number if p0.number is not None else "—"} | {title} | ' + ' | '.join(cell(s) for s in editions) + ' |')
        return '\n'.join(lines) + '\n'

    def swallowed(self, source: str) -> list[str]:
        """A section's heading inside code, the next number after the page holding it: an unclosed fence above it, which
        would drop the section from the mirror without a word."""
        found = []
        pages = self.pages[source]
        raw, masked = _lines(self.texts[source]), _lines(_mask(self.texts[source]))
        for i, line in enumerate(raw):
            m = NUMBERED_HEADING.match(line)
            if m and raw[i] != masked[i]:
                numbers = [p.number for p in pages if p.first <= i + 1 and p.number is not None]  # the last numbered page at or above it
                if numbers and int(m.group(1)) == numbers[-1] + 1:
                    found.append(f'mirror: {source} line {i + 1}: the heading of section {m.group(1)} is inside code; is a fence above it unclosed?')
        return found

    def render(self) -> tuple[dict[str, str], list[str]]:
        """Every page and index, and the errors: a link naming an anchor or a line its mirrored file lacks, a page over the
        limit, two sources writing one page, a number twice in one file, a heading swallowed by a fence, an anchor of a
        section headed elsewhere out of order, and a page in the folder that no section writes any more."""
        out, errors = {}, []
        for source, pages in self.pages.items():
            errors += [f'mirror: {source} has {n} sections numbered {k}' for k, n in Counter(p.number for p in pages if p.number is not None).items() if n > 1]
            errors += self.swallowed(source)
            last = None
            for page in pages:
                if page.remnant and last is not None and page.number <= last:
                    errors.append(f'mirror: {source} line {page.first}: an anchor of section {page.number} below section {last}; is it inside a section?')
                last = page.number if page.number is not None else last
            for page in pages:
                if page.path in out:
                    errors.append(f'mirror: {page.path} is written twice')
                out[page.path] = self.page_text(page, errors)
                if len(out[page.path].encode('utf-8')) > PAGE_LIMIT:
                    errors.append(f'mirror: {page.path} is over {PAGE_LIMIT:,} bytes')
        for folder in dict.fromkeys(self.folders.values()):
            out[folder + '/README.md'] = self.index_text(folder)
            directory = self.root / folder
            if directory.is_dir():
                errors += [f'mirror: {folder}/{p.name} is no longer written from its source; remove it' for p in sorted(directory.glob('*.md')) if f'{folder}/{p.name}' not in out]
        return out, ['mirror: ' + e if not e.startswith('mirror: ') else e for e in errors]

    def record_sources(self, record: dict) -> tuple[dict[str, dict], list[str]]:
        """For each reference of a record to a mirrored source: the index and the pages of the sections its history names.
        A named section that no edition in the folder has is an error, not a fallback."""
        rows, errors = {}, []
        mirrored = [x['path'] for x in record.get('references') or [] if isinstance(x, dict) and x.get('path') in self.folders]
        for source in dict.fromkeys(mirrored):
            pages = self.section_pages(source)
            cited = self.cited(record, source)
            errors += [f'{record.get("id")}: its history names section {n} of {source}, which no edition has' for n in cited if n not in pages]
            rows[source] = {'index': self.index(source), 'sections': [(n, pages[n], is_chinese(pages[n])) for n in cited if n in pages]}
        return rows, errors


def render(config=None) -> tuple[dict[str, str], list[str]]:
    return Mirror(config).render()


def inputs(config=None) -> set:
    return {ROOT / s for s in folders(config)}
