"""Generated mirrors of studies too large for GitHub to render (RW, 8 November 2026).

GitHub renders no Markdown file much over a megabyte. The renewal study is 3.78 MB and its Chinese edition 1.82 MB, and
records, the Lean catalogue and process documents link them. A mirror writes each `##` section of such a file, with the
explicit anchors directly above its heading, to its own page in a generated folder that `_process/research-config.json`
names (`mirrors.folders`, source to folder). A source and its `.zh.md` edition share a folder, the edition's pages
ending in `.zh.md`. Each page holds its section's bytes unchanged except link targets, which are made to point from the
page: a link into a mirrored file goes to the page that now holds its anchor (or its line), or to the folder's index
where it names neither. The index lists every section of every edition in the folder.

The source stays the source. Records bind it by hash and cite its sections by number in their history; nothing here
changes it, and every render writes the mirror again from it.

`Mirror.section_pages(source)` gives each numbered section the page holding its text: the first edition, in the
folder's order, with the section's heading. `Mirror.route(source, anchor)` gives the page and anchor where an anchor of
a mirrored file now is. `Mirror.cited(record)` gives the section numbers a record's history names.
"""
from __future__ import annotations

from dataclasses import dataclass, field
import hashlib
import posixpath
import re

from tools.research import moves, navigation

ROOT = navigation.ROOT
PAGE_LIMIT = 1_048_576  # the atlas's and the Lean catalogue's page limit, under what GitHub renders
GENERATED = '<!-- Generated by tools/research/mirror.py from {source}; do not edit. Edit the source, then make research-render. -->'
HEADER_LINES = 4  # the comment, a blank line, the navigation line, a blank line; then the section's own lines
NUMBERED = re.compile(r'(\d+)\.\s')
ANCHOR_LINE = re.compile(r'^<a id="[^"]+"></a>[ \t]*$')
SETEXT = re.compile(r'^ {0,3}(=+|-+)[ \t]*$')
LIST_ITEM = re.compile(r'^ {0,3}([-*+]|\d+[.)])\s')
# "study section 358", "study sections 61 and 62", "study sections 243–245", "Study section 422's"
CITED = re.compile(r'\bstudy sections?\s+(\d+(?:\s*(?:,\s*(?:and\s+)?|and\s+|[–-]\s*)\d+)*)', re.I)


def folders(config=None) -> dict[str, str]:
    """Mirrored source to its folder, in the configured order (an English source before its edition)."""
    config = navigation.read(navigation.CONFIG) if config is None else config
    return dict(((config.get('mirrors') or {}).get('folders')) or {})


def is_chinese(source: str) -> bool:
    return source.endswith('.zh.md')


def heading_offsets(text: str, masked: str | None = None) -> list[tuple[int, str]]:
    """(offset, slug before GitHub's -1, -2 suffixes) of each heading, in order, found as `moves.anchors` finds them:
    ATX and setext, code masked, front matter skipped. `masked` is `moves.code_mask(text)`, where already made."""
    lines = (moves.code_mask(text) if masked is None else masked).split('\n')
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line) + 1)
    start = 0
    if lines and lines[0].strip() == '---':
        for k in range(1, len(lines)):
            if lines[k].strip() in ('---', '...'):
                start = k + 1
                break
    found, previous = [], ''
    for k in range(start, len(lines)):
        line = lines[k]
        m = moves.HEADING.match(line)
        if m:
            found.append((offsets[k], moves.github_slug(m.group(2) or '')))
            previous = ''
            continue
        if previous.strip() and SETEXT.match(line) and not LIST_ITEM.match(previous) \
                and not previous.lstrip().startswith(('|', '>')) and not moves.HEADING.match(previous):
            found.append((offsets[k - 1], moves.github_slug(previous.strip())))
            previous = ''
            continue
        previous = line
    return found


def suffixed(slugs: list[str]) -> list[str]:
    """GitHub's anchors for headings in order: a repeated slug gets -1, -2, ..."""
    counts, out = {}, []
    for slug in slugs:
        n = counts.get(slug, 0)
        counts[slug] = n + 1
        out.append(slug if not n else f'{slug}-{n}')
    return out


@dataclass
class Page:
    source: str
    path: str
    start: int  # offset of the section in the source
    end: int
    first: int  # its first and last line in the source, from 1
    last: int
    number: int | None
    title: str
    anchors: dict = field(default_factory=dict)  # anchor in the whole source -> anchor on this page


_SPLITS: dict = {}


def split(source: str, text: str, folder: str) -> list[Page]:
    """The pages of one source: a preamble before its first `##` heading, then one page for each `##` heading with the
    explicit anchor lines directly above it. Headings inside code do not split. Kept for the process by the text's
    hash, since records, the render and the Lean catalogue each read the mirror."""
    digest = hashlib.sha256(text.encode('utf-8')).hexdigest()
    kept = _SPLITS.get((source, folder))
    if kept is None or kept[0] != digest:  # one version of each source at a time
        kept = _SPLITS[(source, folder)] = (digest, _split(source, text, folder))
    return kept[1]


def _split(source: str, text: str, folder: str) -> list[Page]:
    lines = text.splitlines(keepends=True)
    mask = moves.code_mask(text)
    masked = mask.splitlines(keepends=True)
    heads = [i for i, line in enumerate(masked) if (m := moves.HEADING.match(line.rstrip('\r\n'))) and len(m.group(1)) == 2]
    starts = []
    for n, i in enumerate(heads):
        j, floor = i, (heads[n - 1] + 1 if n else 0)
        while j > floor and ANCHOR_LINE.match(lines[j - 1].rstrip('\r\n')):
            j -= 1
        starts.append(j)
    bounds = ([0] if not starts or starts[0] > 0 else []) + starts + [len(lines)]
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line))
    suffix = '.zh.md' if is_chinese(source) else '.md'
    pages, used = [], set()
    for a, b in zip(bounds, bounds[1:]):
        head = next((i for i in heads if a <= i < b), None)
        title = (moves.HEADING.match(lines[head].rstrip('\r\n')).group(2) or '') if head is not None else ''
        m = NUMBERED.match(title)
        number = int(m.group(1)) if m else None
        base = f'{number:03d}' if number is not None else 'preamble' if head is None else (moves.github_slug(title)[:60].strip('-') or 'section')
        name, k = base, 1
        while name in used:
            name, k = f'{base}-{k}', k + 1
        used.add(name)
        pages.append(Page(source, f'{folder}/{name}{suffix}', offsets[a], offsets[b], a + 1, b, number, title))
    # Each anchor of the whole source on the page that holds it: headings renumbered within the page, explicit ids kept.
    heads_all = heading_offsets(text, mask)
    whole = suffixed([s for _, s in heads_all])
    # The id's own offset: a match can begin at an earlier '<' on the page before.
    ids = [(m.start(2), m.group(2)) for m in moves.ANCHOR_ATTR.finditer(mask)]
    for page in pages:
        inside = [(o, s, w) for (o, s), w in zip(heads_all, whole) if page.start <= o < page.end]
        page.anchors.update(zip([w for _, _, w in inside], suffixed([s for _, s, _ in inside])))
        page.anchors.update({i: i for o, i in ids if page.start <= o < page.end})
    return pages


class Mirror:
    """The mirrors of every configured source, read from the tree (or from `texts`, path to text, in tests)."""

    def __init__(self, config=None, root=ROOT, texts=None):
        self.folders = folders(config)
        self.texts = {s: (texts[s] if texts is not None else (root / s).read_text(encoding='utf-8')) for s in self.folders}
        self.pages = {s: split(s, t, self.folders[s]) for s, t in self.texts.items()}
        self.where = {}
        for source, pages in self.pages.items():
            # Where a heading's anchor and an explicit id coincide, a browser goes to the first in the source.
            spots = sorted((p.start, a, p) for p in pages for a in p.anchors)
            first = {}
            for _, anchor, page in spots:
                first.setdefault(anchor, page)
            self.where[source] = {a: (p.path, p.anchors[a]) for a, p in first.items()}

    def index(self, source: str) -> str:
        return self.folders[source] + '/README.md'

    def editions(self, source: str) -> list[str]:
        """The sources sharing this source's folder, in the configured order."""
        return [s for s in self.folders if self.folders[s] == self.folders[source]]

    def route(self, source: str, anchor: str):
        """(page, anchor on it) where an anchor of a mirrored source now is, or None if the source has no such anchor."""
        return self.where.get(source, {}).get(anchor)

    def line(self, source: str, line: int):
        """(page, line on it) holding a line of a mirrored source, or None."""
        page = next((p for p in self.pages.get(source, []) if p.first <= line <= p.last), None)
        return (page.path, HEADER_LINES + line - page.first + 1) if page else None

    def section_pages(self, source: str) -> dict[int, str]:
        """Each numbered section to the page holding its text: the first edition in the folder with its heading."""
        found = {}
        for edition in self.editions(source):
            for page in self.pages[edition]:
                if page.number is not None:
                    found.setdefault(page.number, page.path)
        return found

    def first_pages(self, source: str) -> dict[str, str]:
        """Each file a mirrored source links, to the first page whose section links it."""
        found = {}
        for page in self.pages.get(source, []):
            for _, _, raw in moves.links(self.texts[source][page.start:page.end]):
                parts = moves.split_target(raw)
                if parts and parts[0] and (dest := moves.resolve(source, parts[0])):
                    found.setdefault(dest, page.path)
        return found

    @staticmethod
    def cited(record: dict) -> list[int]:
        """The section numbers a record's history names ("study section N", "study sections N and M", "N–M")."""
        found = set()
        for entry in record.get('history') or []:
            text = entry.get('en', '') if isinstance(entry, dict) else ''
            for m in CITED.finditer(text if isinstance(text, str) else ''):
                spec = m.group(1)
                for a, b in re.findall(r'(\d+)\s*[–-]\s*(\d+)', spec):
                    found.update(range(int(a), int(b) + 1))
                found.update(int(x) for x in re.findall(r'\d+', spec))
        return sorted(found)

    def retarget(self, page: Page, body: str, errors: list[str]) -> str:
        """The section's text with every link target the link checker reads made to point from the page."""
        out, last = [], 0
        for start, end, raw in moves.links(body):
            out += [body[last:start], self.target(page, raw, errors)]
            last = end
        return ''.join(out + [body[last:]])

    def target(self, page: Page, raw: str, errors: list[str]) -> str:
        parts = moves.split_target(raw)
        if parts is None:
            return raw
        path, query, fragment = parts
        dest = page.source if not path else moves.resolve(page.source, path)
        if dest is None:
            return raw
        if dest in self.folders:
            if query == 'plain=1' and re.fullmatch(r'L\d+(-L\d+)?', fragment or ''):
                lines = [int(x) for x in re.findall(r'\d+', fragment)]
                spots = [self.line(dest, n) for n in lines]
                if None in spots or len({p for p, _ in spots}) > 1:
                    errors.append(f'{page.path}: {raw} names lines no single page of {dest} holds')
                    return raw
                dest, fragment = spots[0][0], '-'.join(f'L{n}' for _, n in spots)
            elif fragment:
                spot = self.route(dest, fragment)
                if spot is None:
                    errors.append(f'{page.path}: {raw} names an anchor {dest} does not have')
                    return raw
                dest, fragment = spot
            elif not query:
                dest = self.index(dest)
        relative = '' if dest == page.path and fragment and not query else posixpath.relpath(dest, posixpath.dirname(page.path))
        target = relative + ('?' + query if query else '') + ('#' + fragment if fragment else '')
        return '<' + target + '>' if raw.startswith('<') or ' ' in target else target

    def nav(self, page: Page, pages: list[Page]) -> str:
        k = pages.index(page)
        name = page.source.rsplit('/', 1)[-1]
        def label(p):
            return str(p.number) if p.number is not None else ('序' if is_chinese(p.source) else 'preamble') if not p.title else p.title[:40]
        def step(p):
            return f'[{label(p)}]({posixpath.basename(p.path)})'
        prev = f' · ← {step(pages[k - 1])}' if k else ''
        nxt = f' · {step(pages[k + 1])} →' if k + 1 < len(pages) else ''
        if is_chinese(page.source):
            where = f'第 {page.number} 节' if page.number is not None else ('序' if not page.title else page.title)
            return f'*[{name} 的生成镜像](README.md) · {where}，原文第 {page.first}–{page.last} 行{prev}{nxt}*'
        where = f'section {page.number}' if page.number is not None else ('the preamble' if not page.title else page.title)
        return f'*[The generated mirror of {name}](README.md) · {where}, lines {page.first}–{page.last} of the source{prev}{nxt}*'

    def page_text(self, page: Page, errors: list[str]) -> str:
        body = self.texts[page.source][page.start:page.end]
        head = '\n'.join([GENERATED.format(source=page.source), '', self.nav(page, self.pages[page.source]), '', ''])
        return head + self.retarget(page, body, errors)

    def index_text(self, folder: str) -> str:
        editions = [s for s in self.folders if self.folders[s] == folder]
        english = next((s for s in editions if not is_chinese(s)), editions[0])
        size = {s: len(self.texts[s].encode('utf-8')) for s in editions}
        def mb(n):
            return f'{n / 1_000_000:.2f} MB'
        named = ', '.join(f'[{s.rsplit("/", 1)[-1]}]({posixpath.relpath(s, folder)}) ({mb(size[s])})' for s in editions)
        # One row for each section number, the preamble first, an unnumbered section after the numbered one before it.
        rows = {}
        for s in editions:
            last = 0
            for p in self.pages[s]:
                if p.number is not None:
                    key, last = (p.number, 0, ''), p.number
                else:
                    key = (-1, 0, '') if not p.title else (last, 1, p.title)
                rows.setdefault(key, {})[s] = p
        only = {}
        for s in editions:
            others = [e for e in editions if e != s]
            nums = [k[0] for k, r in rows.items() if k[1] == 0 and k[0] >= 0 and s in r and not any(e in r for e in others)]
            only[s] = nums
        def ranges(nums):
            out = []
            for n in sorted(nums):
                if out and n == out[-1][1] + 1:
                    out[-1][1] = n
                else:
                    out.append([n, n])
            return ', '.join(f'{a}–{b}' if a != b else str(a) for a, b in out)
        alone = [(f'section {ranges(only[s])} has its text' if len(only[s]) == 1 else f'sections {ranges(only[s])} have their text')
                 + f' only in {s.rsplit("/", 1)[-1]}' for s in editions if only[s] and len(editions) > 1]
        lines = [GENERATED.format(source=' and '.join(editions)), '',
                 f'# Mirror of {english.rsplit("/", 1)[-1]}', '',
                 f'A page for each section of {named}: GitHub renders no Markdown file this large. Each page holds its section\'s '
                 'bytes as the source has them, except link targets, which point from the page; a link to another section goes to '
                 'that section\'s page. The source is the source: records bind it by hash and cite its sections by number, and every '
                 'render writes this folder again from it.' + (' In the source, ' + '; '.join(alone) + '.' if alone else ''), '',
                 '| § | Section | ' + ' | '.join('中文' if is_chinese(s) else 'English' for s in editions) + ' |',
                 '|---|---|' + '---|' * len(editions)]
        for key in sorted(rows):
            r = rows[key]
            p0 = r.get(english) or next(iter(r.values()))
            title = (NUMBERED.sub('', p0.title, count=1) if p0.number is not None else p0.title) or 'Preamble'
            cells = [f'[{(p.last - p.first + 1):,} lines]({posixpath.basename(p.path)})' if (p := r.get(s)) else '—' for s in editions]
            title = title.replace('|', '\\|')
            lines.append(f'| {p0.number if p0.number is not None else "—"} | {title} | ' + ' | '.join(cells) + ' |')
        return '\n'.join(lines) + '\n'

    def render(self) -> tuple[dict[str, str], list[str]]:
        """Every page and index, and the errors: a link naming an anchor or a line its mirrored file lacks, a page over
        the limit, two sources writing one page."""
        out, errors = {}, []
        for source, pages in self.pages.items():
            for page in pages:
                if page.path in out:
                    errors.append(f'mirror: {page.path} is written twice')
                out[page.path] = self.page_text(page, errors)
                if len(out[page.path].encode('utf-8')) > PAGE_LIMIT:
                    errors.append(f'mirror: {page.path} is over {PAGE_LIMIT:,} bytes')
        for folder in dict.fromkeys(self.folders.values()):
            out[folder + '/README.md'] = self.index_text(folder)
        return out, ['mirror: ' + e if not e.startswith('mirror: ') else e for e in errors]

    def record_sources(self, record: dict) -> tuple[dict[str, dict], list[str]]:
        """For each reference of a record to a mirrored source: the index and the pages of the sections its history names.
        A named section that no edition in the folder has is an error, not a fallback."""
        rows, errors = {}, []
        mirrored = [x['path'] for x in record.get('references') or [] if isinstance(x, dict) and x.get('path') in self.folders]
        if not mirrored:
            return rows, errors
        cited = self.cited(record)
        for source in dict.fromkeys(mirrored):
            pages = self.section_pages(source)
            missing = [n for n in cited if n not in pages]
            errors += [f'{record.get("id")}: its history names study section {n}, which no edition of {source} has' for n in missing]
            rows[source] = {'index': self.index(source),
                            'sections': [(n, pages[n], is_chinese(pages[n])) for n in cited if n in pages]}
        return rows, errors


def render(config=None) -> tuple[dict[str, str], list[str]]:
    mirror = Mirror(config)
    return mirror.render()


def inputs(config=None) -> set:
    return {ROOT / s for s in folders(config)}
