# ---------------------------------------------------------------- git and bytes

def git(root: Path, *args: str, data: bytes | None = None) -> bytes:
    return subprocess.run(['git', *args], cwd=root, input=data, stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, check=True).stdout


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def tracked(root: Path) -> dict[str, str]:
    """Tracked path -> index blob id."""
    out = {}
    for entry in git(root, 'ls-files', '-s', '-z').split(b'\0'):
        if entry:
            meta, name = entry.split(b'\t', 1)
            out[name.decode()] = meta.split()[1].decode()
    return out


def gitlinks(root: Path) -> set[str]:
    """Tracked submodule paths (mode 160000): their contents belong to another repository."""
    out = set()
    for entry in git(root, 'ls-files', '-s', '-z').split(b'\0'):
        if entry.startswith(b'160000 '):
            out.add(entry.split(b'\t', 1)[1].decode())
    return out


def ignored_paths(root: Path, candidates) -> set[str]:
    """The candidates git's ignore rules exclude (they need not exist)."""
    candidates = sorted(set(candidates))
    if not candidates:
        return set()
    out = subprocess.run(['git', 'check-ignore', '--stdin', '-z'], cwd=root, input='\0'.join(candidates).encode(),
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE).stdout
    return {p for p in out.decode().split('\0') if p}


def untracked(root: Path, ignored: bool = False) -> list[str]:
    args = ['ls-files', '--others', '-z'] + (['--ignored', '--exclude-standard'] if ignored else ['--exclude-standard'])
    return [p for p in git(root, *args).decode().split('\0') if p]


def inventory(root: Path) -> list[str]:
    return sorted(set(tracked(root)) | set(untracked(root)))


def directories(files) -> set[str]:
    out = set()
    for f in files:
        d = posixpath.dirname(f)
        while d and d not in out:
            out.add(d)
            d = posixpath.dirname(d)
    return out


def write_atomic(path: Path, data: bytes):
    mode = path.stat().st_mode if path.exists() else None
    fd, temporary = tempfile.mkstemp(dir=path.parent, prefix=f'.{path.name}.')
    with os.fdopen(fd, 'wb') as stream:
        stream.write(data)
    if mode is not None:
        os.chmod(temporary, mode & 0o7777)
    os.replace(temporary, path)


# ---------------------------------------------------------------- Markdown links and anchors

def code_mask(text: str) -> str:
    """The text with fenced code blocks and inline code spans blanked (same offsets)."""
    out = list(text)
    pos, fence = 0, None
    for line in text.splitlines(keepends=True):
        stripped = line.lstrip(' ')
        indent = len(line) - len(stripped)
        m = re.match(r'(`{3,}|~{3,})', stripped) if indent <= 3 else None
        if fence is None and m:
            fence = m.group(1)
            blank = True
        elif fence is not None:
            blank = True
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence) and not stripped[len(m.group(1)):].strip():
                fence = None
        else:
            blank = False
        if blank:
            for i in range(pos, pos + len(line)):
                if out[i] != '\n':
                    out[i] = ' '
        pos += len(line)
    masked = ''.join(out)
    # Inline code: a run of n backticks closes at the next run of exactly n, within a paragraph.
    runs = [(m.start(), m.end()) for m in re.finditer(r'`+', masked)]
    by_length = defaultdict(list)
    for k, (a, b) in enumerate(runs):
        by_length[b - a].append(k)
    position = {k: i for ks in by_length.values() for i, k in enumerate(ks)}
    result, k, done = list(masked), 0, -1
    while k < len(runs):
        a, b = runs[k]
        if a < done:
            k += 1
            continue
        same = by_length[b - a]
        i = position[k] + 1
        while i < len(same) and runs[same[i]][0] < done:
            i += 1
        if i < len(same) and '\n\n' not in masked[b:runs[same[i]][0]]:
            end = runs[same[i]][1]
            for x in range(a, end):
                if result[x] != '\n':
                    result[x] = ' '
            done = end
        k += 1
    return ''.join(result)


INLINE = re.compile(r'\]\(')
# Inline TeX on one line, \( ... \): `[EX](0)` inside it is notation, not a link.
TEX_INLINE = re.compile(r'\\\(.*?\\\)')
REFDEF = re.compile(r'^ {0,3}\[(?!\^)[^\]\n]+\]:[ \t]*(<[^>\n]*>|\S+)', re.M)
HTMLREF = re.compile(r'<(?:a|img|source|link)\b[^>]*?\s(?:href|src)\s*=\s*(["\'])([^"\'\n]*)\1', re.I)


def links(text: str):
    """(start, end, raw) for every link target outside code and inline TeX: inline, reference and HTML."""
    masked = TEX_INLINE.sub(lambda m: re.sub(r'[^\n]', ' ', m.group(0)), code_mask(text))
    found = []
    for m in INLINE.finditer(masked):
        i = m.end()
        if i < len(masked) and masked[i] == '<':
            j = masked.find('>', i)
            if j < 0 or '\n' in masked[i:j]:
                continue
            found.append((i, j + 1, text[i:j + 1]))
            continue
        while i < len(masked) and masked[i] in ' \t':
            i += 1
        start, depth = i, 0
        while i < len(masked):
            c = masked[i]
            if c in ' \t\n':
                break
            if c == '(':
                depth += 1
            elif c == ')':
                if depth == 0:
                    break
                depth -= 1
            i += 1
        if i > start:
            found.append((start, i, text[start:i]))
    for m in REFDEF.finditer(masked):
        found.append((m.start(1), m.end(1), text[m.start(1):m.end(1)]))
    for m in HTMLREF.finditer(masked):
        found.append((m.start(2), m.end(2), text[m.start(2):m.end(2)]))
    return sorted(found)


def split_target(raw: str):
    """(path, query, fragment) of a link target, or None for an external or empty one."""
    target = raw[1:-1] if raw.startswith('<') and raw.endswith('>') else raw
    if not target or SCHEME.match(target) or target.startswith('//'):
        return None
    path, _, fragment = target.partition('#')
    path, _, query = path.partition('?')
    return path, query, fragment


def resolve(referrer: str, path: str) -> str | None:
    """The repository-relative path a link names, or None outside the repository."""
    path = unquote(path)
    joined = path.lstrip('/') if path.startswith('/') else posixpath.join(posixpath.dirname(referrer), path)
    normal = posixpath.normpath(joined) if joined else ''
    if normal in ('.', ''):
        return ''
    if normal == '..' or normal.startswith('../'):
        return None
    return normal


def slug_text(heading: str) -> str:
    heading = re.sub(r'!\[([^\]]*)\]\([^)]*\)', r'\1', heading)
    heading = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', heading)
    heading = re.sub(r'\[([^\]]*)\]\[[^\]]*\]', r'\1', heading)
    heading = re.sub(r'<[^>]*>', '', heading)
    heading = heading.replace('`', '')
    heading = re.sub(r'(?<![\w])[*_]+|[*_]+(?![\w])', '', heading)
    heading = re.sub(r'&(?:[a-zA-Z]+|#\d+);', '', heading)
    return heading


def github_slug(heading: str) -> str:
    """GitHub's heading anchor: lowercase, keep letters, marks, numbers (CJK included),
    `_`, `-` and spaces; drop other punctuation and symbols; spaces become `-`."""
    text = slug_text(heading).strip().lower()
    kept = ''.join(c for c in text if c in ' -' or unicodedata.category(c)[0] in 'LMN' or unicodedata.category(c) == 'Pc')
    return kept.replace(' ', '-')


HEADING = re.compile(r'^ {0,3}(#{1,6})(?:[ \t]+(.*?))?(?:[ \t]+#+)?[ \t]*$')
ANCHOR_ATTR = re.compile(r'<[A-Za-z][^>]*?\s(?:id|name)\s*=\s*(["\'])([^"\']+)\1')


def anchors(text: str) -> set[str]:
    """Heading anchors (ATX and setext, with GitHub's -1, -2 suffixes) and explicit ids."""
    masked = code_mask(text)
    lines = masked.split('\n')
    start = 0
    if lines and lines[0].strip() == '---':  # YAML front matter is not a heading
        for k in range(1, len(lines)):
            if lines[k].strip() in ('---', '...'):
                start = k + 1
                break
    found, counts = set(), {}

    def add(heading):
        slug = github_slug(heading)
        n = counts.get(slug, 0)
        counts[slug] = n + 1
        found.add(slug if not n else f'{slug}-{n}')

    previous = ''
    for k in range(start, len(lines)):
        line = lines[k]
        m = HEADING.match(line)
        if m:
            add(m.group(2) or '')
            previous = ''
            continue
        if previous.strip() and re.match(r'^ {0,3}(=+|-+)[ \t]*$', line) and not re.match(r'^ {0,3}([-*+]|\d+[.)])\s', previous) \
                and not previous.lstrip().startswith(('|', '>')) and not HEADING.match(previous):
            add(previous.strip())
            previous = ''
            continue
        previous = line
    found |= {m.group(2) for m in ANCHOR_ATTR.finditer(masked)}
    return found


def line_of(text: str, offset: int) -> int:
    return text.count('\n', 0, offset) + 1


def link_spans(text: str):
    """(start, end) of every Markdown link target in `text`, sorted."""
    return [(a, b) for a, b, _raw in links(text)]


def inside(offset: int, spans) -> bool:
    import bisect
    if not spans:
        return False
    k = bisect.bisect_right(spans, (offset, float('inf'))) - 1
    return k >= 0 and spans[k][0] <= offset < spans[k][1]


# ---------------------------------------------------------------- link checking

def check_links(root: Path = ROOT, only=None, classifier=None, include_generated: bool = True):
    """Broken relative links and anchors in live (and generated) Markdown files."""
    classifier = classifier or path_roles.Classifier(root=root)
    files = inventory(root)
    present = set(files)
    dirs = directories(files)
    submodules = gitlinks(root)
    roles_ok = {'live', 'generated'} if include_generated else {'live'}
    selected = [f for f in files if f.endswith('.md') and classifier.role(f) in roles_ok
                and (not only or any(f == p.rstrip('/') or f.startswith(p.rstrip('/') + '/') for p in only))]
    anchor_cache: dict[str, set[str]] = {}

    def anchors_of(path):
        if path not in anchor_cache:
            try:
                anchor_cache[path] = anchors((root / path).read_text(errors='replace'))
            except OSError:
                anchor_cache[path] = set()
        return anchor_cache[path]

    broken, checked, absent = [], 0, []
    for referrer in selected:
        try:
            text = (root / referrer).read_text(errors='replace')
        except OSError:
            continue
        for start, _end, raw in links(text):
            parts = split_target(raw)
            if parts is None:
                continue
            path, _query, fragment = parts
            checked += 1
            kind = None
            if not path:
                target = referrer
            else:
                target = resolve(referrer, path)
                if target is None:
                    kind = 'outside-repository'
                elif target == '':
                    target = None  # the repository root
                elif target not in present and target.rstrip('/') not in dirs:
                    kind = 'absolute-path' if path.startswith('/') else 'missing-path'
            if kind is None and fragment and target and target.endswith('.md') and target in present:
                wanted = unquote(fragment)
                found = anchors_of(target)
                if wanted not in found and wanted.lower() not in found and not re.fullmatch(r'L\d+(-L\d+)?', wanted):
                    kind = 'missing-anchor'
            if kind:
                item = {'file': referrer, 'line': line_of(text, start), 'target': raw, 'kind': kind,
                        'role': classifier.role(referrer)}
                if kind == 'missing-path' and any(target == s or target.startswith(s + '/') for s in submodules):
                    item['kind'] = 'in-submodule'
                    absent.append(item)
                elif kind == 'missing-path':
                    absent.append(item)  # settled below: ignored by git, or broken
                else:
                    broken.append(item)
    # A missing target that git's ignore rules exclude is kept outside the repository by design
    # (a recording kept locally, say); it is listed, not counted as broken.
    ignored = ignored_paths(root, {resolve(a['file'], split_target(a['target'])[0]).rstrip('/')
                                   for a in absent if a['kind'] == 'missing-path'})
    local_only = []
    for a in absent:
        if a['kind'] == 'missing-path' and resolve(a['file'], split_target(a['target'])[0]).rstrip('/') in ignored:
            a['kind'] = 'ignored-by-git'
        (local_only if a['kind'] != 'missing-path' else broken).append(a)
    broken.sort(key=lambda b: (b['file'], b['line']))
    by_dir, by_kind, by_role = defaultdict(int), defaultdict(int), defaultdict(int)
    for b in broken:
        by_dir[posixpath.dirname(b['file']) or '.'] += 1
        by_kind[b['kind']] += 1
        by_role[b['role']] += 1
    return {'files_checked': len(selected), 'links_checked': checked, 'broken': len(broken),
            'broken_by_kind': dict(sorted(by_kind.items())), 'broken_by_role': dict(sorted(by_role.items())),
            'by_directory': dict(sorted(by_dir.items(), key=lambda kv: (-kv[1], kv[0]))),
            'list': broken,
            'not_in_repository': local_only,
            'scope': 'Relative links and #anchors in live and generated Markdown (paths.py roles); history, evidence, '
                     'sources and scratch are frozen and not checked. Paths must match tracked or untracked files exactly. '
                     'Targets inside a submodule or excluded by .gitignore are listed under not_in_repository, not counted.'}


# ---------------------------------------------------------------- the move plan

class Plan:
    def __init__(self, entries, root: Path = ROOT, settings: dict | None = None, batch: str | None = None,
                 plan_name: str = 'plan', keep_references: bool = False):
        self.root = root
        self.keep_references = keep_references
        self.kept = []
        self.settings = path_roles.load_config(root) if settings is None else settings
        self.classifier = path_roles.Classifier(self.settings, root)
        self.entries = entries
        today = _dt.date.today().isoformat()
        self.batch = batch or f'moves-{today}-{re.sub(r"[^A-Za-z0-9._-]+", "-", plan_name)}'
        self.receipts = self.settings.get('move_receipts', DEFAULT_RECEIPTS).rstrip('/')

    # ---- plan reading
    @staticmethod
    def read(path: Path):
        entries = []
        for n, line in enumerate(path.read_text().splitlines(), 1):
            if not line.strip() or line.lstrip().startswith('#'):
                continue
            cells = line.split('\t')
            if n == 1 and cells[0].strip() == 'old_path':
                continue
            if len(cells) < 3 or not cells[0].strip() or not cells[1].strip() or not cells[2].strip():
                raise ValueError(f'{path}:{n}: expected old_path<TAB>new_path<TAB>reason')
            entries.append({'line': n, 'old': cells[0].strip(), 'new': cells[1].strip(), 'reason': cells[2].strip()})
        return entries

    # ---- pins
    def pins(self, files: dict[str, str]):
        """(glob patterns, pinned files, pinned directory prefixes, why) from config and freezes."""
        patterns = list(self.settings.get('move_pinned', []))
        manifests = self.settings.get('move_pin_manifests', DEFAULT_PIN_MANIFESTS)
        pinned, prefixes, why = set(), set(), {}
        names = [f for f in files if path_roles.matches(f, manifests, re.I)]
        dirs = directories(files)
        for manifest in names:
            pinned.add(manifest)
            why.setdefault(manifest, f'freeze manifest {manifest}')
            try:
                data = json.loads((self.root / manifest).read_text())
            except (OSError, ValueError):
                continue
            base = posixpath.dirname(manifest)
            for s in strings(data, keys=True):
                for candidate in (s, posixpath.normpath(posixpath.join(base, s))):
                    candidate = candidate.split('#', 1)[0].rstrip('/')
                    if candidate in files:
                        pinned.add(candidate)
                        why.setdefault(candidate, f'pinned by {manifest}')
                    elif candidate in dirs and candidate.count('/') >= 2:
                        prefixes.add(candidate)
                        why.setdefault(candidate, f'directory pinned by {manifest}')
        return patterns, pinned, prefixes, why

    # ---- analysis
    def analyse(self):
        root = self.root
        files = tracked(root)
        others = set(untracked(root))
        dirs = directories(files)
        patterns, pinned, pinned_dirs, why = self.pins(files)
        conflicts, moves, seen_old, seen_new = [], [], {}, {}
        file_map, dir_map = {}, {}
        status = self.status([e['old'] for e in self.entries if not bad_path(e['old'])])
        leftovers = []
        for e in self.entries:
            old, new = e['old'].rstrip('/'), e['new'].rstrip('/')
            e['old'], e['new'] = old, new
            problems = []
            if bad_path(old) or bad_path(new):
                problems.append('paths must be repository-relative without ..')
            elif old == new or new.startswith(old + '/'):
                problems.append('new path is the old path or inside it')
            members = []
            if not problems:
                if old in files:
                    members = [(old, new)]
                    e['kind'] = 'file'
                elif old in dirs:
                    members = [(f, new + f[len(old):]) for f in sorted(files) if f.startswith(old + '/')]
                    e['kind'] = 'directory'
                else:
                    problems.append('old path missing (not a tracked file or directory)')
                if (root / new).exists() or new in files or new in dirs or new in others:
                    problems.append('target exists')
            for f, n in members:
                reason = pin_reason(f, patterns, pinned, pinned_dirs, why)
                if reason:
                    problems.append(f'pinned: {f} ({reason})')
                if f in status.get('modified', set()):
                    problems.append(f'uncommitted change: {f}')
                if (root / n).exists() or n in files:
                    problems.append(f'target exists: {n}')
                if n in seen_new:
                    problems.append(f'two files move to {n}')
                if f in seen_old:
                    problems.append(f'{f} is in two plan entries (line {seen_old[f]})')
                seen_old[f], seen_new[n] = e['line'], f
            extra = [p for p in status.get('untracked', set()) | status.get('ignored', set())
                     if p == old or p.startswith(old + '/')]
            if extra:
                leftovers.append({'entry': old, 'untracked_or_ignored': sorted(extra)})
            e['extra'] = sorted(extra)
            e['conflicts'] = problems[:50] + ([f'... and {len(problems) - 50} more'] if len(problems) > 50 else [])
            if problems:
                conflicts.append({'line': e['line'], 'old': old, 'new': new, 'problems': e['conflicts']})
            e['members'] = members
            for f, n in members:
                file_map[f] = n
                moves.append({'old_path': f, 'new_path': n, 'blob': files[f], 'reason': e['reason'], 'plan_entry': old})
            if e.get('kind') == 'directory':
                for d in directories([f for f, _ in members]) | {old}:
                    if d == old or d.startswith(old + '/'):
                        dir_map[d] = new + d[len(old):]
        for f in sorted(set(seen_new) & set(seen_old)):
            conflicts.append({'line': seen_old[f], 'old': f, 'new': file_map[f], 'problems': ['a path is both moved and a target']})
        for m in moves:
            p = root / m['old_path']
            m['sha256'] = sha256(p) if p.is_file() else None
        self.files, self.file_map, self.dir_map = files, file_map, dir_map
        self.moves, self.conflicts, self.leftovers = moves, conflicts, leftovers
        self.rewrites, self.generated_refs, self.unrewritten, self.frozen_refs, self.outgoing = self.references()
        return self

    def status(self, olds):
        if not olds:
            return {}
        out = git(self.root, 'status', '--porcelain=v1', '-z', '--untracked-files=all', '--ignored=matching', '--', *olds)
        found = defaultdict(set)
        items = out.decode().split('\0')
        i = 0
        while i < len(items):
            item = items[i]
            i += 1
            if not item:
                continue
            code, name = item[:2], item[3:]
            if code[0] in 'RC':
                i += 1  # the original name follows
            if code == '??':
                found['untracked'].add(name.rstrip('/'))
            elif code == '!!':
                found['ignored'].add(name.rstrip('/'))
            else:
                found['modified'].add(name)
        return found

    def relocate(self, path: str):
        if path in self.file_map:
            return self.file_map[path]
        bare = path.rstrip('/')
        if bare in self.dir_map:
            return self.dir_map[bare] + ('/' if path.endswith('/') and bare else '')
        return None

    def relocate_string(self, s: str):
        """The rewritten form of a repository-relative path string, or None."""
        m = re.match(r'([^#?:\s]+)(.*)\Z', s, re.S)
        if not m:
            return None
        head, rest = m.groups()
        if rest and rest[0] not in '#?:':
            return None
        moved = self.relocate(head)
        return moved + rest if moved is not None else None

    # ---- references
    EXCLUDED = ('sources/', '_process/architecture/history/')

    def candidates(self, needles) -> set[str]:
        """Tracked and untracked (not ignored) text files outside sources/ and the record
        snapshot store that contain any of `needles`. ripgrep's Aho-Corasick search when it is
        installed (git grep tries each of thousands of patterns in turn), else git grep."""
        if not needles:
            return set()
        with tempfile.NamedTemporaryFile('w', suffix='.txt', delete=False) as stream:
            stream.write('\n'.join(sorted(needles)) + '\n')
            name = stream.name
        try:
            rg = shutil.which('rg')
            if rg:
                inventory_set = set(self.files if getattr(self, 'files', None) else tracked(self.root)) | set(untracked(self.root))
                command = [rg, '-l', '-0', '-F', '--hidden', '--no-messages', '-f', name, '-g', '!.git']
                command += [x for prefix in self.EXCLUDED for x in ('-g', '!/' + prefix + '**')]
                out = subprocess.run(command, cwd=self.root, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
                if out.returncode in (0, 1):
                    found = {p[2:] if p.startswith('./') else p for p in out.stdout.decode().split('\0') if p}
                    # Tracked files that a .gitignore rule covers are searched by name.
                    forced = [p for p in git(self.root, 'ls-files', '-ci', '--exclude-standard', '-z').decode().split('\0')
                              if p and not p.startswith(self.EXCLUDED)]
                    if forced:
                        more = subprocess.run([rg, '-l', '-0', '-F', '--no-messages', '-f', name, '--', *forced],
                                              cwd=self.root, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
                        found |= {p for p in more.stdout.decode().split('\0') if p}
                    return {p for p in found if p in inventory_set and not self.binary(p)}
            out = subprocess.run(['git', 'grep', '-I', '-l', '-z', '--untracked', '-F', '-f', name, '--',
                                  *[':(exclude)' + prefix for prefix in self.EXCLUDED]],
                                 cwd=self.root, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        finally:
            os.unlink(name)
        if out.returncode not in (0, 1):
            raise ValueError('git grep failed: ' + out.stderr.decode()[:500])
        return {p for p in out.stdout.decode().split('\0') if p}

    def binary(self, path: str) -> bool:
        """git grep -I's test: a NUL byte in the first 8000 bytes."""
        try:
            with (self.root / path).open('rb') as stream:
                return b'\0' in stream.read(8000)
        except OSError:
            return True

    def references(self):
        moved = set(self.file_map)
        rewrites, unrewritten, generated, frozen = self.scan(moved)
        after = (set(self.files) - moved) | set(self.file_map.values()) | set(untracked(self.root))
        after_dirs = directories(after)
        for r in rewrites:
            for c in r['changes']:
                if c['kind'] == 'markdown-link':
                    target = resolve(r['path'], split_target(c['new'])[0]) if split_target(c['new']) else None
                    c['resolves'] = target is not None and (target in after or target.rstrip('/') in after_dirs)
        if self.keep_references:
            # The vacated paths receive new files afterwards (H1-replace, H6-replace): live
            # references keep naming them, so nothing is rewritten; they are reported.
            self.kept = rewrites + [{'path': m['file'], 'changes': [{'kind': 'path-mention', 'line': m['line'], 'old': m['path']}]}
                                    for m in unrewritten]
            rewrites, unrewritten = [], []
        outgoing = self.outgoing_links(after, after_dirs)
        return rewrites, generated, unrewritten, frozen, outgoing

    def scan(self, skip):
        """(rewrites, unrewritten mentions, generated pages, frozen referrers by role) for the
        files that name a path in file_map/dir_map; `skip` names files never treated as referrers."""
        olds = set(self.file_map) | set(self.dir_map)
        full = self.candidates(olds)
        names = {posixpath.basename(p) for p in olds}
        md_candidates = {p for p in self.candidates({n for n in names if n}) if p.endswith('.md')}
        json_globs = self.settings.get('move_rewrite_json', DEFAULT_REWRITE_JSON)
        extra_globs = self.settings.get('move_rewrite_extra', [])
        md_mentions = self.settings.get('move_rewrite_markdown_mentions', True)
        mention_exclude = self.settings.get('move_mentions_exclude', [])
        rewrites, generated, unrewritten, frozen = [], [], [], defaultdict(int)
        for path in sorted(full | md_candidates):
            if path in skip:
                continue
            role = self.classifier.role(path)
            p = self.root / path
            if not p.is_file():
                continue
            if role != 'live':
                if role == 'generated':
                    generated.append(path)
                else:
                    frozen[role] += 1
                continue
            try:
                text = p.read_text()
            except (OSError, UnicodeDecodeError):
                continue
            if GENERATED_MARK in text[:2000] and path.endswith('.md'):
                generated.append(path)
                continue
            changes, new = [], text
            markdown = path.endswith('.md')
            mentioned = markdown and md_mentions and not path_roles.matches(path, mention_exclude)
            if markdown:
                new, changes = self.rewrite_markdown(path, new)
                # Exact repository-relative path strings in prose and code (`a/b/C.md`) are
                # what readers follow; link targets were handled above.
                if mentioned:
                    new, more = self.rewrite_mentions(new, skip=link_spans(new), multi=True)
                    changes += more
            if path_roles.matches(path, json_globs) and path.endswith('.json'):
                new, more = self.rewrite_json(path, new)
                changes += more
            elif not markdown and path_roles.matches(path, extra_globs):
                new, more = self.rewrite_mentions(new)
                changes += more
            if changes:
                rewrites.append({'path': path, 'old_sha256': sha256_bytes(text.encode()), 'new_sha256': sha256_bytes(new.encode()),
                                 'changes': changes, '_text': new})
            if mentioned:
                continue  # every multi-component mention outside link targets was rewritten
            for m in self.mentions(new, path, skip=link_spans(new) if markdown else ()):
                unrewritten.append(m)
        return rewrites, unrewritten, sorted(set(generated)), dict(frozen)

    def rewrite_markdown(self, referrer: str, text: str):
        changes, out, last = [], [], 0
        for start, end, raw in links(text):
            parts = split_target(raw)
            if not parts or not parts[0]:
                continue
            path, query, fragment = parts
            target = resolve(referrer, path)
            if target is None or target == '':
                continue
            moved = self.relocate(target + ('/' if path.endswith('/') else ''))
            if moved is None:
                continue
            rel = posixpath.relpath(moved.rstrip('/'), posixpath.dirname(referrer) or '.')
            if path.endswith('/'):
                rel += '/'
            if path.startswith('./') and not rel.startswith('.'):
                rel = './' + rel
            if path.startswith('/'):
                rel = '/' + moved
            bracketed = raw.startswith('<')
            if '%' in path or (' ' in rel and not bracketed):
                rel = quote(rel, safe="/-._~!$&'()*+,;=:@")
            replacement = rel + (('?' + query) if query else '') + (('#' + fragment) if fragment else '')
            if bracketed:
                replacement = '<' + replacement + '>'
            if replacement == raw:
                continue
            out.append(text[last:start] + replacement)
            last = end
            changes.append({'kind': 'markdown-link', 'line': line_of(text, start), 'old': raw, 'new': replacement})
        out.append(text[last:])
        return ''.join(out), changes

    def rewrite_json(self, path: str, text: str):
        changes = []

        def replace(m):
            literal = m.group(0)
            try:
                value = json.loads(literal)
            except ValueError:
                return literal
            moved = self.relocate_string(value)
            if moved is None:
                return literal
            new = json.dumps(moved, ensure_ascii='\\u' in literal)
            changes.append({'kind': 'json-path', 'line': line_of(text, m.start()), 'old': value, 'new': moved})
            return new
        new = re.sub(r'"(?:[^"\\\n]|\\.)*"', replace, text)
        if changes:
            before, after = json.loads(text), json.loads(new)
            if transform(before, self.relocate_string) != after:
                raise ValueError(f'{path}: JSON rewrite changed more than the moved path strings')
        return new, changes

    TOKEN = re.compile(r'(?<![\w.\-/])([\w.\-][\w.\-/]*)')

    def rewrite_mentions(self, text: str, skip=(), multi=False):
        """Rewrite exact repository-relative path tokens; `skip` holds (start, end) spans left
        alone; with `multi`, only tokens of two or more components (a bare `MAP.md` in prose
        may name a neighbouring file)."""
        changes = []

        def replace(m):
            token = m.group(1)
            if inside(m.start(), skip):
                return token
            core = token.rstrip('.,;:')
            if multi and '/' not in core.rstrip('/'):
                return token
            moved = self.relocate(core)
            if moved is None:
                return token
            changes.append({'kind': 'path-mention', 'line': line_of(text, m.start()), 'old': core, 'new': moved})
            return moved + token[len(core):]
        return self.TOKEN.sub(replace, text), changes

    def mentions(self, text: str, path: str, skip=()):
        found = []
        for m in self.TOKEN.finditer(text):
            core = m.group(1).rstrip('.,;:')
            if '/' in core and not inside(m.start(), skip) and self.relocate(core) is not None:
                found.append({'file': path, 'line': line_of(text, m.start()), 'path': core})
        return found

    def outgoing_links(self, after, after_dirs):
        """Links inside moved Markdown files that stop resolving at the new location."""
        broken = []
        for old, new in self.file_map.items():
            if not old.endswith('.md') or not (self.root / old).is_file():
                continue
            text = (self.root / old).read_text(errors='replace')
            for start, _end, raw in links(text):
                parts = split_target(raw)
                if not parts or not parts[0]:
                    continue
                before = resolve(old, parts[0])
                if before is None or not ((self.root / before).exists() if before else True):
                    continue  # already broken before the move
                later = resolve(new, parts[0])
                if later is None or (later and later not in after and later.rstrip('/') not in after_dirs):
                    broken.append({'file': new, 'line': line_of(text, start), 'target': raw})
        return broken

    # ---- report and apply
    def report(self, full=True):
        summary = {
            'batch': self.batch, 'entries': len(self.entries), 'files_moved': len(self.moves),
            'conflicts': len(self.conflicts), 'live_files_rewritten': len(self.rewrites),
            'references_rewritten': sum(len(r['changes']) for r in self.rewrites),
            'references_by_kind': count_by(c['kind'] for r in self.rewrites for c in r['changes']),
            'rewritten_links_not_resolving_after_move': sum(1 for r in self.rewrites for c in r['changes'] if c.get('resolves') is False),
            'generated_pages_to_rerender': len(self.generated_refs),
            'frozen_files_referring_by_role': self.frozen_refs,
            'unrewritten_live_mentions': len(self.unrewritten),
            'moved_markdown_links_broken_by_move': len(self.outgoing),
            'untracked_or_ignored_left_behind': sum(len(x['untracked_or_ignored']) for x in self.leftovers),
        }
        if self.keep_references:
            summary['keep_references'] = True
            summary['live_references_kept_for_replacement'] = sum(len(r['changes']) for r in self.kept)
            summary['live_files_naming_vacated_paths'] = len(self.kept)
        result = {'summary': summary, 'conflicts': self.conflicts}
        if full:
            result.update({
                'moves': [{k: m[k] for k in ('old_path', 'new_path', 'sha256', 'blob', 'reason')} for m in self.moves],
                'rewrites': [{k: v for k, v in r.items() if k != '_text'} for r in self.rewrites],
                'generated_pages_to_rerender': self.generated_refs,
                'unrewritten_live_mentions': self.unrewritten,
                'moved_markdown_links_broken_by_move': self.outgoing,
                'untracked_or_ignored_left_behind': self.leftovers,
            })
            if self.keep_references:
                result['live_references_kept_for_replacement'] = [{k: v for k, v in r.items() if k != '_text'} for r in self.kept]
        return result

    def apply(self):
        if self.conflicts:
            raise ValueError(f'{len(self.conflicts)} conflict(s); nothing moved. Run without --apply to list them.')
        if not re.fullmatch(r'[A-Za-z0-9._-]+', self.batch):
            raise ValueError('batch name may contain only letters, digits, ".", "_" and "-"')
        receipt_path = self.root / self.receipts / f'{self.batch}.json'
        if receipt_path.exists():
            raise ValueError(f'receipt exists: {receipt_path.relative_to(self.root)}; choose another --batch')
        base = git(self.root, 'rev-parse', 'HEAD').decode().strip()
        for e in self.entries:
            target = self.root / e['new']
            target.parent.mkdir(parents=True, exist_ok=True)
            if e['kind'] == 'directory' and e['extra']:
                for f, n in e['members']:
                    (self.root / n).parent.mkdir(parents=True, exist_ok=True)
                    git(self.root, 'mv', '--', f, n)
            else:
                git(self.root, 'mv', '--', e['old'], e['new'])
        for r in self.rewrites:
            write_atomic(self.root / r['path'], r['_text'].encode())
        errors = self.verify()
        roots = self.write_history_manifests()
        receipt = {
            'schema_version': 1, 'batch': self.batch,
            'date': _dt.datetime.now(_dt.timezone.utc).isoformat(timespec='seconds'),
            'base_commit': base, 'tool': 'tools/research/moves.py',
            'files': [{k: m[k] for k in ('old_path', 'new_path', 'sha256', 'blob', 'reason', 'plan_entry')} for m in self.moves],
            'keep_references': self.keep_references,
            'rewritten': [{'path': r['path'], 'old_sha256': r['old_sha256'], 'new_sha256': r['new_sha256'],
                           'references': len(r['changes'])} for r in self.rewrites],
            'history_roots': roots,
            'generated_pages_to_rerender': self.generated_refs,
            'verification_errors': errors,
        }
        receipt_path.parent.mkdir(parents=True, exist_ok=True)
        receipt_path.write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + '\n')
        result = self.report(full=False)
        result.update({'applied': True, 'receipt': str(receipt_path.relative_to(self.root)), 'history_roots': roots,
                       'verification_errors': errors,
                       'next': 'Review `git status`; run make research-render, make research-check and research.py links; the integrator commits.'})
        return result

    def verify(self):
        errors = []
        present = [m['new_path'] for m in self.moves if (self.root / m['new_path']).is_file()]
        hashed = git(self.root, 'hash-object', '--stdin-paths', data=''.join(p + '\n' for p in present).encode()).decode().split()
        blobs = dict(zip(present, hashed))
        for m in self.moves:
            p = self.root / m['new_path']
            if not p.is_file():
                errors.append(f'missing after move: {m["new_path"]}')
                continue
            if sha256(p) != m['sha256']:
                errors.append(f'bytes changed: {m["new_path"]}')
            if blobs.get(m['new_path']) != m['blob']:
                errors.append(f'blob changed: {m["new_path"]}')
            if (self.root / m['old_path']).exists():
                errors.append(f'old path still present: {m["old_path"]}')
        record_globs = [d.rstrip('/') + '/*.json' for d in self.settings.get('record_directories', [])]
        for r in self.rewrites:
            if not path_roles.matches(r['path'], record_globs):
                continue
            data = json.loads((self.root / r['path']).read_text())
            changed = {c['new'] for c in r['changes'] if c['kind'] == 'json-path'}
            for ref in data.get('references', []):
                if isinstance(ref, dict) and ref.get('path') in changed:
                    p = self.root / ref['path']
                    if not p.is_file():
                        errors.append(f'{r["path"]}: reference missing at {ref["path"]}')
                    elif ref.get('sha256') and sha256(p) != ref['sha256']:
                        errors.append(f'{r["path"]}: reference sha256 differs at {ref["path"]}')
            for value in strings(data):
                if value in changed:
                    head = value.split('#', 1)[0]
                    head = re.split(r':(?=\d)', head, 1)[0]
                    if not (self.root / head).exists():
                        errors.append(f'{r["path"]}: rewritten path does not exist: {value}')
        for r in self.rewrites:
            for c in r['changes']:
                if c.get('resolves') is False:
                    errors.append(f'{r["path"]}:{c["line"]}: rewritten link does not resolve: {c["new"]}')
        return errors

    def history_root(self, path: str):
        parts = path.split('/')
        for i, c in enumerate(parts[:-1]):
            if c in self.classifier.rules['history_components']:
                return '/'.join(parts[:i + 1])
        return None

    def write_history_manifests(self):
        grouped = defaultdict(list)
        for m in self.moves:
            root = self.history_root(m['new_path'])
            if root:
                grouped[root].append(m)
        written = []
        for root, items in sorted(grouped.items()):
            manifest_path = self.root / root / 'MANIFEST.json'
            try:
                manifest = json.loads(manifest_path.read_text())
            except (OSError, ValueError):
                manifest = {'schema_version': 1, 'root': root, 'entries': []}
            for m in items:
                manifest['entries'].append({'old_path': m['old_path'], 'new_path': m['new_path'], 'sha256': m['sha256'],
                                            'blob': m['blob'], 'batch': self.batch, 'reason': m['reason'],
                                            'plan_entry': m['plan_entry']})
            manifest['entries'].sort(key=lambda x: x['new_path'])
            manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
            (self.root / root / 'INDEX.md').write_text(history_index(root, manifest))
            written.append(root)
        return written


def history_index(root: str, manifest: dict) -> str:
    groups = defaultdict(list)
    for e in manifest['entries']:
        groups[(e.get('batch', ''), e.get('plan_entry') or e['old_path'], e.get('reason', ''))].append(e)
    lines = [f'<!-- Generated by tools/research/moves.py from MANIFEST.json; do not edit by hand. -->',
             f'# History: `{root}/`', '',
             'Retired material, moved here with its bytes unchanged. Each file\'s former path, sha256 and git blob '
             'are in [MANIFEST.json](MANIFEST.json); each batch has a receipt in `_process/architecture/moves/`.', '',
             '| Here | Came from | Files | Reason | Batch |', '|---|---|---|---|---|']
    for (batch, origin, reason), items in sorted(groups.items()):
        if len(items) == 1 and items[0]['old_path'] == origin:
            here = items[0]['new_path']
        else:
            here = common_prefix([e['new_path'] for e in items])
        rel = posixpath.relpath(here, root) if here else '.'
        lines.append(f'| [{cell(rel)}]({quote(rel, safe="/-._~")}) | `{cell(origin)}` | {len(items)} | {cell(reason)} | {cell(batch)} |')
    return '\n'.join(lines) + '\n'


def cell(s: str) -> str:
    return s.replace('|', '\\|').replace('\n', ' ')


def common_prefix(items):
    prefix = posixpath.commonpath(items) if items else ''
    return prefix


def count_by(items):
    out = defaultdict(int)
    for x in items:
        out[x] += 1
    return dict(sorted(out.items()))


def bad_path(p: str) -> bool:
    return not p or p.startswith('/') or p == '..' or p.startswith('../') or '/../' in p or p.endswith('/..') or '\\' in p


def pin_reason(path, patterns, pinned, prefixes, why):
    for g in patterns:
        if path_roles.matches(path, [g]):
            return f'move_pinned {g}'
    if path in pinned:
        return why.get(path, 'pinned')
    for d in prefixes:
        if path.startswith(d + '/'):
            return why.get(d, 'pinned directory')
    return None


def strings(data, keys=False):
    if isinstance(data, str):
        yield data
    elif isinstance(data, dict):
        for k, v in data.items():
            if keys:
                yield k
            yield from strings(v, keys)
    elif isinstance(data, list):
        for v in data:
            yield from strings(v, keys)


def transform(data, fn):
    """The JSON value with every string (and key) replaced where fn gives a new one."""
    if isinstance(data, str):
        new = fn(data)
        return data if new is None else new
    if isinstance(data, dict):
        return {transform(k, fn): transform(v, fn) for k, v in data.items()}
    if isinstance(data, list):
        return [transform(v, fn) for v in data]
    return data


def receipt_files(root: Path = ROOT, settings: dict | None = None):
    """Every move receipt under `move_receipts` (not its subdirectories), oldest name first."""
    settings = path_roles.load_config(root) if settings is None else settings
    directory = root / settings.get('move_receipts', DEFAULT_RECEIPTS)
    return sorted(directory.glob('*.json'))


_MAPS: dict = {}


def receipt_maps(root: Path = ROOT, settings: dict | None = None):
    """(back, forward, directories) from the move receipts: new -> old and old -> new for each
    moved file, and old -> new for each moved directory (plan entries that were directories).
    Cached by the receipts' names, sizes and modification times."""
    files = receipt_files(root, settings)
    key = (str(root), tuple((p.name, p.stat().st_size, p.stat().st_mtime_ns) for p in files if p.is_file()))
    if key in _MAPS:
        return _MAPS[key]
    back, forward, dirs = {}, {}, {}
    for receipt in files:
        try:
            data = json.loads(receipt.read_text())
        except (OSError, ValueError):
            continue
        if not isinstance(data, dict):
            continue
        for f in data.get('files', []):
            if not isinstance(f, dict) or not isinstance(f.get('old_path'), str) or not isinstance(f.get('new_path'), str):
                continue
            old, new = f['old_path'], f['new_path']
            back[new], forward[old] = old, new
            entry = f.get('plan_entry')
            if isinstance(entry, str) and entry != old and old.startswith(entry + '/'):
                rest = old[len(entry):]
                if new.endswith(rest):
                    dirs[entry] = new[:-len(rest)]
    _MAPS.clear()
    _MAPS[key] = (back, forward, dirs)
    return _MAPS[key]


def former_paths(path: str, root: Path = ROOT, settings: dict | None = None) -> list[str]:
    """Earlier paths of `path` according to the move receipts, newest first (for drift lookup)."""
    back = receipt_maps(root, settings)[0]
    out, seen = [], {path}
    while path in back and back[path] not in seen:
        path = back[path]
        seen.add(path)
        out.append(path)
    return out


def later_path(path: str, root: Path = ROOT, settings: dict | None = None) -> str | None:
    """Where the move receipts say `path` (a file, or a directory moved whole) went, following
    later moves; None when no receipt moved it."""
    _back, forward, dirs = receipt_maps(root, settings)
    bare, seen, moved = path.rstrip('/'), set(), False
    while bare not in seen:
        seen.add(bare)
        if bare in forward:
            bare, moved = forward[bare], True
            continue
        parent = next((d for d in sorted(dirs, key=len, reverse=True) if bare == d or bare.startswith(d + '/')), None)
        if parent is None:
            break
        bare, moved = dirs[parent] + bare[len(parent):], True
    return (bare + ('/' if path.endswith('/') else '')) if moved else None


def current_path(path: str, root: Path = ROOT, settings: dict | None = None) -> str:
    """The path a tool should read or link for `path`: `path` itself while it exists (including
    a replacement written at a vacated path), else where the move receipts moved it, else `path`.
    Tools name the documents they need by their first path and resolve them through this."""
    head, sep, rest = path.partition('#')
    if (root / head).exists():
        return path
    moved = later_path(head, root, settings)
    return (moved + sep + rest) if moved and (root / moved.rstrip('/')).exists() else path


def historical_paths(globs, root: Path = ROOT, settings: dict | None = None) -> set[str]:
    """Files that once matched one of `globs` and that the move receipts moved elsewhere (to a
    history root or another live place), at their present paths where they exist."""
    back, forward, _dirs = receipt_maps(root, settings)
    out = set()
    for old in forward:
        if any(path_roles.matches(old, [g]) for g in globs) and not (root / old).exists():
            new = later_path(old, root, settings)
            if new and (root / new).is_file():
                out.add(new)
    return out


def check_receipt(receipt_path, root: Path = ROOT, settings: dict | None = None):
    """Verify a move receipt against the working tree: every new path exists with the recorded
    sha256; every old path is gone (or holds a replacement, for a batch that kept references);
    and no live reference still names an old path that no longer exists. Frozen evidence,
    history, sources, generated pages and the files in `move_mentions_exclude` keep old paths
    by design; prose mentions in other live files are warnings."""
    settings = path_roles.load_config(root) if settings is None else settings
    p = Path(receipt_path)
    p = p if p.is_absolute() else root / p
    receipt = json.loads(p.read_text())
    kept = bool(receipt.get('keep_references'))
    errors, warnings, replaced = [], [], []
    plan = Plan([], root=root, settings=settings, batch=receipt.get('batch') or p.stem)
    file_map, dir_map = {}, {}
    for f in receipt.get('files', []):
        old, new = f['old_path'], f['new_path']
        target = root / new
        if not target.is_file():
            errors.append(f'missing: {new}')
        elif f.get('sha256') and sha256(target) != f['sha256']:
            errors.append(f'sha256 differs: {new}')
        if (root / old).exists():
            (replaced if kept else errors).append(old if kept else f'old path still present: {old}')
            continue
        file_map[old] = new
        entry = f.get('plan_entry')
        if isinstance(entry, str) and entry != old and old.startswith(entry + '/') and new.endswith(old[len(entry):]):
            for d in directories([old]) | {entry}:
                if (d == entry or d.startswith(entry + '/')) and not (root / d).exists():
                    dir_map[d] = new[:-len(old[len(entry):])] + d[len(entry):]
    plan.file_map, plan.dir_map = file_map, dir_map
    plan.files = tracked(root)
    remaining, mentions, generated, frozen = plan.scan(set(file_map.values()))
    for r in remaining:
        for c in r['changes']:
            errors.append(f'{r["path"]}:{c["line"]}: {c["kind"]} still names {c["old"]}')
    for m in mentions:
        warnings.append(f'{m["file"]}:{m["line"]}: prose mentions {m["path"]}')
    return {'receipt': str(p.relative_to(root)) if p.is_relative_to(root) else str(p), 'batch': receipt.get('batch'),
            'files': len(receipt.get('files', [])), 'replaced_at_old_path': len(replaced),
            'live_references_remaining': sum(len(r['changes']) for r in remaining),
            'generated_pages_naming_old_paths': generated, 'frozen_files_naming_old_paths_by_role': frozen,
            'errors': errors, 'warnings': warnings,
            'scope': 'Bytes of moved files and live references (Markdown links and exact path mentions, JSON path '
                     'strings in move_rewrite_json, mentions in move_rewrite_extra). Frozen evidence, history, '
                     'sources and generated pages keep old paths by design; rerender generated pages.'}


def run(plan_path: str, apply: bool = False, batch: str | None = None, root: Path = ROOT, full: bool = True,
        keep_references: bool = False):
    p = Path(plan_path)
    entries = Plan.read(p)
    plan = Plan(entries, root=root, batch=batch, plan_name=p.stem, keep_references=keep_references).analyse()
    if apply:
        return plan.apply()
    result = plan.report(full=full)
    result['applied'] = False
    return result
