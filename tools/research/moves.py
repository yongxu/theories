"""File-level moves that keep moved bytes frozen and rewrite references in live files only.

`python3 -B tools/research/research.py move --plan PLAN.tsv [--apply] [--batch NAME] [--keep-references]`
`python3 -B tools/research/research.py move --check RECEIPT.json`

A plan is a TSV with the columns old_path, new_path, reason; old_path is a tracked file or
directory. A dry run (the default) reports every file that would move, every live reference
that would be rewritten, and every conflict. `--apply` refuses while any conflict remains; it
then `git mv`s each entry (the only state-changing git command here), rewrites live
references, verifies the moved bytes and rewritten record references, and writes a receipt
in `move_receipts` plus a MANIFEST.json and generated INDEX.md in each history root.

What is rewritten (live files only, as decided by tools/research/paths.py):
- relative Markdown links in .md files, resolved against the referring file's directory,
  `path#anchor` included;
- repository-relative path strings in the JSON files named by `move_rewrite_json` (records,
  research config, goals, results data): any string equal to an old path or starting with it
  followed by `/`, `#`, `:` or `?`;
- exact repository-relative path strings in the prose and code of live Markdown files
  (`a/b/C.md`, outside link targets), unless `move_rewrite_markdown_mentions` is false or the
  file matches `move_mentions_exclude`;
- path mentions in the (non-Markdown) files named by `move_rewrite_extra`.
Generated pages are not edited (rerun `make research-render`); moved files keep their bytes.
With `--keep-references` nothing is rewritten: the vacated paths receive new files afterwards
(the H1/H6 replace plans), and the report lists the references that keep naming them.

`--check RECEIPT` verifies an applied batch: every new path holds the recorded sha256, and no
live reference names an old path that is gone. Receipts are frozen evidence and are never
rewritten; `former_paths`, `later_path` and `current_path` read them so that tools follow moves
(drift lookup in registry.reviewed_version, discovery in generative_chain and reading_catalogue,
fixed links in navigation and lean_catalogue).

The module also holds the Markdown link and GitHub anchor reader that `research.py links`
uses, so the rewriter and the checker resolve a link the same way.
"""
