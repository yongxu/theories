def selected_results(records, key, config=None):
    """Resolve an explicit editorial list of result IDs without promoting open or retired claims.
    A selected record shows its overview where it has one, otherwise its statement or claim."""
    configured = (read(CONFIG) if config is None else config).get(key, [])
    if not isinstance(configured, list) or not all(isinstance(ident, str) for ident in configured):
        raise ValueError(key + ' must be a list of result IDs')
    if len(configured) != len(set(configured)):
        raise ValueError(key + ' contains duplicate result IDs')
    by_id = {r['id']: r for r in records}
    selected = []
    for ident in configured:
        if ident not in by_id:
            raise ValueError(key + ' refers to missing result: ' + ident)
        record = by_id[ident]
        if record.get('status') not in COMPLETED or record.get('kind') == 'target':
            raise ValueError(key + ' requires a completed scoped result: ' + ident)
        if 'overview' in record and not registry.valid_overview(record.get('overview')):
            raise ValueError(key + ' requires an overview title, summary and evidence, each in English or Chinese: ' + ident)
        if 'overview' not in record and not any(registry.pair(record.get(k)) for k in ('statement', 'claim')):
            raise ValueError(key + ' requires an overview or a statement: ' + ident)
        selected.append(record)
    return selected


