def markdown_file(key, destination, config=None, root=ROOT):
    """A Markdown file named by the configuration, its links adapted to `destination`."""
    configured = (read(CONFIG) if config is None else config).get(key)
    if configured is None:
        return ''
    if not isinstance(configured, str) or not configured.endswith('.md'):
        raise ValueError(key + ' must be the path of a Markdown file')
    p = root / configured
    if not p.is_file():
        raise ValueError(key + ' refers to a missing file: ' + configured)
    # A leading comment addresses editors of the file and stays out of the page.
    body = re.sub(r'\A\s*<!--.*?-->', '', p.read_text(), flags=re.S).strip()
    if not body:
        raise ValueError(key + ' is empty: ' + configured)
    return adapt_links(body, configured, destination)


FOOTNOTE_DEF = re.compile(r'^\[\^([^\]]+)\]:[ \t]*(.*)$', re.M)
FOOTNOTE_REF = re.compile(r'\[\^([^\]]+)\](?!:)')


def endnotes(body):
    """Footnotes as numbered notes with ordinary links. On a repository's front page GitHub
    leaves links inside footnotes unrewritten, so they resolve against the repository URL
    and break; links in body text are rewritten and work."""
    defs = {m.group(1): m.group(2) for m in FOOTNOTE_DEF.finditer(body)}
    if not defs:
        return body
    order, uses = [], {}

    def ref(m):
        key = m.group(1)
        if key not in defs:
            return m.group(0)
        if key not in order:
            order.append(key)
        uses[key] = uses.get(key, 0) + 1
        anchor = 'ref-' + key + ('' if uses[key] == 1 else '-' + str(uses[key]))
        return f'<sup><a id="{anchor}"></a>[{order.index(key) + 1}](#note-{key})</sup>'

    text = FOOTNOTE_REF.sub(ref, FOOTNOTE_DEF.sub('', body))
    order += [k for k in defs if k not in order]
    notes = [f'{i}. <a id="note-{k}"></a>{defs[k]} [↩](#ref-{k})' for i, k in enumerate(order, 1)]
    return re.sub(r'\n{3,}', '\n\n', text).rstrip() + '\n\n### Notes\n\n' + '\n\n'.join(notes)


def readme_opening(config=None, root=ROOT):
    """The opening placed first in README: a Markdown file named by the configuration, its
    footnotes as numbered notes (`endnotes`)."""
    opening = markdown_file('readme_opening', 'README.md', config, root)
    return endnotes(opening) if opening else opening


# Reading time, as the release gate's budgets count it (WHAT-REMAINS, item 6; AJ4's measure_layers.py counts the same
# way): visible prose only, English in words and Chinese in characters, read at 100 to 130 words, or 200 to 260
# characters, a minute.
def visible_prose(text):
    text = re.sub(r'```.*?```', '', text, flags=re.S)
    text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    text = re.sub(r'\]\([^)]*\)', ']', text)
    text = re.sub(r'<a id="[^"]*"></a>|<sup>.*?</sup>', '', text)
    return re.sub(r'(Quote|Source)\s*\[[^\]]*\]\s*:\s*', '', text)


def prose_counts(text):
    """(English words, Chinese characters) of a text's visible prose."""
    v = visible_prose(text)
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’\-.]*", v)), len(re.findall(r'[一-鿿]', v))


def reading_time(text):
    """A text's reading time in whole minutes (halves rounded up), fast to slow: '17–22 minutes', '2 minutes' where the
    two round alike, or 'a minute' below a minute and a half at the slow rate."""
    en, zh = prose_counts(text)
    fast, slow = en / 130 + zh / 260, en / 100 + zh / 200
    if slow < 1.5:
        return 'a minute'
    lo, hi = max(1, int(fast + 0.5)), max(1, int(slow + 0.5))
    return f'{hi} minutes' if lo == hi else f'{lo}–{hi} minutes'


def span(time):
    """A reading time's ends in minutes, longer first ('17–22 minutes': (22, 17); 'a minute': (1, 1))."""
    ends = [int(x) for x in re.findall(r'\d+', time)] or [1]
    return ends[-1], ends[0]


