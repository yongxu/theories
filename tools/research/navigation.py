def markdown_file(key, destination, config=None, root=ROOT):
    """A Markdown file named by the configuration, its links adapted to `destination`."""
    configured = (read(CONFIG) if config is None else config).get(key)
    if configured is None:
        return ''
    if not isinstance(configured, str) or not configured.endswith('.md'):
        raise ValueError(key + ' must be the path of a Markdown file')
    p = root / configured
    if not p.is_file():
        raise ValueError(key + ' refers to a missing file: ' + configured)
    # A leading comment addresses editors of the file and stays out of the page.
    body = re.sub(r'\A\s*<!--.*?-->', '', p.read_text(), flags=re.S).strip()
    if not body:
        raise ValueError(key + ' is empty: ' + configured)
    return adapt_links(body, configured, destination)


FOOTNOTE_DEF = re.compile(r'^\[\^([^\]]+)\]:[ \t]*(.*)$', re.M)
FOOTNOTE_REF = re.compile(r'\[\^([^\]]+)\](?!:)')


def endnotes(body):
    """Footnotes as numbered notes with ordinary links. On a repository's front page GitHub
    leaves links inside footnotes unrewritten, so they resolve against the repository URL
    and break; links in body text are rewritten and work."""
    defs = {m.group(1): m.group(2) for m in FOOTNOTE_DEF.finditer(body)}
    if not defs:
        return body
    order, uses = [], {}

    def ref(m):
        key = m.group(1)
        if key not in defs:
            return m.group(0)
        if key not in order:
            order.append(key)
        uses[key] = uses.get(key, 0) + 1
        anchor = 'ref-' + key + ('' if uses[key] == 1 else '-' + str(uses[key]))
        return f'<sup><a id="{anchor}"></a>[{order.index(key) + 1}](#note-{key})</sup>'

    text = FOOTNOTE_REF.sub(ref, FOOTNOTE_DEF.sub('', body))
    order += [k for k in defs if k not in order]
    notes = [f'{i}. <a id="note-{k}"></a>{defs[k]} [↩](#ref-{k})' for i, k in enumerate(order, 1)]
    return re.sub(r'\n{3,}', '\n\n', text).rstrip() + '\n\n### Notes\n\n' + '\n\n'.join(notes)


def readme_opening(config=None, root=ROOT):
    """The opening placed first in README: a Markdown file named by the configuration, its
    footnotes as numbered notes (`endnotes`)."""
    opening = markdown_file('readme_opening', 'README.md', config, root)
    return endnotes(opening) if opening else opening


# Reading time, as the release gate's budgets count it (WHAT-REMAINS, item 6; AJ4's measure_layers.py counts the same
# way): visible prose only, English in words and Chinese in characters, read at 100 to 130 words, or 200 to 260
# characters, a minute.
def visible_prose(text):
    text = re.sub(r'```.*?```', '', text, flags=re.S)
    text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    text = re.sub(r'\]\([^)]*\)', ']', text)
    text = re.sub(r'<a id="[^"]*"></a>|<sup>.*?</sup>', '', text)
    return re.sub(r'(Quote|Source)\s*\[[^\]]*\]\s*:\s*', '', text)


def prose_counts(text):
    """(English words, Chinese characters) of a text's visible prose."""
    v = visible_prose(text)
    return len(re.findall(r"[A-Za-z0-9][A-Za-z0-9'’\-.]*", v)), len(re.findall(r'[一-鿿]', v))


def reading_time(text):
    """A text's reading time in whole minutes (halves rounded up), fast to slow: '17–22 minutes', '2 minutes' where the
    two round alike, or 'a minute' below a minute and a half at the slow rate."""
    en, zh = prose_counts(text)
    fast, slow = en / 130 + zh / 260, en / 100 + zh / 200
    if slow < 1.5:
        return 'a minute'
    lo, hi = max(1, int(fast + 0.5)), max(1, int(slow + 0.5))
    return f'{hi} minutes' if lo == hi else f'{lo}–{hi} minutes'


def span(time):
    """A reading time's ends in minutes, longer first ('17–22 minutes': (22, 17); 'a minute': (1, 1))."""
    ends = [int(x) for x in re.findall(r'\d+', time)] or [1]
    return ends[-1], ends[0]


FIRST_SCREEN_FIELD = re.compile(r'\{\{([a-z]+):([^}]*)\}\}')
SCREEN_TIME = '{{time:screen}}'


def timed_paths(config=None, root=ROOT):
    """The files the first screen's `{{time:PATH}}` fields name, which README depends on as it does on its readme_*
    files (the render's input snapshot holds them)."""
    configured = (read(CONFIG) if config is None else config).get('readme_first_screen')
    p = root / configured if isinstance(configured, str) else None
    if p is None or not p.is_file():
        return []
    return [root / arg for kind, arg in FIRST_SCREEN_FIELD.findall(p.read_text())
            if kind == 'time' and arg not in ('screen', 'opening', 'notes')]


def first_screen(records, opening, config=None, root=ROOT, above=''):
    """README's first screen (the release gate's, WHAT-REMAINS item 6: everything before the opening's heading): the
    readme_first_screen file, placed before the opening, its fields filled at render so that no figure is copied.
    `{{time:PATH}}` is the reading time of a file of the repository (PATH from the repository's root, and no page the
    render writes, whose copy on disk is the last render's), `{{time:opening}}` and `{{time:notes}}` that of the
    opening's body and of its notes, `{{time:screen}}` that of the whole screen as it renders, `above` (the title,
    navigation and status) with the file and its own time filled in (where filling it in moves the time back and forth,
    the longer); `{{count:registered}}` is the number of registered results and `{{count:STATUS}}` the number with
    that status. A field of no such form left in the file is an error."""
    lead = markdown_file('readme_first_screen', 'README.md', config, root)
    if not lead:
        return lead
    body, _, notes = opening.partition('\n### Notes\n')

    def fill(m):
        kind, arg = m.groups()
        if kind == 'count':
            if arg == 'registered':
                return str(len(records))
            if arg not in STATUS_TEXT:
                raise ValueError('readme_first_screen names an unknown status: ' + arg)
            return str(sum(r['status'] == arg for r in records))
        if kind == 'time':
            if arg == 'screen':
                return m.group(0)
            if arg in ('opening', 'notes'):
                text = body if arg == 'opening' else notes
                if not text.strip():
                    raise ValueError('readme_first_screen times the ' + arg + ', which the opening does not have')
                return reading_time(text)
            p = (root / arg).resolve()
            if Path(root).resolve() not in p.parents or not p.is_file():
                raise ValueError('readme_first_screen times a missing file (a path from the repository root): ' + arg)
            text = p.read_text()
            if '<!-- Generated by ' in text:
                raise ValueError('readme_first_screen times a page the render writes: ' + arg)
            return reading_time(text)
        raise ValueError('readme_first_screen has an unknown field: ' + m.group(0))

    screen = FIRST_SCREEN_FIELD.sub(fill, lead)
    if '{{' in screen.replace(SCREEN_TIME, ''):
        raise ValueError('readme_first_screen has a malformed field: ' + screen.replace(SCREEN_TIME, '').split('{{', 1)[1][:40])

    def timed(t):
        return reading_time(above + '\n\n' + screen.replace(SCREEN_TIME, t))
    if SCREEN_TIME not in screen:
        return screen
    t, seen = timed(''), []
    while t not in seen:
        seen.append(t)
        t = timed(t)
    return screen.replace(SCREEN_TIME, max(seen[seen.index(t):], key=span))


def open_question_links(config=None):
    """Groups of links to where open questions are kept: {'programme': [...], 'pending_ren': [...]},
    each item {'path': 'file#anchor', 'label': text}."""
    configured = (read(CONFIG) if config is None else config).get('open_questions', {})
    if not isinstance(configured, dict):
        raise ValueError('open_questions must be an object of link groups')
    groups = {}
    for group in ('programme', 'pending_ren'):
        items = configured.get(group, [])
        if not isinstance(items, list) or not all(isinstance(x, dict) and isinstance(x.get('path'), str) and isinstance(x.get('label'), str) for x in items):
            raise ValueError('open_questions.' + group + ' must be a list of {path, label}')
        for x in items:
            if registry.path_in_repo(x['path'].split('#')[0]) is None:
                raise ValueError('open_questions.' + group + ' refers to a missing file: ' + x['path'])
        groups[group] = items
    return groups


def validate_goals(records):
    ids = {r['id'] for r in records}
    goal_records = goals()
    seen, errors = set(), []
    for g in goal_records:
        ident = g.get('id')
        if ident in seen or not re.fullmatch(r'[a-z][a-z0-9-]+', ident or ''):
            errors.append('invalid or duplicate goal id: ' + str(ident))
        seen.add(ident)
        for field in ('title', 'scope', 'objective', 'completion', 'premises'):
            if not registry.pair(g.get(field)):
                errors.append(f'{ident}: {field} required in English or Chinese')
        if 'overview' in g and not valid_goal_overview(g['overview']):
            errors.append(f'{ident}: overview requires title, summary and next_step, each in English or Chinese')
        if g.get('scope_type') not in {'project-direction', 'authorized-session', 'completed-route'}:
            errors.append(f'{ident}: scope_type required')
        if g.get('state') not in GOAL_STATES:
            errors.append(f'{ident}: state required, one of ' + ', '.join(GOAL_STATES))
        if not g.get('sources'):
            errors.append(f'{ident}: authorization sources required')
        for path in g.get('sources', []):
            if registry.path_in_repo(path.split('#')[0]) is None:
                errors.append(f'{ident}: missing authorization {path}')
        for ident in g.get('result_ids', []):
            if ident not in ids:
                errors.append('goal refers to missing result: ' + ident)
    try:
        opening = readme_opening()
    except ValueError as exc:
        errors.append(str(exc))
        opening = None
    for check in (lambda: featured_results(records), lambda: conditional_results(records), lambda: research_goals(goal_records),
                  lambda: opening is None or first_screen(records, opening), lambda: markdown_file('readme_lead', 'README.md'),
                  lambda: markdown_file('readme_repository', 'README.md'),
                  open_question_links):
        try:
            check()
        except ValueError as exc:
            errors.append(str(exc))
    return errors


