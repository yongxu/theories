def first_screen(records, opening, config=None, root=ROOT, above='', below=''):
    """README's first screen (the release gate's, WHAT-REMAINS item 6: everything before the opening's heading): the
    readme_first_screen file, placed before the opening, its fields filled at render so that no figure is copied.
    `{{time:PATH}}` is the reading time of a file of the repository (PATH from the repository's root, and no page the
    render writes, whose copy on disk is the last render's), `{{time:opening}}` and `{{time:notes}}` that of the
    opening's body and of its notes, `{{time:screen}}` that of the whole screen as it renders: `above` (the title,
    navigation and status), the file with its own time filled in (where filling it in moves the time back and forth, the
    longer) and `below` (the ways in, which stand before the opening's heading); `{{count:registered}}` is the number of
    registered results and `{{count:STATUS}}` the number with that status; `{{tests:ARG}}` is a count of the tests naming a thesis, by tests_page.screen_count (total, a class, unrun, ran,
    other), which README.zh.md's fields share. A field of no such
    form left in the file is an error."""
    lead = markdown_file('readme_first_screen', 'README.md', config, root)
    if not lead:
        return lead
    body, _, notes = opening.partition('\n### Notes\n')

    def fill(m):
        kind, arg = m.groups()
        if kind == 'count':
            if arg == 'registered':
                return str(len(records))
            if arg not in STATUS_TEXT:
                raise ValueError('readme_first_screen names an unknown status: ' + arg)
            return str(sum(r['status'] == arg for r in records))
        if kind == 'tests':
            from tools.research import tests_page  # it imports this module
            try:
                return str(tests_page.screen_count(arg, root))
            except tests_page.UnknownCount as e:
                raise ValueError('readme_first_screen ' + str(e)) from None  # an Unreadable names the data itself
        if kind == 'time':
            if arg == 'screen':
                return m.group(0)
            if arg in ('opening', 'notes'):
                text = body if arg == 'opening' else notes
                if not text.strip():
                    raise ValueError('readme_first_screen times the ' + arg + ', which the opening does not have')
                return reading_time(text)
            p = (root / arg).resolve()
            if Path(root).resolve() not in p.parents or not p.is_file():
                raise ValueError('readme_first_screen times a missing file (a path from the repository root): ' + arg)
            text = p.read_text()
            if '<!-- Generated by ' in text:
                raise ValueError('readme_first_screen times a page the render writes: ' + arg)
            return reading_time(text)
        raise ValueError('readme_first_screen has an unknown field: ' + m.group(0))

    screen = FIRST_SCREEN_FIELD.sub(fill, lead)
    if '{{' in screen.replace(SCREEN_TIME, ''):
        raise ValueError('readme_first_screen has a malformed field: ' + screen.replace(SCREEN_TIME, '').split('{{', 1)[1][:40])

    def timed(t):
        return reading_time(above + '\n\n' + screen.replace(SCREEN_TIME, t) + '\n\n' + below)
    if SCREEN_TIME not in screen:
        return screen
    t, seen = timed(''), []
    while t not in seen:
        seen.append(t)
        t = timed(t)
    return screen.replace(SCREEN_TIME, max(seen[seen.index(t):], key=span))


def open_question_links(config=None):
    """Groups of links to where open questions are kept: {'programme': [...], 'pending_ren': [...]},
    each item {'path': 'file#anchor', 'label': text}."""
    configured = (read(CONFIG) if config is None else config).get('open_questions', {})
