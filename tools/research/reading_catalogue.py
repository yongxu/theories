CJK = re.compile(r'[㐀-䶿一-鿿豈-﫿　-〿＀-￯]')


def english(text: str) -> str:
    """The English half of a 'Chinese / English' value; other text unchanged.
    The split is the first ` / ` with Chinese before it and Latin letters after it whose
    remainder has no Chinese; failing that, the last such split (English may quote a term)."""
    if not isinstance(text, str) or not CJK.search(text):
        return text
    parts = text.split(' / ')
    if len(parts) == 2 and not CJK.search(parts[0]) and re.search('[A-Za-z]', parts[0]):
        return parts[0].strip()  # 'English / Chinese'

    splits = [i for i in range(1, len(parts)) if CJK.search(' / '.join(parts[:i])) and re.search('[A-Za-z]', ' / '.join(parts[i:]))]
    if not splits:
        return text
    clean = [i for i in splits if not CJK.search(' / '.join(parts[i:]))]
    return ' / '.join(parts[(clean or splits[-1:])[0]:]).strip()


def pick(d: dict, field: str) -> str:
    """The English of a paired field, or its Chinese where no English exists."""
    value = d.get(field + '_en')
    if isinstance(value, str) and value.strip():
        return value.strip()
    return (d.get(field + '_zh') or '').strip()


