def titled(d: dict) -> str:
    return pick(d, 'title')


def former_title(d: dict) -> str:
    """The bilingual heading the pages used before 17 October 2026 (its anchor is kept)."""
    zh, en = d.get('title_zh', ''), d.get('title_en', '')
    return f'{zh} / {en}' if zh and en else zh or en


def unprefixed(text: str, label: str) -> str:
    """`Next: Next: x` reads `Next: x`: drop a label the register text repeats."""
    return text[len(label) + 1:].lstrip() if text.lower().startswith(label.lower() + ':') else text


def reading_note(d: dict, drift: dict) -> list[str]:
    if d['id'] not in drift:
        return []
    return [f"**Reading status:** the source changed after this reading (read version sha256 `{d['source_sha256'][:12]}…`). The entry describes that earlier version; it awaits a reread before its hash is refreshed.", '']


