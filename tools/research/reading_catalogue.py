def chapter_link(identifier: str, source: str | None = None) -> str:
    """The entry's reading in the frozen volume of 8 October 2026 where it has one, else the chapter itself."""
    volume = 'A-L' if identifier[0].upper() <= 'L' else 'M-Z'
    frozen = FROZEN[volume]
    if frozen.is_file() and identifier in anchors(frozen):
        return f'{rel(str(frozen.relative_to(ROOT)))}#{identifier}'
    return rel(source) if source else f'{rel(str(frozen.relative_to(ROOT)))}'


def link(label: str, target: str) -> str:
    return f'[{label}](<{target}>)' if ' ' in target else f'[{label}]({target})'


@lru_cache(maxsize=None)
def anchors(path: Path) -> set[str]:
    """Explicit IDs and GitHub-style headings in a Markdown reading document."""
    return anchors_from_text(path.read_text())


HEADING = re.compile(r'^#{1,6}\s+(.+?)\s*#*\s*$', re.M)


def slug(heading: str) -> str:
    """GitHub's anchor for a heading's text, before numbering repeats."""
    heading = re.sub(r'\[([^\]]+)\]\([^)]*\)', r'\1', heading)
    heading = re.sub(r'<[^>]*>', '', heading).replace('`','').lower()
    return ''.join(c for c in heading if c in '-_' or not unicodedata.category(c).startswith(('P','S'))).replace(' ', '-')


def numbered(slugs: list[str]) -> list[str]:
    """Number repeated anchors as GitHub does: x, x-1, x-2."""
    counts: dict[str, int] = {}
    out = []
    for s in slugs:
        n = counts.get(s, 0)
        counts[s] = n + 1
        out.append(s if not n else f'{s}-{n}')
    return out


def anchors_from_text(body: str) -> set[str]:
    found = set(re.findall(r'<a\s+(?:id|name)=[\"\']([^\"\']+)[\"\']', body))
    found.update(numbered([slug(h) for h in HEADING.findall(body)]))
    return found


@lru_cache(maxsize=None)
def line_count(path: Path) -> int:
    return len(path.read_text().splitlines())


def heading(marks: str, text: str, former: str | None = None):
    """A heading whose earlier (bilingual) text keeps its anchor; see registry.finish."""
    return (marks, text, text if former is None else former)


def finish(lines: list) -> str:
    import sys
