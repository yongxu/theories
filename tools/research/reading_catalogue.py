def load() -> tuple[list[dict], list[dict]]:
    chapters = []
    for name in ('arguments-a-l.json', 'arguments-m-z.json'):
        chapters += json.loads((OUT / 'data' / name).read_text())
    return chapters, json.loads((OUT / 'data/theory-map.json').read_text())


def expected_chapters(generated: set[str]) -> set[str]:
    """Chapter files that need an entry: every `chapters/*.md` except Chinese editions (covered by
    the English entry) and pages a generator writes other than registered views (the chapter
    index), plus the chapters the move receipts moved to history."""
    out = set()
    for p in CANON.glob('*.md'):
        rel_path = str(p.relative_to(ROOT))
        if p.name.endswith('.zh.md') or p.name == 'README.md':
            continue
        out.add(rel_path)
    return out | {p for p in historical_chapters() if not p.endswith('.zh.md')}


def validate(chapters: list[dict], branches: list[dict]) -> tuple[list[str], dict]:
    """(errors, drift): structural errors block rendering; drift maps an entry ID to its source
    path when the source changed after the reading (the review gate; never refreshed here)."""
    errors, drift = [], {}
    generated = set(json.loads(MANIFEST.read_text())['files']) if MANIFEST.exists() else set()
    for label, rows, expected in (
        ('chapters', chapters, expected_chapters(generated)),
        ('branches', branches, {str(p.relative_to(ROOT)) for p in (ROOT / 'theories').glob('*/README.md')})):
        actual = {x['source'] for x in rows}
        if actual != expected:
            errors.append(f'{label} missing={sorted(expected - actual)}, extra={sorted(actual - expected)}')
        if len({x['id'] for x in rows}) != len(rows):
            errors.append(f'Duplicate {label} IDs')
        for d in rows:
            for field in REQUIRED:
                if not isinstance(d.get(field), str) or not d[field].strip():
                    errors.append(f'{d.get("id")}: missing {field}')
            for field in PAIRED:
                if not pick(d, field):
                    errors.append(f'{d.get("id")}: missing {field}_en and {field}_zh')
            for source in [d['source'], *d.get('lean', []), *d.get('evidence', [])]:
                if not (ROOT / source.split('#')[0]).exists():
                    errors.append(f'{d["id"]}: missing path {source}')
            if d['source'] in generated:
                if d.get('source_sha256') != GENERATED_VIEW:
                    errors.append(f'{d["id"]}: generated view; record {GENERATED_VIEW} after rereading its role')
            elif (ROOT / d['source']).is_file():
                digest = hashlib.sha256((ROOT / d['source']).read_bytes()).hexdigest()
                if d.get('source_sha256') != digest:
                    drift[d['id']] = d['source']
    return errors, drift


def outputs(chapters: list[dict], branches: list[dict], drift: dict) -> dict[str, str]:
    """Repository path -> page body."""
    base = str(OUT.relative_to(ROOT))
    return {base + '/README.md': index(chapters, branches, drift),
            base + '/ARGUMENTS-A-L.md': stub('A–L', FROZEN['A-L']),
            base + '/ARGUMENTS-M-Z.md': stub('M–Z', FROZEN['M-Z'])}


def stub(volume: str, frozen: Path) -> str:
    """The page left at a frozen volume's old path, which the curated chain's page links (R35, E2)."""
    target = rel(str(frozen.relative_to(ROOT)))
    return finish([heading('#', f'Arguments {volume} (frozen)'), '', MARKER, '',
                   f'The chapter readings {volume} of 8 October 2026 and later are frozen at [{frozen.name}]({target}), '
                   'unchanged. The readings themselves are kept in the registers in [data/](data/); the live register of '
                   'results is [the register](../../../RESULTS.md), and every chapter with its status is in the '
                   '[chapter index](../chapters/README.md).', ''])


def render() -> tuple[dict[str, str], list[str], dict]:
    """(outputs, errors, drift) for `research.py render`; no outputs when a structural error exists."""
    chapters, branches = load()
    errors, drift = validate(chapters, branches)
    return ({} if errors else outputs(chapters, branches, drift)), errors, drift


def check_page_links(errors: list[str]) -> tuple[int, int]:
    """Relative Markdown file targets and fragments in results/ and the root README."""
    files = [ROOT / 'README.md', *OUT.rglob('*.md')]
    checked_links = checked_fragments = 0
    for p in files:
        text = p.read_text()
        for match in re.finditer(r'(?<!!)\[[^\]\n]*\]\(([^\n]+?)\)', text):
            target = match.group(1).strip().strip('<>')
            if urlsplit(target).scheme:
                continue
            pathname, _, fragment = target.partition('#')
            target = unquote(pathname)
            dest = (p.parent / target).resolve() if target else p.resolve()
            checked_links += 1
            if not dest.exists():
                errors.append(f'{p.relative_to(ROOT)}: broken target {target}')
            elif fragment and dest.suffix.lower() == '.md':
                checked_fragments += 1
                if unquote(fragment) not in anchors(dest):
                    errors.append(f'{p.relative_to(ROOT)}: missing anchor {target}#{fragment}')
            elif fragment and dest.suffix.lower() == '.lean':
                checked_fragments += 1
                m = re.fullmatch(r'L(\d+)(?:-L(\d+))?', fragment)
                if m and int(m.group(2) or m.group(1)) > line_count(dest):
                    errors.append(f'Line beyond source: {target}#{fragment}')
    return checked_links, checked_fragments


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    chapters, branches = load()
    errors, drift = validate(chapters, branches)
    if not errors:
        for name, body in outputs(chapters, branches, drift).items():
            target = ROOT / name
            if args.check:
                if not target.exists() or target.read_text() != body:
                    errors.append(f'Stale generated file: {name}')
            else:
                target.write_text(body)
    checked_links, checked_fragments = check_page_links(errors)
    print(json.dumps({'chapters': len(chapters), 'branches': len(branches), 'local_file_links_checked': checked_links,
                      'fragments_checked': checked_fragments, 'errors': errors,
                      'reading_drift': sorted(drift),
                      'reading_drift_note': 'Sources changed after their readings; reread each entry before refreshing its source_sha256.'},
                     ensure_ascii=False, indent=2))
    return 1 if errors else 2 if drift else 0


if __name__ == '__main__':
    raise SystemExit(main())
