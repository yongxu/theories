"""Render the reading catalogue (English) and check its documentary coverage, not proofs.

From the repository root:
  python3 -B tools/research/reading_catalogue.py           # write the four pages
  python3 -B tools/research/reading_catalogue.py --check   # compare, write nothing
`make research-render` writes the same pages through the guarded renderer.

Argument prose is edited in the three JSON reading registers (results/data/). This
script owns results/README.md and the two stubs ARGUMENTS-A-L.md and ARGUMENTS-M-Z.md. The volumes and the
theory map of 8 October 2026 are frozen in theories/becoming/history/ (R35, E2); the index links them there and the
stubs keep the old paths for the curated chain's page. The pages show
the English of each paired field, or the Chinese where no English exists; the Chinese
stays in the registers.

Review gate: `source_sha256` names the source version an entry was read against. A
changed source is never relabelled as read: its entry is rendered with a visible
"source changed since this reading" note and listed under `reading_drift` (exit 2 for
--check), until someone rereads the entry and refreshes the hash. Views listed in the
generated manifest carry the token `generated-view`: their rows follow the record
checks, so record additions do not stale the reading. A chapter's Chinese edition
(`NAME.zh.md`) is covered by the entry for `NAME.md`.
"""
