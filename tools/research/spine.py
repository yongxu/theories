        (f'<line x1="{x0}" y1="{{y}}" x2="{x0 + 28}" y2="{{y}}" stroke="{MUTED}" stroke-width="1.6" stroke-dasharray="1.5 4" stroke-linecap="round" marker-end="url(#diamond)"/>', words['application']),
