import json
import unittest

from tools.research import registry, theory_graph


class TheoryGraphTest(unittest.TestCase):
    def setUp(self):
        self.records, _ = registry.load_records()
        self.out = theory_graph.render(self.records)
        self.graph = json.loads(self.out[theory_graph.GRAPH])

    def test_every_edge_joins_two_nodes(self):
        ids = {n['id'] for n in self.graph['nodes']}
        for e in self.graph['edges']:
            self.assertIn(e['from'], ids, e)
            self.assertIn(e['to'], ids, e)

    def test_every_record_is_a_node(self):
        ids = {n['id'] for n in self.graph['nodes']}
        for r in self.records:
            self.assertIn('record:' + r['id'], ids)

    def test_regions_are_known(self):
        for n in self.graph['nodes']:
            if 'region' in n:
                self.assertIn(n['region'], theory_graph.REGION_ORDER, n['id'])

    def test_every_result_and_module_is_assigned(self):
        for n in self.graph['nodes']:
            if n['type'] in ('result', 'module'):
                self.assertNotEqual(n['region'], 'unassigned', n['id'])

    def test_a_results_region_is_its_homes_chapter(self):
        chapter = {'01': 'root', '02': 'map', '03': 'knowing', '04': 'life', '05': 'collective', '06': 'classical',
                   '07': 'significance', '08': 'method'}
        homes = {}
        for path, anchor in theory_graph.sections():
            homes.setdefault(anchor, set()).add(chapter.get(path.rsplit('/', 1)[-1][:2]))
        for n in self.graph['nodes']:
            if n['type'] == 'result' and n['record'] in homes:
                self.assertIn(n['region'], homes[n['record']], n['id'])

    def test_every_concept_joins_its_module(self):
        defined = {e['from']: e['to'] for e in self.graph['edges'] if e['type'] == 'defined-in'}
        for n in self.graph['nodes']:
            if n['type'] == 'concept':
                self.assertEqual(defined.get(n['id']), 'module:' + n['module'], n['id'])

    def test_every_read_as_edge_has_an_outcome_and_starts_at_a_text(self):
        for e in self.graph['edges']:
            if e['type'] == 'read-as':
                self.assertTrue(e['from'].startswith('text:'), e)
                self.assertTrue(e.get('outcome'), e)

    def test_only_a_law_outcome_counts_as_read_against_a_law(self):
        seen = {e['outcome'] for e in self.graph['edges'] if e['type'] == 'read-as'}
        self.assertTrue(theory_graph.LAW_OUTCOMES <= seen, seen)
        self.assertIn('not expressible', seen)
        self.assertNotIn('not expressible', theory_graph.LAW_OUTCOMES)
        self.assertNotIn('evaluation', theory_graph.LAW_OUTCOMES)

    def test_the_conditional_laws_counts_stand(self):
        # 06 §四: 219 read, 128 in 22 families, 103 laws, 19 premises, 6 false as read; the other 91 no law.
        rows = [e for e in self.graph['edges'] if e['to'] == 'record:' + theory_graph.CONDITIONALS_RECORD
                and e['type'] == 'read-as']
        self.assertEqual(len(rows), 219)
        self.assertEqual(sum(1 for e in rows if e['outcome'] in ('law', 'premise', 'false as read')), 128)
        self.assertEqual(sum(1 for e in rows if 'family' in e), 128)

    def test_no_edge_is_inferred_for_an_unread_text(self):
        joined = {e['from'] for e in self.graph['edges'] if e['from'].startswith('text:')}
        unread = [n for n in self.graph['nodes'] if n['type'] == 'text' and n['id'] not in joined]
        self.assertIn(f'| Classified, and read against nothing yet | {len(unread)} |', self.out[theory_graph.PAGE])

    def test_every_other_node_has_an_edge(self):
        touched = {x for e in self.graph['edges'] for x in (e['from'], e['to'])}
        apart = [n['id'] for n in self.graph['nodes'] if n['type'] != 'text' and n['id'] not in touched]
        self.assertEqual(apart, [])

    def test_a_section_states_a_record(self):
        states = {e['from'] for e in self.graph['edges'] if e['type'] == 'states'}
        for n in self.graph['nodes']:
            if n['type'] == 'section':
                self.assertIn(n['id'], states)

    def test_page_is_generated(self):
        self.assertTrue(self.out[theory_graph.PAGE].startswith('<!-- Generated by'))


if __name__ == '__main__':
    unittest.main()
