def fill(model: dict, geo: list[dict]) -> str:
    """The template with the counts, the drawing and the data in place; the data last, so that nothing in it is filled."""
    body = (ROOT / TEMPLATE).read_text(encoding='utf-8')
    said = dict(model['counts'], kinds=kinds(model), Kinds=kinds(model).capitalize(), drawn_min=number(DRAWN_MIN))
    for k, v in said.items():
        body = body.replace('{{' + k + '}}', str(v))
    body = (body.replace('/*W*/', str(W)).replace('/*H*/', str(H)).replace('/*HOME*/', SITE)
            .replace('/*PAGE*/', SITE + PAGE[:-3] + '.html').replace('/*LAWS*/', SITE + LAWS_PAGE[:-3] + '.html')
            .replace('/*DYNAMICS*/', SITE + DYNAMICS_PAGE[:-3] + '.html')
            .replace('/*CASES*/', SITE + CASES_PAGE[:-3] + '.html'))
    data = json.dumps(model, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    head, _, tail = body.partition('/*MAP*/')
    middle, _, end = tail.partition('/*DATA*/')
    return head + drawing(model, geo) + middle + data + end


def interactive(model: dict, geo: list[dict]) -> str:
    """One standalone document: no outside font, script or style."""
    style, _, rest = fill(model, geo).partition('</style>\n')
    return ('<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n'
            '<title>The map · The Theory of Becoming</title>\n' + GENERATED + '\n' + style + '</style>\n</head>\n<body>\n' + rest.rstrip('\n')
            + '\n</body>\n</html>\n')


def load(root: Path = ROOT):
    """The data as (web, cards, cases, dynamics by id, ledger by id, the tests' folders by id), or the errors."""
    def read(path):
        return json.loads((root / path).read_text(encoding='utf-8'))
    try:
        web, cards, cases = read(WEB), read(CARDS)['cards'], read(CASES)['cases']
        dyn = {d['id']: d for d in read(DYNAMICS)}
        ledger = {p['id']: p for p in read(PREMISES)}
        folders = {t['id']: t.get('folder') for t in read(TESTS)['tests']}
    except (OSError, ValueError, KeyError, TypeError) as e:
        return None, [f'{MAP}: the map\'s data cannot be read: {e}']
    return (web, cards, cases, dyn, ledger, folders), []


def build(loaded) -> tuple:
    """(the model, its geometry), or the errors that stop a render."""
    web, cards, cases, dyn, ledger, folders = loaded
    errors = validate(web, cards, cases, dyn, set(folders), set(ledger))
    if errors:
        return None, errors
    model = join(web, cards, cases, dyn, ledger)
    try:
        return (model, geometry(model)), []
    except ValueError as e:
        return None, [f'{MAP}: {e}']


def render():
    """The six views and the errors that stop a render; nothing where the map has no data."""
    if not (ROOT / WEB).is_file():
        return {}, []
    loaded, errors = load()
    built, errors = build(loaded) if not errors else (None, errors)
    if errors:
        return {}, errors
    model, geo = built
    document = interactive(model, geo)
    size = len(document.encode('utf-8'))
    if size > MAX_INTERACTIVE:
        return {}, [f'{INTERACTIVE}: {size} bytes, over {MAX_INTERACTIVE}: the site takes a page under 2,000,000 bytes']
    return {PAGE: page(model), LAWS_PAGE: laws_page(model), DYNAMICS_PAGE: dynamics_page(model), CASES_PAGE: cases_page(model, loaded[5]),
            PICTURE: picture(model, geo), INTERACTIVE: document}, []


