def _edge_point(centre, toward, pad=6):
    (cx, cy), (tx, ty) = centre, toward
    dx, dy = tx - cx, ty - cy
    if not dx and not dy:
        return cx, cy
    s = min((NW / 2 + pad) / abs(dx) if dx else 1e9, (NH / 2 + pad) / abs(dy) if dy else 1e9)
    return cx + dx * s, cy + dy * s


def _rot(v, degrees):
    r = math.radians(degrees)
    return v[0] * math.cos(r) - v[1] * math.sin(r), v[0] * math.sin(r) + v[1] * math.cos(r)


def geometry(model: dict) -> list[dict]:
    """Each drawn tie's path, where its label sits and how heavy its line is, the most-used first."""
    edges = model['edges']
    missing = sorted({r['id'] for r in model['roles'] if r['id'] != 'any'} - set(POS))
    if missing:
        raise ValueError('the map has no place for the role ' + ', '.join(missing) + ': set it in the_map.POS')
    pairs, loops, out = defaultdict(list), defaultdict(list), {}
    for k, e in edges.items():
        if e['drawn']:
            (loops[e['from']] if e['from'] == e['to'] else pairs[tuple(sorted((e['from'], e['to'])))]).append(k)
    weight = lambda e: 1.2 + min(3.4, math.sqrt(len(e['dyn'])) * .42)
    for (a, b), ks in sorted(pairs.items()):
        ks.sort(key=lambda k: (-len(edges[k]['dyn']), k))
        for i, k in enumerate(ks):
            e = edges[k]
            (x1, y1), (x2, y2) = POS[e['from']], POS[e['to']]
            n = math.hypot(x2 - x1, y2 - y1)
            off = (i - (len(ks) - 1) / 2) * (150 if len(ks) == 2 else 92) * (1 if (e['from'], e['to']) == (a, b) else -1)
            cx, cy = (x1 + x2) / 2 - (y2 - y1) / n * off, (y1 + y2) / 2 + (x2 - x1) / n * off
            s, t = _edge_point((x1, y1), (cx, cy)), _edge_point((x2, y2), (cx, cy))
            out[k] = {'d': f'M{s[0]:.1f},{s[1]:.1f} Q{cx:.1f},{cy:.1f} {t[0]:.1f},{t[1]:.1f}',
                      'x': (s[0] + 2 * cx + t[0]) / 4, 'y': (s[1] + 2 * cy + t[1]) / 4, 'w': weight(e)}
    for node, ks in sorted(loops.items()):
        ks.sort(key=lambda k: (-len(edges[k]['dyn']), k))
        x, y = POS[node]
        ways = LOOP.get(node, [(0, -1)])
        for i, k in enumerate(ks):
            v = ways[i] if i < len(ways) else _rot(ways[-1], 64 * (i - len(ways) + 1))
            n = math.hypot(*v)
            v = (v[0] / n, v[1] / n)
            a, b = _rot(v, -20), _rot(v, 20)
            p1, p2 = _edge_point((x, y), (x + a[0] * 100, y + a[1] * 100)), _edge_point((x, y), (x + b[0] * 100, y + b[1] * 100))
            a, b = _rot(v, -34), _rot(v, 34)
            out[k] = {'d': f'M{p1[0]:.1f},{p1[1]:.1f} C{p1[0] + a[0] * 92:.1f},{p1[1] + a[1] * 92:.1f} '
                           f'{p2[0] + b[0] * 92:.1f},{p2[1] + b[1] * 92:.1f} {p2[0]:.1f},{p2[1]:.1f}',
                      'x': (p1[0] + p2[0]) / 2 + v[0] * 78, 'y': (p1[1] + p2[1]) / 2 + v[1] * 78, 'w': weight(edges[k])}
    return [{'k': k, **out[k]} for k in sorted(out, key=lambda k: (-len(edges[k]['dyn']), k))]


