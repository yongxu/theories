"""The theory graph (board item RA): one machine-readable graph of the theory and its readable index.

Nodes:
- concepts of the grammar, read from the binding tables in the grammar modules' headers;
- results (the records);
- Lean modules of the core package;
- texts: classified corpus units of the classes that state something (定义, 文法之定理, 有条件之律, 相分, 反读);
- sections of the live chapters that state a result, marked by an anchor `<a id="r-<record id>"></a>`;
- the review dossiers, which cite corpus units.

Edges:
- concept → module (defined in);
- record → record (the record's dependencies by relation, and related);
- record → module (proved in);
- module → module (imports);
- text → record (read as: the record that registers the reading, with the reading's `outcome`, and its `family` for a
  conditional law; an outcome can be that no law was read, such as not expressible);
- text → concept (names: a concept's binding row cites the unit);
- text → module, record, section or dossier (cited in: that source cites the unit by its id);
- section → record (states).

A text with no edge has been classified and read against nothing yet. Edges are never inferred from shared words, so
most of the corpus has none, and the page says how many.

Regions and bases come from `theories/becoming/results/data/regions.json`, curated by RA.
`make research-render` writes `theories/becoming/results/data/theory-graph.json` and
`theories/becoming/results/THEORY-GRAPH.md`; do not edit them."""
import csv
import json
import os
import re
from pathlib import Path

from tools.research import registry

ROOT = registry.ROOT
PKG = 'experiments/integrated-correction/general-framework/generative-basis/lean/becoming'
DATA = 'theories/becoming/results/data'
REGIONS = f'{DATA}/regions.json'
GRAPH = f'{DATA}/theory-graph.json'
PAGE = 'theories/becoming/results/THEORY-GRAPH.md'
CHAPTERS = 'theories/becoming/chapters'
CLASSIFY = '_process/research/2026-10-05-generative-foundation-review/root-foundation/development/one-unfolding-root/classify'
CORPUS = '_process/research/2026-10-05-generative-foundation-review/root-foundation/development/one-unfolding-root/corpus'
OUTCOMES = '_process/research/2026-10-05-generative-foundation-review/root-foundation/development/ou2-candidates/outcomes.tsv'
CONDITIONALS = '_process/research/2026-10-05-generative-foundation-review/root-foundation/development/ou7-conditional-laws/data/groups.tsv'
CANDIDATES_RECORD = 'candidate-theorems-of-the-corpus'
CONDITIONALS_RECORD = 'conditional-laws-of-the-corpus'
DOSSIERS = 'theories/becoming/review'
# An outcome where a law was read, against one where the unit was read and no law came of it.
LAW_OUTCOMES = {'proved', 'conditional', 'refuted', 'law', 'premise', 'false as read'}
DISPOSITIONS = {'law': 'law', 'premise': 'premise', 'false': 'false as read', 'NE': 'not expressible',
                '丁': 'evaluation', '甲': 'definition'}
GRAMMAR_MODULES = ['Grammar', 'GrammarReadings', 'GrammarMap', 'GrammarTesting', 'GrammarCandidates']
TEXT_CLASSES = {'甲': 'definition', '乙': 'grammar-theorem', '丙一': 'conditional-law', '戊': 'split', '己': 'counter-reading'}
WORKS = {'xici': '系辞', 'laozi': '老子', 'mojing': '墨经', 'xunzi-zhengming': '荀子·正名', 'zhuangzi-yangshengzhu': '庄子·养生主',
         'qixinlun': '大乘起信论', 'jinshizizhang': '金师子章', 'zhonglun': '中论', 'zhonglun-2': '中论',
         'chengweishi': '成唯识论', 'wujiaozhang-liuxiang': '华严五教章'}
REGION_ORDER = ['root', 'map', 'knowing', 'life', 'collective', 'classical', 'significance', 'method', 'process', 'retire',
                'unassigned']
REGION_TITLES = {
    'root': 'The root: relation, condition, class, continuation, core',
    'map': 'The map: generation, keeping, degeneration, orders',
    'knowing': 'Knowing and testing',
    'life': 'Life and evolution',
    'collective': 'Collectives and selection',
    'classical': 'The classical texts',
    'significance': 'Significance and alignment',
    'method': 'Method and the formal core',
    'process': 'Process',
    'retire': 'To retire',
    'unassigned': 'Not yet assigned',
}
HEADER = ('<!-- Generated by tools/research/research.py render (tools/research/theory_graph.py). Edit records, Lean '
          'module headers, the corpus classification and theories/becoming/results/data/regions.json, not this view. -->')


def _read(path):
    p = ROOT / path
    return p.read_text(encoding='utf-8') if p.is_file() else None


def regions():
    text = _read(REGIONS)
    data = json.loads(text) if text else {}
    return data.get('records', {}), data.get('modules', {})


def concepts():
    """Rows `| `«X»`, `«Y»` | gloss |` of the grammar modules' header tables."""
    out = []
    for mod in GRAMMAR_MODULES:
        text = _read(f'{PKG}/Becoming/{mod}.lean')
        if not text:
            continue
        header = text.split('-/', 1)[0]
        for line in header.split('\n'):
            m = re.match(r'^\| (`«[^|]+»`[^|]*?) \| ([^|]+)\|', line)
            if not m:
                continue
            names = re.findall(r'`(«[^»]+»)`', m.group(1))
            gloss = m.group(2).strip()
            for n in names:
                out.append({'id': 'concept:' + n.strip('«»'), 'type': 'concept', 'name': n, 'gloss': gloss,
                            'module': 'Becoming.' + mod, 'region': 'map' if mod == 'GrammarMap' else
                            'knowing' if mod == 'GrammarTesting' else 'classical' if mod != 'Grammar' else 'root'})
    seen, unique = set(), []
    for c in out:
        if c['id'] not in seen:
            seen.add(c['id'])
            unique.append(c)
    return unique


def modules(region_of):
    root = _read(f'{PKG}/Becoming.lean') or ''
    names = re.findall(r'^import (Becoming\.\S+)', root, re.M)
    # A root bullet's note opens with its layer ("L2, through `Becoming.X`"); the level is that layer alone.
    level = dict(re.findall(r'^\* `(Becoming\.[^`]+)` \((L\d)\b[^)]*\)', root, re.M))
    nodes, imports, sources = {}, {}, {}
    for n in names:
        text = _read(f'{PKG}/Becoming/{n.split(".", 1)[1].replace(".", "/")}.lean') or ''
        imports[n] = [m for m in re.findall(r'^import (\S+)', text, re.M) if m.startswith('Becoming.')]
        sources[n] = text
        info = region_of.get(n, {})
        nodes[n] = {'id': 'module:' + n, 'type': 'module', 'name': n, 'level': level.get(n, ''),
                    'theorems': len(re.findall(r'^theorem ', text, re.M)), 'region': info.get('region', 'unassigned'),
                    'base': info.get('base', '')}
    grammar = {f'Becoming.{m}' for m in GRAMMAR_MODULES}
    memo = {}

    def on_grammar(n, stack=()):
        if n in memo:
            return memo[n]
        if n in grammar:
            memo[n] = True
            return True
        if n in stack:
            return False
        memo[n] = any(on_grammar(m, stack + (n,)) for m in imports.get(n, []))
        return memo[n]

    for n in nodes:
        # Stated on the grammar: a grammar module, one importing a grammar module, or one whose source uses the
        # grammar's names (written «…»), typically in an instance section; reaches it: through what it imports.
        nodes[n]['on_grammar'] = n in grammar or any(m in grammar for m in imports.get(n, [])) or '«' in sources[n]
        nodes[n]['reaches_grammar'] = on_grammar(n)
    return nodes, imports, sources


def texts():
    rows = []
    for f in sorted((ROOT / CLASSIFY).glob('*.tsv')) if (ROOT / CLASSIFY).is_dir() else []:
        work = f.stem
        with open(f, encoding='utf-8') as fh:
            for r in csv.DictReader(fh, delimiter='\t'):
                cls = r.get('class', '')
                if cls in TEXT_CLASSES:
                    rows.append({'id': 'text:' + r['id'], 'type': 'text', 'unit': r['id'], 'work': WORKS.get(work, work),
                                 'class': cls, 'role': TEXT_CLASSES[cls], 'form': (r.get('form') or '')[:120],
                                 'region': 'classical'})
    return rows


def classified_total():
    """Every classified unit of the corpus, stating something or not."""
    total = 0
    for f in sorted((ROOT / CLASSIFY).glob('*.tsv')) if (ROOT / CLASSIFY).is_dir() else []:
        with open(f, encoding='utf-8') as fh:
            total += sum(1 for _ in csv.DictReader(fh, delimiter='\t'))
    return total


def outcomes():
    """Unit id → (outcome, declarations named) of the candidates read as root statements."""
    text = _read(OUTCOMES)
    out = {}
    if text:
        for r in csv.DictReader(text.splitlines(), delimiter='\t'):
            out[r['id']] = (r.get('outcome', '').replace('-', ' '),
                            ['Becoming.' + d for d in re.findall(r'«[^»]+»', r.get('declaration', ''))])
    return out


def conditionals():
    """Unit id → (outcome, family) of the sentences read as conditional laws; a family is None where the unit has none."""
    text = _read(CONDITIONALS)
    out = {}
    if text:
        for r in csv.DictReader(text.splitlines(), delimiter='\t'):
            disposition = r.get('disposition', '')
            family = r.get('group', '')
            out[r['id']] = (DISPOSITIONS.get(disposition, disposition), family if family.startswith('G') else None)
    return out


def unit_pattern(units):
    """Matches a unit's id as the repository writes it, by the prefixes the corpus uses."""
    prefixes = sorted({u.split('-', 1)[0] for u in units})
    return re.compile(r'(?<![\w-])(?:' + '|'.join(map(re.escape, prefixes)) + r')-[A-Za-z0-9+.\-]*[0-9](?![\w-])') if prefixes else None


def cited(pattern, text, units):
    """The corpus units `text` cites by id."""
    return {m for m in pattern.findall(text) if m in units} if pattern and text else set()


def sections():
    out = []
    for f in sorted((ROOT / CHAPTERS).glob('*.md')):
        rel = str(f.relative_to(ROOT))
        text = f.read_text(encoding='utf-8')
        for m in re.finditer(r'<a id="r-([a-z0-9-]+)"></a>', text):
            out.append((rel, m.group(1)))
    return out


def build(records):
    record_region, module_region = regions()
    nodes, edges = [], []
    ids = {r['id'] for r in records}
    alias = {}
    for r in records:
        for a in r.get('aliases', []):
            alias.setdefault(a, r['id'])
    mods, imports, module_sources = modules(module_region)
    path_to_module = {f'{PKG}/Becoming/{n.split(".", 1)[1].replace(".", "/")}.lean': n for n in mods}
    grammar_concepts = concepts()
    for c in grammar_concepts:
        nodes.append(c)
        if c['module'] in mods:
            edges.append({'from': c['id'], 'to': 'module:' + c['module'], 'type': 'defined-in'})
    for r in records:
        info = record_region.get(r['id'], {})
        t = r.get('title', {})
        nodes.append({'id': 'record:' + r['id'], 'type': 'result', 'record': r['id'],
                      'title': t.get('en', '') if isinstance(t, dict) else str(t),
                      'title_zh': t.get('zh', '') if isinstance(t, dict) else '',
                      'status': r.get('status', ''), 'kind': r.get('kind', ''),
                      'region': info.get('region', 'unassigned'), 'base': info.get('base', ''),
                      'page': str(registry.record_path(r).with_suffix('.md').relative_to(ROOT))})
        for d in r.get('dependencies', []):
            if d.get('id') in ids:
                edges.append({'from': 'record:' + r['id'], 'to': 'record:' + d['id'], 'type': d.get('relation', 'depends'),
                              **({'interface': True} if 'interface' in d else {})})
        for d in r.get('related', []):
            if d.get('id') in ids:
                edges.append({'from': 'record:' + r['id'], 'to': 'record:' + d['id'], 'type': 'related'})
        for ref in r.get('references', []):
            m = path_to_module.get(ref.get('path', ''))
            if m and ref.get('role') == 'proof':
                edges.append({'from': 'record:' + r['id'], 'to': 'module:' + m, 'type': 'proved-in'})
    for n, node in mods.items():
        nodes.append(node)
        for m in imports.get(n, []):
            if m in mods:
                edges.append({'from': 'module:' + n, 'to': 'module:' + m, 'type': 'imports'})
    out, cond = outcomes(), conditionals()
    corpus = texts()
    units = {t['unit'] for t in corpus}
    pattern = unit_pattern(units)
    for t in corpus:
        nodes.append(t)
        if t['unit'] in out:
            outcome, decls = out[t['unit']]
            target = next((alias[d] for d in decls if d in alias), CANDIDATES_RECORD)
            if target in ids:
                edges.append({'from': t['id'], 'to': 'record:' + target, 'type': 'read-as', 'outcome': outcome})
        if t['unit'] in cond and CONDITIONALS_RECORD in ids:
            outcome, family = cond[t['unit']]
            edge = {'from': t['id'], 'to': 'record:' + CONDITIONALS_RECORD, 'type': 'read-as', 'outcome': outcome}
            if family:
                edge['family'] = family
            edges.append(edge)
    for c in grammar_concepts:
        for u in cited(pattern, c['gloss'], units):
            edges.append({'from': 'text:' + u, 'to': c['id'], 'type': 'names'})
    for n, source in module_sources.items():
        for u in cited(pattern, source, units):
            edges.append({'from': 'text:' + u, 'to': 'module:' + n, 'type': 'cited-in'})
    for r in records:
        for u in cited(pattern, json.dumps(r, ensure_ascii=False), units):
            edges.append({'from': 'text:' + u, 'to': 'record:' + r['id'], 'type': 'cited-in'})
    for f in sorted((ROOT / DOSSIERS).glob('*.md')) if (ROOT / DOSSIERS).is_dir() else []:
        found = cited(pattern, f.read_text(encoding='utf-8'), units)
        if found:
            did = 'dossier:' + f.stem
            nodes.append({'id': did, 'type': 'dossier', 'name': f.stem, 'page': str(f.relative_to(ROOT))})
            for u in found:
                edges.append({'from': 'text:' + u, 'to': did, 'type': 'cited-in'})
    for f in sorted((ROOT / CHAPTERS).glob('*.md')):
        # A chapter's citation goes to the result section it falls under; one before any such section joins nothing.
        rel, text = str(f.relative_to(ROOT)), f.read_text(encoding='utf-8')
        marks = [(m.start(), m.group(1)) for m in re.finditer(r'<a id="r-([a-z0-9-]+)"></a>', text)]
        for m in pattern.finditer(text) if pattern else ():
            under = [rid for start, rid in marks if start < m.start() and rid in ids]
            if m.group(0) in units and under:
                edges.append({'from': 'text:' + m.group(0), 'to': f'section:{rel}#r-{under[-1]}', 'type': 'cited-in'})
    for path, rid in sections():
        # An anchor naming no record is an old name kept for links, not a section stating a result.
        if rid in ids:
            sid = f'section:{path}#r-{rid}'
            nodes.append({'id': sid, 'type': 'section', 'chapter': path, 'anchor': 'r-' + rid})
            edges.append({'from': sid, 'to': 'record:' + rid, 'type': 'states'})
    seen, unique = set(), []
    for e in edges:
        k = (e['from'], e['to'], e['type'])
        if k not in seen:
            seen.add(k)
            unique.append(e)
    edges = sorted(unique, key=lambda e: (e['from'], e['to'], e['type']))
    return {'schema_version': 1,
            'about': 'The theory graph: concepts of the grammar, results, Lean modules, corpus texts, chapter '
                     'sections and review dossiers, with their edges. Generated by tools/research/theory_graph.py; '
                     'regions curated in ' + REGIONS + '.',
            'classified_total': classified_total(),
            'regions': {k: REGION_TITLES[k] for k in REGION_ORDER},
            'nodes': nodes, 'edges': edges}


def corpus_counts(graph):
    """How far the corpus has been read, from the edges: the units in each class of reading."""
    outcomes_of, others = {}, set()
    for e in graph['edges']:
        if e['from'].startswith('text:'):
            if e['type'] == 'read-as':
                outcomes_of.setdefault(e['from'], set()).add(e.get('outcome', ''))
            else:
                others.add(e['from'])
    corpus = [n for n in graph['nodes'] if n['type'] == 'text']
    law = sum(1 for t in corpus if outcomes_of.get(t['id'], set()) & LAW_OUTCOMES)
    no_law = sum(1 for t in corpus if t['id'] in outcomes_of and not outcomes_of[t['id']] & LAW_OUTCOMES)
    cited = sum(1 for t in corpus if t['id'] in others and t['id'] not in outcomes_of)
    return {'classified': graph.get('classified_total', len(corpus)), 'stating': len(corpus), 'law': law, 'no_law': no_law,
            'cited': cited, 'only': len(corpus) - law - no_law - cited}


def corpus_section(graph):
    """How far the corpus has been read, and what in the graph has no edge."""
    c = corpus_counts(graph)
    touched = {end for e in graph['edges'] for end in (e['from'], e['to'])}
    apart = sorted(n['id'] for n in graph['nodes'] if n['id'] not in touched and n['type'] != 'text')
    lines = ['', '## How far the corpus has been read', '',
             f'{c["classified"]} corpus units are classified, {c["stating"]} of them in the '
             'classes that state something, which are the texts here. Of those:', '',
             '| Reading so far | Units |', '|---|---:|',
             f'| Read against a law: a candidate theorem or a conditional law, whatever its outcome | {c["law"]} |',
             f'| Read, and no law came of it: not expressible, an evaluation, a definition, misclassified | {c["no_law"]} |',
             f'| Named by a grammar concept or cited by a module, record, section or dossier, and not read as above | {c["cited"]} |',
             f'| Classified, and read against nothing yet | {c["only"]} |', '',
             'The last row has no edge in this graph. Its units are not shown to agree or disagree with anything.']
    if apart:
        lines += ['', 'Other nodes with no edge: ' + ', '.join(f'`{a}`' for a in apart) + '.']
    return lines


def page(graph):
    by = {}
    for n in graph['nodes']:
        by.setdefault(n['type'], []).append(n)
    counts = {k: {'result': 0, 'module': 0, 'text': 0, 'section': 0, 'concept': 0} for k in REGION_ORDER}
    for n in graph['nodes']:
        reg = n.get('region', 'unassigned')
        if n['type'] in ('result', 'module', 'text', 'concept') and reg in counts:
            counts[reg][n['type']] += 1
    states = {e['to'] for e in graph['edges'] if e['type'] == 'states'}
    retired_superseded = all(n.get('status') == 'superseded' for n in graph['nodes'] if n['type'] == 'result' and n.get('region') == 'retire')
    from tools.research import navigation, spine  # the picture's sections read this module's regions, so imported here
    lines = [HEADER, '', '# The theory graph', '', ' · '.join(navigation.link(p, PAGE, label) for p, label in navigation.NAV),
             '', '{time}', '',
             'One graph of the theory: the grammar\'s concepts, the results, the Lean modules, the corpus texts, the '
             'chapter sections that state results and the review dossiers, with the edges between them '
             f'([data](data/theory-graph.json); regions curated in [regions.json](data/regions.json)). '
             f'{len(graph["nodes"])} nodes, {len(graph["edges"])} edges. An edge records a dependence, a citation or a '
             'registered reading, not an agreement in meaning.', '',
             ]
    lead = spine.lead(graph, PAGE)
    lines += lead
    lines += ['', '## The regions', '',
              'A region\'s results are the records whose home section is in its chapter, so the counts below are those the '
              '[chapters page](../chapters/README.md) gives as results stated. A chapter also keeps the anchors of former record '
              'names, so that old links resolve; those are not results, and neither page counts them. In the lists below, ◆ marks a '
              'result the [coverage file](completion/COVERAGE.json) names as central.'
              + (f' To retire holds the {counts["retire"]["result"]} superseded records that no chapter states, which the '
                 'chapters page does not list.' if counts.get('retire', {}).get('result') and retired_superseded else ''), '',
              '| Region | Concepts | Results | Modules | Texts |', '|---|---:|---:|---:|---:|']
    for k in REGION_ORDER:
        c = counts[k]
        if sum(c.values()):
            lines.append(f'| {REGION_TITLES[k]} | {c["concept"]} | {c["result"]} | {c["module"]} | {c["text"]} |')
    section = spine.section(graph, PAGE)
    lines += section
    lines += corpus_section(graph)
    lines += ['', '## The grammar\'s concepts', '', '| Name | Gloss | Module |', '|---|---|---|']
    rows = {}
    for c in by.get('concept', []):  # one row of a header table may bind several names to one gloss
        rows.setdefault((c['gloss'], c['module']), []).append(c['name'])
    for (gloss, module), names in rows.items():
        lines.append(f'| {", ".join(f"`{n}`" for n in names)} | {gloss.replace("|", "/")} | `{module}` |')
    results = by.get('result', [])
    coverage = Path(registry.ROOT / 'theories/becoming/results/completion/COVERAGE.json')
    central = {x for row in json.loads(coverage.read_text(encoding='utf-8')).get('rows', []) for x in row.get('records', [])} if coverage.is_file() else set()
    for k in REGION_ORDER:
        rs = [r for r in results if r['region'] == k]
        ms = [m for m in by.get('module', []) if m['region'] == k]
        if not rs and not ms:
            continue
        lines += ['', f'## {REGION_TITLES[k]}', '']
        if rs:
            lines += [f'Results ({len(rs)}):', '']
            for r in sorted(rs, key=lambda r: r['title']):
                rel = os.path.relpath(r['page'], Path(PAGE).parent)
                mark = '' if 'record:' + r['record'] in states else ' ·'
                central_mark = ' ◆' if r['record'] in central else ''
                lines.append(f'- [{r["title"] or r["record"]}]({rel}) ({r["status"]}){central_mark}{mark}')
            lines.append('')
        if ms:
            on = [m for m in ms if m['on_grammar']]
            lines += [f'Modules ({len(ms)}, {len(on)} stated on the grammar): '
                      + ', '.join(f'`{m["name"].split(".", 1)[1]}`' for m in sorted(ms, key=lambda m: m['name'])), '']
    off = [m for m in by.get('module', []) if not m['on_grammar']]
    lines += ['', '## Not yet on the root', '',
              f'{len(off)} of {len(by.get("module", []))} core modules do not yet state their laws on the grammar (they '
              'neither are a grammar module nor import one); lifting them, as the continuation family was lifted, is '
              'the restructure\'s remaining formal work. A result marked · is not yet stated by a section of a live '
              'chapter.', '']
    text = '\n'.join(lines).rstrip() + '\n'
    full = navigation.reading_time(text.replace('{time}', '', 1))
    part = navigation.reading_time('\n'.join(lead + section))
    return text.replace('{time}', f'[中文（各章一览）](THEORY-GRAPH.zh.md) · {full} to read in full; the chapters at a glance, with their tables, in '
                                  f'{part}.', 1)


def render(records):
    graph = build(records)
    return {GRAPH: json.dumps(graph, ensure_ascii=False, indent=1) + '\n', PAGE: page(graph)}
